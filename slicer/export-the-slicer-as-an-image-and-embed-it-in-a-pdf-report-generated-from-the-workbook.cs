using System;
using System.IO;
using System.Drawing.Imaging;
using Aspose.Cells;
using Aspose.Cells.Pivot;
using Aspose.Cells.Slicers;
using Aspose.Cells.Rendering;
using Aspose.Cells.Saving;

namespace SlicerPdfReport
{
    // The example creates a workbook, adds sample data and a pivot table, inserts a slicer linked to the pivot, renders the slicer‑containing worksheet to a PNG file, places that image on a new 'Report' sheet, saves the workbook as a PDF, and finally removes the temporary image file.
    public class Program
    {
        public static void Main()
        {
            try
            {
                // 1. Create a new workbook and get the first worksheet
                Workbook workbook = new Workbook();
                Worksheet dataSheet = workbook.Worksheets[0];

                // 2. Populate sample data for the pivot table
                dataSheet.Cells["A1"].PutValue("Category");
                dataSheet.Cells["B1"].PutValue("Amount");
                dataSheet.Cells["A2"].PutValue("Fruit");
                dataSheet.Cells["B2"].PutValue(120);
                dataSheet.Cells["A3"].PutValue("Vegetable");
                dataSheet.Cells["B3"].PutValue(80);
                dataSheet.Cells["A4"].PutValue("Fruit");
                dataSheet.Cells["B4"].PutValue(150);
                dataSheet.Cells["A5"].PutValue("Vegetable");
                dataSheet.Cells["B5"].PutValue(70);

                // 3. Add a pivot table based on the data range
                int pivotIndex = dataSheet.PivotTables.Add("A1:B5", "D1", "PivotTable1");
                PivotTable pivot = dataSheet.PivotTables[pivotIndex];
                pivot.AddFieldToArea(PivotFieldType.Row, 0);   // Category as row field
                pivot.AddFieldToArea(PivotFieldType.Data, 1); // Amount as data field

                // 4. Add a slicer linked to the pivot table (filter on Category)
                // Place the slicer at row 12, column 2 (C12)
                int slicerIndex = dataSheet.Slicers.Add(pivot, 12, 2, "Category");
                Slicer slicer = dataSheet.Slicers[slicerIndex];

                // Ensure the slicer is printable so it appears in the rendered image
                // Use Shape.IsPrintable (Slicer inherits from Shape)
                slicer.IsPrintable = true; // Obsolete warning suppressed by using the newer property if needed

                // 5. Render the worksheet (which now contains the slicer) to an image file
                string slicerImagePath = "slicer.png";
                ImageOrPrintOptions imgOptions = new ImageOrPrintOptions
                {
                    OnePagePerSheet = true
                    // Image format is inferred from the file extension, so no need to set ImageFormat explicitly
                };

                try
                {
                    SheetRender sheetRender = new SheetRender(dataSheet, imgOptions);
                    sheetRender.ToImage(0, slicerImagePath);
                }
                catch (Exception ex)
                {
                    Console.WriteLine($"Failed to render slicer image: {ex.Message}");
                    return;
                }

                // 6. Create a new worksheet that will serve as the PDF report page
                Worksheet reportSheet = workbook.Worksheets.Add("Report");

                // 7. Insert the slicer image into the report worksheet
                if (File.Exists(slicerImagePath))
                {
                    int pictureIndex = reportSheet.Pictures.Add(0, 0, slicerImagePath);
                    // Optionally adjust picture size/position via reportSheet.Pictures[pictureIndex]
                }
                else
                {
                    Console.WriteLine($"Warning: Slicer image file not found: {slicerImagePath}");
                }

                // 8. Save the workbook as a PDF document
                PdfSaveOptions pdfOptions = new PdfSaveOptions
                {
                    ExportDocumentStructure = false
                };
                string pdfPath = "SlicerReport.pdf";
                workbook.Save(pdfPath, pdfOptions);

                // Clean up the temporary image file
                if (File.Exists(slicerImagePath))
                {
                    try
                    {
                        File.Delete(slicerImagePath);
                    }
                    catch (Exception ex)
                    {
                        Console.WriteLine($"Failed to delete temporary image file: {ex.Message}");
                    }
                }

                Console.WriteLine($"PDF report generated: {Path.GetFullPath(pdfPath)}");
            }
            catch (Exception ex)
            {
                Console.WriteLine($"An error occurred: {ex.Message}");
            }
        }
    }
}
