using System;
using System.IO;
using Aspose.Cells;

// The sample loads an Excel workbook, checks for a VBA project, and attempts to protect it with workbook.VbaProject.Protect using an empty password. The protection call is wrapped in a try‑catch block to capture and report the exception generated by the empty password, followed by error‑handled saving of the workbook.
class Program
{
    static void Main()
    {
        const string inputPath = "input.xlsx";
        const string outputPath = "output.xlsx";

        // Verify that the input file exists before attempting to load it
        if (!File.Exists(inputPath))
        {
            Console.WriteLine($"Input file '{inputPath}' not found.");
            return;
        }

        Workbook workbook = null;
        try
        {
            // Load the existing workbook (lifecycle rule: load)
            workbook = new Workbook(inputPath);
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error loading workbook: {ex.Message}");
            return;
        }

        // Check if the workbook contains a VBA project
        if (workbook?.VbaProject != null)
        {
            // Example password (empty to trigger the error handling)
            string password = "";

            try
            {
                // Protect the VBA project (requires a bool flag and a password)
                // The first argument indicates whether the project is read‑only; false allows editing after unprotecting.
                workbook.VbaProject.Protect(false, password);
                Console.WriteLine("VBA project protected successfully.");
            }
            catch (Exception ex)
            {
                // Capture and report any exception, e.g., when password is empty
                Console.WriteLine($"Error protecting VBA project: {ex.Message}");
            }
        }
        else
        {
            Console.WriteLine("The workbook does not contain a VBA project.");
        }

        try
        {
            // Save the workbook (lifecycle rule: save)
            workbook.Save(outputPath);
            Console.WriteLine($"Workbook saved to '{outputPath}'.");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error saving workbook: {ex.Message}");
        }
    }
}
