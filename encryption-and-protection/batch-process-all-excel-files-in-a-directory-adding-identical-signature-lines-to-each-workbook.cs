using System;
using System.IO;
using Aspose.Cells;
using System.Drawing;

// The example enumerates all .xls, .xlsx, and .xlsm files in a specified folder, loads each workbook with Aspose.Cells, determines the row after the last used row on the first worksheet, inserts a predefined confidential signature text, applies italic gray formatting, merges the signature across several columns, and saves the signed workbook to a designated output directory.
class Program
{
    static void Main()
    {
        // Directory containing the Excel files to process
        string inputDirectory = @"C:\ExcelFiles";

        // Directory where signed workbooks will be saved (can be the same as inputDirectory to overwrite)
        string outputDirectory = @"C:\ExcelFiles\Signed";
        Directory.CreateDirectory(outputDirectory);

        // The signature line that will be added to each workbook
        const string signatureText = "Confidential - Generated by System";

        // Retrieve all Excel files (xls, xlsx, xlsm) in the input directory
        string[] excelFiles = Directory.GetFiles(inputDirectory, "*.*", SearchOption.TopDirectoryOnly);
        foreach (string filePath in excelFiles)
        {
            string extension = Path.GetExtension(filePath).ToLowerInvariant();
            if (extension != ".xls" && extension != ".xlsx" && extension != ".xlsm")
                continue; // Skip non‑Excel files

            // Load the workbook using Aspose.Cells
            Workbook workbook = new Workbook(filePath);

            // Use the first worksheet (or create one if none exist)
            Worksheet sheet = workbook.Worksheets.Count > 0 ? workbook.Worksheets[0] : workbook.Worksheets[workbook.Worksheets.Add()];

            // Determine the row after the last used row to place the signature
            int lastUsedRow = sheet.Cells.MaxDataRow;
            int signatureRow = lastUsedRow + 2; // leave one empty row before the signature

            // Insert the signature text into the first cell of the signature row
            Cell signatureCell = sheet.Cells[signatureRow, 0];
            signatureCell.PutValue(signatureText);

            // Apply a simple style (italic, gray font)
            Style sigStyle = signatureCell.GetStyle();
            sigStyle.Font.IsItalic = true;
            sigStyle.Font.Color = Color.Gray;
            signatureCell.SetStyle(sigStyle);

            // Optionally merge the signature across the used columns for better appearance
            int usedColumns = Math.Max(sheet.Cells.MaxDataColumn + 1, 5); // ensure at least 5 columns
            sheet.Cells.Merge(signatureRow, 0, 1, usedColumns);

            // Save the modified workbook to the output directory (overwrites if same name)
            string outputPath = Path.Combine(outputDirectory, Path.GetFileName(filePath));
            workbook.Save(outputPath);
        }

        Console.WriteLine("All Excel files have been processed and signed.");
    }
}
