using System;
using System.IO;
using Aspose.Cells;
using System.Drawing;

// The example enumerates all .xls, .xlsx, .xlsm, and .xlsb files in a specified input folder, loads each workbook with Aspose.Cells, inserts a new row after the last used row on the first worksheet, writes a confidential signature text into the first column, applies bold red formatting, and saves the modified workbook to a separate output directory.
class Program
{
    static void Main(string[] args)
    {
        // Directory that contains the Excel files to process
        string inputDirectory = @"C:\ExcelFiles";

        // Directory where the signed workbooks will be saved (can be the same as inputDirectory)
        string outputDirectory = @"C:\ExcelFiles\Signed";

        // Ensure the output directory exists
        Directory.CreateDirectory(outputDirectory);

        // Retrieve all files with Excel extensions in the input directory
        string[] files = Directory.GetFiles(inputDirectory, "*.*", SearchOption.TopDirectoryOnly);
        foreach (string filePath in files)
        {
            // Filter only supported Excel file types
            string ext = Path.GetExtension(filePath).ToLowerInvariant();
            if (ext != ".xls" && ext != ".xlsx" && ext != ".xlsm" && ext != ".xlsb")
                continue; // skip non‑Excel files

            // Load the workbook
            Workbook workbook = new Workbook(filePath);

            // Use the first worksheet (you can change this to a specific sheet if needed)
            Worksheet sheet = workbook.Worksheets[0];

            // Determine the last used row in the sheet
            int lastRow = sheet.Cells.MaxDataRow;

            // Insert a new row after the last used row to hold the signature
            sheet.Cells.InsertRows(lastRow + 1, 1);

            // Write the signature text into the first column of the new row
            const string signatureText = "Confidential - Generated by Company";
            sheet.Cells[lastRow + 1, 0].PutValue(signatureText);

            // Apply simple formatting to the signature (bold and red)
            Style signatureStyle = workbook.CreateStyle();
            signatureStyle.Font.IsBold = true;
            signatureStyle.Font.Color = Color.Red;
            sheet.Cells[lastRow + 1, 0].SetStyle(signatureStyle);

            // Save the modified workbook to the output directory (overwrites if same name exists)
            string fileName = Path.GetFileName(filePath);
            string outputPath = Path.Combine(outputDirectory, fileName);
            workbook.Save(outputPath);
        }

        Console.WriteLine("All Excel files have been processed and signed.");
    }
}
