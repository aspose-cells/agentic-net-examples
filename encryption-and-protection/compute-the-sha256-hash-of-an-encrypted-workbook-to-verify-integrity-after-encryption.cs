using System;
using System.IO;
using System.Security.Cryptography;
using Aspose.Cells;

// The sample creates a Workbook, adds data, applies a password to encrypt it, saves the encrypted file to a MemoryStream in XLSX format, computes a SHA‑256 hash of the resulting byte array, converts the hash to a lowercase hexadecimal string, and outputs the hash to the console.
class WorkbookHashExample
{
    static void Main()
    {
        // Create a new workbook and add some data
        Workbook workbook = new Workbook();
        Worksheet sheet = workbook.Worksheets[0];
        sheet.Cells["A1"].PutValue("Hello");
        sheet.Cells["B1"].PutValue("World");

        // Encrypt the workbook with a password
        workbook.Settings.Password = "SecretPassword";

        // Save the encrypted workbook to a memory stream
        using (MemoryStream ms = new MemoryStream())
        {
            workbook.Save(ms, SaveFormat.Xlsx);
            ms.Position = 0; // Reset stream position

            // Compute SHA‑256 hash of the encrypted workbook bytes
            using (SHA256 sha256 = SHA256.Create())
            {
                byte[] hashBytes = sha256.ComputeHash(ms.ToArray());

                // Convert hash to hexadecimal string for display
                string hashString = BitConverter.ToString(hashBytes).Replace("-", "").ToLowerInvariant();

                Console.WriteLine("SHA‑256 hash of encrypted workbook:");
                Console.WriteLine(hashString);
            }
        }
    }
}
