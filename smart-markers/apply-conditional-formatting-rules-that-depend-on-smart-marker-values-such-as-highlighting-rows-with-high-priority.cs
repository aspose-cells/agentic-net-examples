using System;
using System.Drawing;
using System.IO;
using Aspose.Cells;

namespace AsposeCellsConditionalFormattingExample
{
    // The sample loads an existing workbook, locates the "Priority" column generated by smart markers, and creates an expression‑based conditional formatting rule that fills entire rows with yellow when the priority equals "High". The formatted workbook is saved as a new file.
    class Program
    {
        static void Main(string[] args)
        {
            try
            {
                const string inputPath = "Input.xlsx";
                const string outputPath = "Output.xlsx";

                // Verify that the input file exists to avoid FileNotFoundException
                if (!File.Exists(inputPath))
                {
                    Console.WriteLine($"Input file \"{inputPath}\" not found.");
                    return;
                }

                // Load the workbook
                Workbook workbook = new Workbook(inputPath);

                // Get the first worksheet
                Worksheet worksheet = workbook.Worksheets[0];

                // ------------------------------------------------------------
                // Assume that the worksheet already contains data populated
                // via Smart Markers. For example, a column named "Priority"
                // may contain values like "High", "Medium", "Low".
                // ------------------------------------------------------------

                // Find the column index of the "Priority" header (assumed to be in the first row)
                int headerRowIndex = 0;
                int priorityColumnIndex = -1;
                int maxColumn = worksheet.Cells.MaxColumn;

                for (int col = 0; col <= maxColumn; col++)
                {
                    if (worksheet.Cells[headerRowIndex, col].StringValue.Equals("Priority", StringComparison.OrdinalIgnoreCase))
                    {
                        priorityColumnIndex = col;
                        break;
                    }
                }

                // If the "Priority" column is found, apply conditional formatting
                if (priorityColumnIndex != -1)
                {
                    // Determine the data range (from the row after the header to the last used row)
                    int firstDataRow = headerRowIndex + 1;
                    int lastDataRow = worksheet.Cells.MaxDataRow;

                    // Ensure there is at least one data row
                    if (lastDataRow < firstDataRow)
                    {
                        Console.WriteLine("No data rows found to apply conditional formatting.");
                    }
                    else
                    {
                        // Define the area to which the conditional formatting will be applied
                        int lastDataColumn = worksheet.Cells.MaxDataColumn;
                        CellArea area = new CellArea
                        {
                            StartRow = firstDataRow,
                            StartColumn = 0,
                            EndRow = lastDataRow,
                            EndColumn = lastDataColumn
                        };

                        // Add a new conditional formatting collection to the worksheet
                        int cfIndex = worksheet.ConditionalFormattings.Add();

                        // Use dynamic to avoid compile‑time dependency on the ConditionalFormatting type
                        dynamic cf = worksheet.ConditionalFormattings[cfIndex];
                        cf.AddArea(area);

                        // Build the formula that checks if the "Priority" cell in the current row equals "High"
                        string priorityColumnLetter = CellsHelper.ColumnIndexToName(priorityColumnIndex);
                        string formula = $"=${priorityColumnLetter}{firstDataRow + 1}=\"High\"";

                        // Add a condition of type Expression using the formula
                        int conditionIndex = cf.AddCondition(FormatConditionType.Expression);
                        dynamic condition = cf[conditionIndex];
                        condition.Formula1 = formula;

                        // Define the style to apply when the condition is met (e.g., yellow fill)
                        Style highlightStyle = workbook.CreateStyle();
                        highlightStyle.ForegroundColor = Color.Yellow;
                        highlightStyle.Pattern = BackgroundType.Solid;
                        condition.Style = highlightStyle;
                    }
                }
                else
                {
                    Console.WriteLine("Column \"Priority\" not found.");
                }

                // Save the modified workbook
                workbook.Save(outputPath);
                Console.WriteLine($"Workbook saved to \"{outputPath}\".");
            }
            catch (Exception ex)
            {
                Console.WriteLine($"An error occurred: {ex.Message}");
            }
        }
    }
}
