using System;
using System.Data;
using System.IO;
using Aspose.Cells;

// The example loads an Excel template, sets a DataTable as the "Employees" data source for smart markers, processes the markers with WorkbookDesigner, then iterates through all worksheets to increase numeric cell values by 10% and append "(modified)" to string cells before saving the workbook.
class Program
{
    static void Main()
    {
        try
        {
            const string inputPath = "input.xlsx";
            const string outputPath = "output.xlsx";

            // Ensure the input file exists; otherwise create a simple template with smart markers
            if (!File.Exists(inputPath))
            {
                CreateSampleTemplate(inputPath);
            }

            // Load the workbook that contains smart markers
            Workbook workbook = new Workbook(inputPath);

            // Create a WorkbookDesigner to process smart markers
            WorkbookDesigner designer = new WorkbookDesigner(workbook);

            // Set the data source for the smart markers
            designer.SetDataSource("Employees", GetEmployees());

            // Process all smart markers in the workbook
            designer.Process();

            // Apply post‑processing modifications (increase numeric values by 10% and append text)
            ApplyPostProcessing(workbook);

            // Save the modified workbook
            workbook.Save(outputPath);
            Console.WriteLine($"Workbook saved to '{outputPath}'.");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error: {ex.Message}");
        }
    }

    // Increments numeric cells by 10% and appends "(modified)" to all cell values
    private static void ApplyPostProcessing(Workbook workbook)
    {
        foreach (Worksheet sheet in workbook.Worksheets)
        {
            // Determine the used range of the worksheet
            var maxRow = sheet.Cells.MaxDataRow;
            var maxCol = sheet.Cells.MaxDataColumn;

            for (int row = 0; row <= maxRow; row++)
            {
                for (int col = 0; col <= maxCol; col++)
                {
                    Cell cell = sheet.Cells[row, col];
                    if (cell.Type == CellValueType.IsNumeric)
                    {
                        double original = cell.DoubleValue;
                        cell.PutValue(original * 1.10);
                    }

                    // Append custom text to the cell's string representation
                    string currentText = cell.StringValue;
                    if (!string.IsNullOrEmpty(currentText) && !currentText.EndsWith("(modified)"))
                    {
                        cell.PutValue($"{currentText} (modified)");
                    }
                }
            }
        }
    }

    // Creates a minimal template workbook with smart markers if the input file is missing
    private static void CreateSampleTemplate(string path)
    {
        Workbook wb = new Workbook();
        Worksheet ws = wb.Worksheets[0];
        ws.Name = "Report";

        // Header
        ws.Cells["A1"].PutValue("Name");
        ws.Cells["B1"].PutValue("Salary");

        // Smart markers referencing the Employees data source
        ws.Cells["A2"].PutValue("&=Employees.Name");
        ws.Cells["B2"].PutValue("&=Employees.Salary");

        // Save the template
        wb.Save(path);
    }

    // Sample data source for the smart markers
    private static DataTable GetEmployees()
    {
        DataTable dt = new DataTable("Employees");
        dt.Columns.Add("Name", typeof(string));
        dt.Columns.Add("Salary", typeof(double));

        dt.Rows.Add("John Doe", 5000);
        dt.Rows.Add("Jane Smith", 6200);
        dt.Rows.Add("Bob Johnson", 4800);

        return dt;
    }
}
