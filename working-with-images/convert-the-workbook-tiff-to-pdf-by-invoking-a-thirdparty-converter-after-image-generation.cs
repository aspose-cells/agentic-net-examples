using System;
using System.IO;
using Aspose.Cells;
using Aspose.Cells.Drawing;
using Aspose.Cells.Rendering;

// Demonstrates how to create a Workbook with Aspose.Cells, configure ImageOrPrintOptions for LZW‑compressed multi‑page TIFF output using WorkbookRender, save the TIFF, and then hand it off to an external library or service to produce a PDF file.
class Program
{
    static void Main()
    {
        // Create a new workbook and add sample data
        Workbook workbook = new Workbook();
        Worksheet sheet = workbook.Worksheets[0];
        sheet.Cells["A1"].PutValue("Sample data for TIFF to PDF conversion");

        // Configure image options for TIFF rendering
        ImageOrPrintOptions imgOptions = new ImageOrPrintOptions
        {
            ImageType = ImageType.Tiff,                     // render as TIFF
            TiffCompression = TiffCompression.CompressionLZW,
            OnePagePerSheet = true
        };

        // Render the entire workbook to a multi‑page TIFF file
        string tiffPath = "workbook_output.tiff";
        WorkbookRender wbRender = new WorkbookRender(workbook, imgOptions);
        wbRender.ToImage(tiffPath); // uses WorkbookRender.ToImage(string)

        // Invoke a third‑party converter to turn the TIFF into PDF
        string pdfPath = "workbook_output.pdf";
        ConvertTiffToPdf(tiffPath, pdfPath);

        Console.WriteLine("TIFF generated and converted to PDF successfully.");
    }

    // Placeholder for the third‑party TIFF‑to‑PDF conversion logic
