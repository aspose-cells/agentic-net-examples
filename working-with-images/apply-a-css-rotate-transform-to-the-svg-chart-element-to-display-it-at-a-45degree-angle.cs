using System;
using System.IO;
using System.Text;
using Aspose.Cells;
using Aspose.Cells.Charts;
using Aspose.Cells.Rendering;

namespace AsposeCellsSvgRotateDemo
{
    // The example creates a workbook, adds a line chart, exports it to an intermediate SVG using Aspose.Cells, reads the SVG content, injects a <style> block that applies a 45-degree CSS rotate transform to the root <svg> element, and saves the rotated SVG as the final output.
    class Program
    {
        static void Main(string[] args)
        {
            // Paths for the intermediate and final SVG files
            const string intermediateSvgPath = "chart_intermediate.svg";
            const string finalSvgPath = "chart_rotated_45deg.svg";

            try
            {
                // 1. Create a workbook and populate it with sample data
                Workbook workbook = new Workbook();
                Worksheet sheet = workbook.Worksheets[0];

                // Header
                sheet.Cells["A1"].PutValue("Year");
                sheet.Cells["B1"].PutValue("Sales");

                // Data
                sheet.Cells["A2"].PutValue(2019);
                sheet.Cells["A3"].PutValue(2020);
                sheet.Cells["A4"].PutValue(2021);
                sheet.Cells["A5"].PutValue(2022);

                sheet.Cells["B2"].PutValue(4500);
                sheet.Cells["B3"].PutValue(4900);
                sheet.Cells["B4"].PutValue(5200);
                sheet.Cells["B5"].PutValue(6100);

                // 2. Add a line chart that uses the data range
                int chartIndex = sheet.Charts.Add(ChartType.Line, 6, 0, 20, 10);
                Chart chart = sheet.Charts[chartIndex];
                chart.SetChartDataRange("A1:B5", true);

                // 3. Configure SVG generation options
                SvgImageOptions svgOptions = new SvgImageOptions
                {
                    // Optional: set a CSS prefix if you want to target specific elements later
                    CssPrefix = "mychart-"
                };

                // 4. Export the chart to an SVG file (intermediate version)
                chart.ToImage(intermediateSvgPath, svgOptions);
                Console.WriteLine($"Chart exported to intermediate SVG: {intermediateSvgPath}");

                // 5. Load the generated SVG, inject a CSS rotate transform, and save the final file
                string svgContent = File.ReadAllText(intermediateSvgPath, Encoding.UTF8);

                // Approach A: Add a <style> block that rotates the root <svg> element
                // This works in modern browsers that support CSS transforms on SVG.
                string styleBlock = @"
    <style type=""text/css"">
        svg { 
            transform: rotate(45deg); 
            transform-origin: center; 
        }
    </style>";

                // Insert the style block just after the opening <svg> tag
                int svgTagEnd = svgContent.IndexOf('>');
                if (svgTagEnd > -1)
                {
                    // Preserve any existing attributes on the <svg> tag
                    svgContent = svgContent.Insert(svgTagEnd + 1, styleBlock);
                }
                else
                {
                    Console.WriteLine("Warning: Unable to locate opening <svg> tag. No rotation will be applied.");
                }

                // 6. Write the modified SVG to the final path
                File.WriteAllText(finalSvgPath, svgContent, Encoding.UTF8);
                Console.WriteLine($"Rotated SVG saved as: {finalSvgPath}");
            }
            catch (Exception ex)
            {
                Console.WriteLine("An error occurred while processing the SVG chart:");
                Console.WriteLine(ex.Message);
            }
        }
    }
}
