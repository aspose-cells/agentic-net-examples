using System;
using System.IO;
using Aspose.Cells;
using Aspose.Cells.Rendering;

namespace AsposeCellsSvgTooltipDemo
{
    // C# example that creates a workbook, renders the first worksheet to SVG using Aspose.Cells, injects a <script> block, adds data-value attributes to <rect> elements, and saves the modified SVG so each cell displays a tooltip on hover in a browser.
    class Program
    {
        static void Main()
        {
            try
            {
                // Create a new workbook and populate some data
                Workbook workbook = new Workbook();
                Worksheet sheet = workbook.Worksheets[0];
                sheet.Cells["A1"].PutValue("Product");
                sheet.Cells["B1"].PutValue("Price");
                sheet.Cells["A2"].PutValue("Apple");
                sheet.Cells["B2"].PutValue(1.2);
                sheet.Cells["A3"].PutValue("Orange");
                sheet.Cells["B3"].PutValue(0.8);

                // Configure SVG rendering options
                SvgImageOptions svgOptions = new SvgImageOptions
                {
                    FitToViewPort = true
                    // CssClassPrefix is not supported in this version of Aspose.Cells
                };

                // Render the worksheet to an SVG file
                string svgPath = "worksheet.svg";
                SheetRender renderer = new SheetRender(sheet, svgOptions);
                renderer.ToImage(0, svgPath);

                // Ensure the SVG file was created before attempting to read it
                if (!File.Exists(svgPath))
                    throw new FileNotFoundException("SVG file was not generated.", svgPath);

                // Load the generated SVG content
                string svgContent = File.ReadAllText(svgPath);

                // JavaScript to show a simple tooltip on hover.
                // It adds a <title> element to each <rect> (cell background) if not present.
                string script = @"
<script type='text/javascript'>
document.addEventListener('DOMContentLoaded', function() {
    var cells = document.querySelectorAll('rect');
    cells.forEach(function(cell) {
        var tooltip = document.createElementNS('http://www.w3.org/2000/svg', 'title');
        tooltip.textContent = 'Cell value: ' + cell.getAttribute('data-value');
        cell.appendChild(tooltip);
    });
});
</script>";

                // Insert the script just before the closing </svg> tag
                int insertPos = svgContent.LastIndexOf("</svg>", StringComparison.OrdinalIgnoreCase);
                if (insertPos >= 0)
                {
                    svgContent = svgContent.Insert(insertPos, script);
                }

                // Optionally, add data-value attributes to rect elements based on cell values.
                // This simple example replaces each <rect .../> with a version that includes data-value.
                // In a real scenario, you would map cell positions to values more precisely.
                svgContent = svgContent.Replace("<rect ", "<rect data-value='Sample' ");

                // Save the modified SVG back to file
                File.WriteAllText(svgPath, svgContent);

                Console.WriteLine("SVG worksheet saved with embedded JavaScript tooltip support at: " + Path.GetFullPath(svgPath));
            }
            catch (Exception ex)
            {
                Console.Error.WriteLine("An error occurred: " + ex.Message);
            }
        }
    }
}
