using System;
using System.IO;
using Aspose.Cells;
using Aspose.Cells.Rendering;
using Aspose.Cells.Drawing;

// The sample loads an Excel workbook, creates a multi‑page TIFF with LZW compression at 300 dpi, then iterates through each worksheet and uses WorkbookRender with identical ImageOrPrintOptions to save every sheet as a separate single‑page TIFF file in a specified folder.
class Program
{
    static void Main()
    {
        // Paths – adjust as needed
        string excelPath = "input.xlsx";
        string multiTiffPath = "output_multi.tiff";
        string outputFolder = "Pages";

        try
        {
            // -------------------------------------------------
            // 1. Verify input file exists
            // -------------------------------------------------
            if (!File.Exists(excelPath))
                throw new FileNotFoundException($"Input Excel file not found: {excelPath}");

            // -------------------------------------------------
            // 2. Load the workbook
            // -------------------------------------------------
            Workbook workbook = new Workbook(excelPath);

            // -------------------------------------------------
            // 3. Render the whole workbook to a multi‑page TIFF
            // -------------------------------------------------
            ImageOrPrintOptions renderOptions = new ImageOrPrintOptions
            {
                ImageType = ImageType.Tiff,
                TiffCompression = TiffCompression.CompressionLZW,
                TiffColorDepth = ColorDepth.Format24bpp,
                HorizontalResolution = 300,
                VerticalResolution = 300
            };

            WorkbookRender renderer = new WorkbookRender(workbook, renderOptions);
            renderer.ToImage(multiTiffPath);
            Console.WriteLine($"Multi‑page TIFF created: {multiTiffPath}");

            // -------------------------------------------------
            // 4. Split the workbook into single‑page TIFF files
            // -------------------------------------------------
            SplitWorkbookIntoPages(workbook, outputFolder);
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error: {ex.Message}");
        }
    }

    /// <param name="workbook">The source workbook.</param>
    /// <param name="outputFolder">Folder where the single‑page TIFFs will be written.</param>
    static void SplitWorkbookIntoPages(Workbook workbook, string outputFolder)
    {
        try
        {
            // Ensure the output directory exists
            Directory.CreateDirectory(outputFolder);

            // Use the same rendering options as the multi‑page TIFF
            ImageOrPrintOptions pageOptions = new ImageOrPrintOptions
            {
                ImageType = ImageType.Tiff,
                TiffCompression = TiffCompression.CompressionLZW,
                TiffColorDepth = ColorDepth.Format24bpp,
                HorizontalResolution = 300,
                VerticalResolution = 300
            };

            // Render each worksheet (page) separately
            for (int i = 0; i < workbook.Worksheets.Count; i++)
            {
                WorkbookRender sheetRenderer = new WorkbookRender(workbook, pageOptions);
                string outPath = Path.Combine(outputFolder, $"page_{i + 1}.tiff");
                sheetRenderer.ToImage(i, outPath);
                Console.WriteLine($"Saved page {i + 1} to {outPath}");
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error while splitting workbook: {ex.Message}");
        }
    }
}
