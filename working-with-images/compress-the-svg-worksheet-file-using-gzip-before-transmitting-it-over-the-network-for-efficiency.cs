// Title: Render an Aspose.Cells worksheet to SVG, compress it with GZip, and upload the .gz file via HttpClient in C#
// Common Searches: C# render Excel worksheet to SVG using Aspose.Cells and compress with GZipStream | how to upload a gzip‑compressed SVG file with HttpClient in .NET | save Aspose.Cells worksheet as SVG in a memory stream then gzip before sending | optimal GZip compression settings for SVG generated by Aspose.Cells | set Content-Type for gzip file upload using HttpClient
// Tags: Aspose.Cells SVG generation | GZip compression of SVG stream | HttpClient gzip file upload | ImageOrPrintOptions SVG rendering | SheetRender to memory stream

using System;
using System.IO;
using System.Net.Http;
using System.Net.Http.Headers;
using System.Threading.Tasks;
using System.IO.Compression;
using Aspose.Cells;
using Aspose.Cells.Rendering;
using Aspose.Cells.Drawing;

namespace AsposeCellsSvgGzipDemo
{
    // The example creates a workbook, renders the first worksheet to an SVG stream with Aspose.Cells SheetRender, compresses the SVG using GZipStream into a .gz file, saves both raw and compressed files, and then posts the compressed SVG to a REST endpoint using HttpClient with the appropriate application/gzip content type.
    class Program
    {
        static async Task Main(string[] args)
        {
            const string tempSvgPath = "worksheet.svg";
            const string compressedPath = "worksheet.svg.gz";
            const string uploadUrl = "https://example.com/api/uploadSvg";

            try
            {
                // 1. Create a simple workbook with some data.
                Workbook workbook = new Workbook();
                Worksheet sheet = workbook.Worksheets[0];
                sheet.Name = "DemoSheet";
                sheet.Cells["A1"].PutValue("Aspose.Cells SVG GZip Demo");
                sheet.Cells["A2"].PutValue(DateTime.Now);
                sheet.Cells["B1"].PutValue(12345);
                // Set formula using the Formula property.
                sheet.Cells["B2"].Formula = "=SUM(B1)";

                // 2. Render the first worksheet to SVG.
                ImageOrPrintOptions options = new ImageOrPrintOptions
                {
                    ImageType = ImageType.Svg,
                    OnePagePerSheet = true
                };

                SheetRender renderer = new SheetRender(sheet, options);
                using (MemoryStream svgStream = new MemoryStream())
                {
                    // Render worksheet to SVG stream.
                    renderer.ToImage(0, svgStream);
                    svgStream.Position = 0;

                    // Optional: save raw SVG for debugging.
                    File.WriteAllBytes(tempSvgPath, svgStream.ToArray());
                    Console.WriteLine($"Raw SVG saved to '{tempSvgPath}' ({svgStream.Length} bytes).");

                    // 3. Compress the SVG using GZip.
                    using (MemoryStream compressedStream = new MemoryStream())
                    {
                        using (GZipStream gzip = new GZipStream(compressedStream, CompressionLevel.Optimal, leaveOpen: true))
                        {
                            svgStream.CopyTo(gzip);
                        }

                        compressedStream.Position = 0;
                        byte[] compressedBytes = compressedStream.ToArray();

                        // Optional: save compressed file for inspection.
                        File.WriteAllBytes(compressedPath, compressedBytes);
                        Console.WriteLine($"Compressed SVG saved to '{compressedPath}' ({compressedBytes.Length} bytes).");

                        // 4. Transmit the compressed data over HTTP.
                        using (HttpClient client = new HttpClient())
                        using (ByteArrayContent content = new ByteArrayContent(compressedBytes))
                        {
                            content.Headers.ContentType = new MediaTypeHeaderValue("application/gzip");
                            content.Headers.ContentDisposition = new ContentDispositionHeaderValue("attachment")
                            {
                                FileName = Path.GetFileName(compressedPath)
                            };

                            Console.WriteLine($"Uploading compressed SVG to {uploadUrl} ...");
                            HttpResponseMessage response = await client.PostAsync(uploadUrl, content);
                            if (response.IsSuccessStatusCode)
                            {
                                Console.WriteLine("Upload succeeded.");
                            }
                            else
                            {
                                Console.WriteLine($"Upload failed. Status: {(int)response.StatusCode} {response.ReasonPhrase}");
                                string responseBody = await response.Content.ReadAsStringAsync();
                                Console.WriteLine("Response body:");
                                Console.WriteLine(responseBody);
                            }
                        }
                    }
                }
            }
            catch (Exception ex)
            {
                Console.Error.WriteLine("An error occurred during processing:");
                Console.Error.WriteLine(ex.ToString());
            }
        }
    }
}
