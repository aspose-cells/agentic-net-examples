using System;
using System.IO;
using Aspose.Cells;
using Aspose.Cells.Rendering;

// The example creates a workbook containing a visible sheet and a hidden sheet, configures HtmlSaveOptions.ExportHiddenWorksheet to false, saves the workbook as an HTML file, reads the generated HTML, and confirms that the hidden worksheet's name is not present, demonstrating how to omit hidden worksheets from HTML output using Aspose.Cells for .NET.
class ExportHiddenWorksheetDemo
{
    static void Main()
    {
        // Create a new workbook
        Workbook workbook = new Workbook();

        // Add a visible worksheet
        Worksheet visibleSheet = workbook.Worksheets[0];
        visibleSheet.Name = "VisibleSheet";
        visibleSheet.Cells["A1"].PutValue("This sheet is visible.");

        // Add a hidden worksheet
        Worksheet hiddenSheet = workbook.Worksheets.Add("HiddenSheet");
        hiddenSheet.Cells["A1"].PutValue("This sheet is hidden.");
        hiddenSheet.IsVisible = false; // Hide the worksheet

        // Set HTML save options: do NOT export hidden worksheets
        HtmlSaveOptions htmlOptions = new HtmlSaveOptions(SaveFormat.Html);
        htmlOptions.ExportHiddenWorksheet = false;

        // Define output HTML file path
        string htmlPath = "ExportHiddenWorksheetDemo.html";

        // Save the workbook to HTML
        workbook.Save(htmlPath, htmlOptions);

        // Load the generated HTML content
        string htmlContent = File.ReadAllText(htmlPath);

        // Verify that the hidden worksheet name does not appear in the HTML
        bool hiddenSheetPresent = htmlContent.Contains("HiddenSheet");
        Console.WriteLine("Hidden worksheet present in HTML: " + hiddenSheetPresent);
        // Expected output: false (hidden worksheet should be absent)
    }
}
