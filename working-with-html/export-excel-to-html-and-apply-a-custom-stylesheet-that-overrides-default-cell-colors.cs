using System;
using System.IO;
using System.Drawing;
using Aspose.Cells;

// The sample creates a workbook with colored cells, writes a custom CSS file that forces specific background colors, saves the workbook as HTML using HtmlSaveOptions, and then injects a <link> element referencing the CSS into the generated HTML file.
class ExportExcelToHtmlWithCustomCss
{
    static void Main()
    {
        try
        {
            // Create a new workbook and add sample data with background colors
            Workbook workbook = new Workbook();
            Worksheet sheet = workbook.Worksheets[0];
            Cells cells = sheet.Cells;

            // Header cell with a light blue background
            cells["A1"].PutValue("Header");
            Style headerStyle = cells["A1"].GetStyle();
            headerStyle.ForegroundColor = Color.LightBlue;
            headerStyle.Pattern = BackgroundType.Solid;
            cells["A1"].SetStyle(headerStyle);

            // Data cell with a light green background
            cells["A2"].PutValue(123);
            Style dataStyle = cells["A2"].GetStyle();
            dataStyle.ForegroundColor = Color.LightGreen;
            dataStyle.Pattern = BackgroundType.Solid;
            cells["A2"].SetStyle(dataStyle);

            // Write custom CSS to disk
            string cssPath = "custom.css";
            string cssContent = @"
.aspnet-table td { background-color: #ffffff !important; }
.aspnet-table th { background-color: #f0f0f0 !important; }
";
            File.WriteAllText(cssPath, cssContent);

            // Save the workbook as HTML
            string htmlPath = "output.html";
            HtmlSaveOptions saveOptions = new HtmlSaveOptions(SaveFormat.Html);
            workbook.Save(htmlPath, saveOptions);

            // Insert a link to the custom CSS file into the generated HTML
            if (File.Exists(htmlPath))
            {
                string html = File.ReadAllText(htmlPath);
                string linkTag = $"<link rel=\"stylesheet\" type=\"text/css\" href=\"{cssPath}\" />{Environment.NewLine}";
                if (html.Contains("</head>"))
                {
                    html = html.Replace("</head>", linkTag + "</head>");
                }
                else
                {
                    html = linkTag + html;
                }
                File.WriteAllText(htmlPath, html);
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error: {ex.Message}");
        }
    }
}
