using System;
using System.IO;
using Aspose.Cells;

// Demonstrates how to create a workbook, save it as HTML with extra whitespace, reload the file with DeleteRedundantSpaces enabled, and save a cleaned HTML version using Aspose.Cells for .NET.
class HtmlRedundantSpacesDemo
{
    static void Main()
    {
        // Create a workbook and put text containing redundant spaces
        Workbook workbook = new Workbook();
        Worksheet sheet = workbook.Worksheets[0];
        sheet.Cells["A1"].PutValue("   This    text   has   redundant   spaces   ");

        // Save the workbook as HTML (original file with redundant spaces)
        string originalHtmlPath = "original.html";
        workbook.Save(originalHtmlPath, SaveFormat.Html);

        // Load the generated HTML with DeleteRedundantSpaces enabled
        byte[] htmlBytes = File.ReadAllBytes(originalHtmlPath);
        using (MemoryStream stream = new MemoryStream(htmlBytes))
        {
            HtmlLoadOptions loadOptions = new HtmlLoadOptions();
            loadOptions.DeleteRedundantSpaces = true; // Strip redundant spaces during load

            Workbook loadedWorkbook = new Workbook(stream, loadOptions);

            // Save the cleaned HTML to a new file
            string cleanedHtmlPath = "cleaned.html";
            loadedWorkbook.Save(cleanedHtmlPath, SaveFormat.Html);
        }

        Console.WriteLine("Original and cleaned HTML files have been created.");
    }
}
