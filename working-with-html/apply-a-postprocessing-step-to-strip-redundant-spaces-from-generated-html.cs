using Aspose.Cells;
using System;
using System.IO;
using System.Text;
using System.Text.RegularExpressions;

// The example creates a workbook, adds sample data, saves it as HTML to a memory stream, converts the stream to a string, and then uses regular expressions to collapse multiple spaces or tabs into a single space and to strip leading whitespace after line breaks. The cleaned HTML is written to 'output.html'.
class Program
{
    static void Main()
    {
        // Create a new workbook (lifecycle rule: create)
        Workbook workbook = new Workbook();

        // Populate some sample data
        workbook.Worksheets[0].Cells["A1"].PutValue("Sample");
        workbook.Worksheets[0].Cells["B1"].PutValue("Data");

        // Save the workbook as HTML into a memory stream (lifecycle rule: save)
        using (MemoryStream htmlStream = new MemoryStream())
        {
            workbook.Save(htmlStream, SaveFormat.Html);
            htmlStream.Position = 0;

            // Convert the HTML bytes to a string
            string htmlContent = Encoding.UTF8.GetString(htmlStream.ToArray());

            // Post‑processing: strip redundant spaces (multiple spaces/tabs -> single space)
            string cleanedHtml = Regex.Replace(htmlContent, @"[ \t]{2,}", " ");

            // Optional: remove leading spaces after line breaks
            cleanedHtml = Regex.Replace(cleanedHtml, @"\r?\n\s+", "\n");

            // Write the cleaned HTML to a file
            File.WriteAllText("output.html", cleanedHtml, Encoding.UTF8);
        }
    }
}
