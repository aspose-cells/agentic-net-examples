// Title: Apply a custom style to a specific range and export to HTML with only used styles using Aspose.Cells for .NET (C#)
// Common Searches: how to apply a custom style to a range and save workbook as HTML with Aspose.Cells in C# | Aspose.Cells .NET exclude unused CSS styles when converting Excel to HTML | count CSS class definitions generated by Aspose.Cells HTML export C# | verify that only applied styles are included in HTML output using Aspose.Cells
// Tags: apply custom style to range Aspose.Cells | exclude unused styles HTML save Aspose.Cells | verify generated CSS classes Aspose.Cells | C# export worksheet to HTML with used styles only | Aspose.Cells style verification after HTML conversion

using System;
using System.IO;
using System.Drawing;
using Aspose.Cells;
using Aspose.Cells.Rendering;

// The example creates a workbook, fills cells with data, defines a custom style (white bold font on dark blue background), applies it to the range A2:C4, and saves the sheet as HTML with ExcludeUnusedStyles enabled so only the used CSS is emitted. After saving, it reads the HTML file, counts the ".a" class definitions, and confirms that only the custom style appears, demonstrating style verification in the generated HTML.
class Program
{
    static void Main()
    {
        // Path for the generated HTML file
        const string htmlPath = "StyledRange.html";

        try
        {
            // 1. Create a new workbook and get the first worksheet
            Workbook workbook = new Workbook();
            Worksheet sheet = workbook.Worksheets[0];

            // 2. Populate some sample data
            for (int row = 0; row < 10; row++)
            {
                for (int col = 0; col < 5; col++)
                {
                    sheet.Cells[row, col].PutValue($"R{row + 1}C{col + 1}");
                }
            }

            // 3. Create a custom style
            Style customStyle = workbook.CreateStyle();
            customStyle.Font.Color = Color.White;
            customStyle.Font.IsBold = true;
            customStyle.Font.Size = 12;
            customStyle.ForegroundColor = Color.DarkBlue;
            customStyle.Pattern = BackgroundType.Solid;

            // 4. Apply the custom style to a specific range (A2:C4)
            Aspose.Cells.Range targetRange = sheet.Cells.CreateRange("A2:C4");
            StyleFlag flag = new StyleFlag { All = true };
            targetRange.ApplyStyle(customStyle, flag);

            // 5. Save the workbook to HTML with ExcludeUnusedStyles enabled
            HtmlSaveOptions htmlOptions = new HtmlSaveOptions(SaveFormat.Html)
            {
                ExcludeUnusedStyles = true,          // Exclude styles that are not used
                ExportActiveWorksheetOnly = true     // Export only the sheet we worked on
            };
            workbook.Save(htmlPath, htmlOptions);

            Console.WriteLine($"Workbook saved to HTML at: {Path.GetFullPath(htmlPath)}");

            // 6. Verify that only used styles are present in the generated HTML
            if (File.Exists(htmlPath))
            {
                string htmlContent = File.ReadAllText(htmlPath);

                // Count distinct ".a" class definitions (e.g., .a0{ )
                int usedStyleCount = 0;
                int index = 0;
                while ((index = htmlContent.IndexOf(".a", index, StringComparison.Ordinal)) != -1)
                {
                    if (index + 2 < htmlContent.Length && char.IsDigit(htmlContent[index + 2]))
                    {
                        usedStyleCount++;
                        index += 3; // Move past this occurrence
                    }
                    else
                    {
                        index += 2;
                    }
                }

                // Expect exactly one used style (the custom one)
                if (usedStyleCount == 1)
                {
                    Console.WriteLine("Verification succeeded: only the custom style is present in the HTML.");
                }
                else
                {
                    Console.WriteLine($"Verification warning: expected 1 used style, but found {usedStyleCount}.");
                }

                // Optional: display a snippet of the style block for manual inspection
                int styleStart = htmlContent.IndexOf("<style", StringComparison.OrdinalIgnoreCase);
                int styleEnd = htmlContent.IndexOf("</style>", StringComparison.OrdinalIgnoreCase);
                if (styleStart != -1 && styleEnd != -1 && styleEnd > styleStart)
                {
                    string styleBlock = htmlContent.Substring(styleStart, styleEnd - styleStart + 8);
                    Console.WriteLine("\n--- Extracted <style> block ---");
                    Console.WriteLine(styleBlock);
                    Console.WriteLine("--- End of <style> block ---\n");
                }
                else
                {
                    Console.WriteLine("No <style> block found in the generated HTML.");
                }
            }
            else
            {
                Console.WriteLine($"Error: HTML file '{htmlPath}' was not created.");
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine($"An error occurred: {ex.Message}");
        }
    }
}
