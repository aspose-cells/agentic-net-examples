using System;
using System.IO;
using Aspose.Cells;

namespace AsposeCellsHyperlinkReplacement
{
    // Demonstrates how to generate HTML from an Aspose.Cells workbook with relative links (IsFullPathLink = false), read the output file, and replace specific href attributes with fully qualified URLs by prepending a base domain via a simple string.Replace operation.
    class Program
    {
        static void Main()
        {
            // Create a new workbook and get the first worksheet
            Workbook workbook = new Workbook();
            Worksheet worksheet = workbook.Worksheets[0];

            // Add a sample text and a relative hyperlink to cell A1
            worksheet.Cells["A1"].PutValue("Click Here");
            worksheet.Hyperlinks.Add("A1", 1, 1, "page.html"); // relative link

            // Save the workbook as HTML with relative links (IsFullPathLink = false)
            string htmlPath = "output.html";
            HtmlSaveOptions saveOptions = new HtmlSaveOptions();
            saveOptions.IsFullPathLink = false; // generate relative URLs
            workbook.Save(htmlPath, saveOptions);

            // Read the generated HTML content
            string htmlContent = File.ReadAllText(htmlPath);

            // Define the absolute base URL to prepend
            string baseUrl = "https://mydomain.com/";

            // Replace the relative hyperlink with an absolute one using string replacement
            // This simple replacement assumes the exact pattern href="page.html"
            string updatedHtml = htmlContent.Replace("href=\"page.html\"", $"href=\"{baseUrl}page.html\"");

            // Write the modified HTML back to the same file (or a new file if preferred)
            File.WriteAllText(htmlPath, updatedHtml);

            Console.WriteLine("HTML file saved with absolute hyperlink URLs.");
        }
    }
}
