using System;
using System.IO;
using System.Text.RegularExpressions;
using System.Drawing;
using Aspose.Cells;
using Aspose.Cells.Tables;

// The example creates a workbook, fills column A with numeric data, applies a LightGreen DataBar conditional formatting rule to A1:A5, saves the workbook as an HTML file, reads the HTML, uses a regular expression to capture the width percentages of the rendered data‑bar divs, calculates the expected percentages from the cell values, and reports whether each HTML bar length matches the expected value.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook and get the first worksheet
            Workbook workbook = new Workbook();
            Worksheet sheet = workbook.Worksheets[0];
            Cells cells = sheet.Cells;

            // Populate sample data in column A (values 10, 30, 50, 70, 90)
            int[] values = { 10, 30, 50, 70, 90 };
            for (int i = 0; i < values.Length; i++)
            {
                cells[i, 0].PutValue(values[i]);
            }

            // Apply DataBar conditional formatting to the range A1:A5
            int cfIndex = sheet.ConditionalFormattings.Add();
            FormatConditionCollection collection = sheet.ConditionalFormattings[cfIndex];

            // Define the range for the conditional formatting
            CellArea area = new CellArea
            {
                StartRow = 0,
                EndRow = values.Length - 1,
                StartColumn = 0,
                EndColumn = 0
            };
            collection.AddArea(area);

            // Create a DataBar rule
            FormatCondition dataBarCondition = collection[collection.AddCondition(FormatConditionType.DataBar)];

            // Set the minimum and maximum lengths (percentage of cell width)
            dataBarCondition.DataBar.MinLength = 0;   // 0%
            dataBarCondition.DataBar.MaxLength = 100; // 100%

            // Use a solid fill color for the bar
            dataBarCondition.DataBar.Color = Color.LightGreen;

            // Save the workbook as HTML
            string htmlPath = "DataBarConditionalFormatting.html";
            workbook.Save(htmlPath, SaveFormat.Html);

            // Verify that the rendered bar lengths in HTML correspond to the cell values
            if (!File.Exists(htmlPath))
            {
                Console.WriteLine($"Failed to generate HTML file: {htmlPath}");
                return;
            }

            string htmlContent = File.ReadAllText(htmlPath);

            // Regex to capture width percentages inside style attributes of data bar divs
            // Example snippet: <div class="cf-databar" style="width:55%;"></div>
            Regex regex = new Regex(@"style\s*=\s*""[^""]*width\s*:\s*(\d+)%", RegexOptions.IgnoreCase);
            MatchCollection matches = regex.Matches(htmlContent);

            if (matches.Count != values.Length)
            {
                Console.WriteLine("Mismatch between number of data bars and data values.");
                return;
            }

            // Determine the maximum value to compute expected percentages
            double maxValue = 0;
            foreach (int v in values)
                if (v > maxValue) maxValue = v;

            bool allMatch = true;
            for (int i = 0; i < matches.Count; i++)
            {
                // Extract the width percentage from HTML
                int htmlWidthPercent = int.Parse(matches[i].Groups[1].Value);
                // Compute expected percentage based on cell value
                int expectedPercent = (int)Math.Round((values[i] / maxValue) * 100);
                Console.WriteLine($"Row {i + 1}: Value={values[i]}, Expected%={expectedPercent}, HTML%={htmlWidthPercent}");
                if (htmlWidthPercent != expectedPercent)
                {
                    allMatch = false;
                    Console.WriteLine($"  -> Mismatch detected at row {i + 1}");
                }
            }

            Console.WriteLine(allMatch
                ? "All data bar lengths correctly reflect cell values."
                : "Some data bar lengths do not match the expected values.");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"An error occurred: {ex.Message}");
        }
    }
}
