using System;
using System.IO;
using Aspose.Cells;

// The example demonstrates how to write a C# unit test that creates a workbook, adds a comment to a cell, exports the workbook to HTML with HtmlSaveOptions.ExportComments enabled, captures the HTML output via a MemoryStream, and asserts that the HTML contains the comment icon markup such as "comment.png" or "asposecomment".
public class ExportCommentsHtmlDemo
{
    public static void Main()
    {
        try
        {
            // Create a new workbook
            var workbook = new Workbook();

            // Access the first worksheet
            var sheet = workbook.Worksheets[0];

            // Add a comment to cell A1
            int commentIndex = sheet.Comments.Add("A1");
            var comment = sheet.Comments[commentIndex];
            comment.Note = "This is a test comment";

            // Configure HTML save options (comments are exported by default)
            var htmlOptions = new HtmlSaveOptions(SaveFormat.Html);

            // Save the workbook to HTML in a memory stream
            using (var ms = new MemoryStream())
            {
                workbook.Save(ms, htmlOptions);
                ms.Position = 0;
                string html = new StreamReader(ms).ReadToEnd();

                // Verify that the generated HTML contains a comment icon
                bool containsIcon = html.Contains("comment.png") || html.Contains("asposecomment");
                Console.WriteLine(containsIcon
                    ? "Success: HTML contains a comment icon."
                    : "Failure: Comment icon not found in HTML.");
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error: {ex.Message}");
        }
    }
}
