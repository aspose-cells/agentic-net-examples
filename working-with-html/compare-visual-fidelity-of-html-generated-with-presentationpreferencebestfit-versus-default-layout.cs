using System;
using System.IO;
using Aspose.Cells;
using Aspose.Cells.Charts;

namespace AsposeCellsExamples
{
    // Sample code creates a workbook with text, numbers, dates and a column chart, then saves two HTML files – one using HtmlSaveOptions.PresentationPreference = true (BestFit) and one with the default setting. It reports file‑size differences and shows the first 200 characters of each file to illustrate visual fidelity and layout changes.
    public class HtmlPresentationPreferenceComparison
    {
        public static void Run()
        {
            try
            {
                // Create a sample workbook with diverse content
                Workbook workbook = new Workbook();
                Worksheet sheet = workbook.Worksheets[0];

                // Populate cells with text, numbers, dates and a simple chart
                sheet.Cells["A1"].PutValue("Presentation Preference Comparison");
                sheet.Cells["A2"].PutValue(DateTime.Now);
                sheet.Cells["B2"].PutValue(12345.67);
                sheet.Cells["A4"].PutValue("Category");
                sheet.Cells["B4"].PutValue("Value");
                sheet.Cells["A5"].PutValue("Apple");
                sheet.Cells["B5"].PutValue(150);
                sheet.Cells["A6"].PutValue("Orange");
                sheet.Cells["B6"].PutValue(250);

                // Add a column chart to illustrate visual elements
                int chartIdx = sheet.Charts.Add(ChartType.Column, 8, 0, 20, 6);
                Chart chart = sheet.Charts[chartIdx];
                chart.NSeries.Add("B5:B6", true);
                chart.NSeries.CategoryData = "A5:A6";
                chart.Title.Text = "Fruit Sales";

                // Save with PresentationPreference = true (more beautiful layout)
                HtmlSaveOptions optionsBestFit = new HtmlSaveOptions
                {
                    PresentationPreference = true
                };
                string bestFitPath = "PresentationPreference_True.html";
                workbook.Save(bestFitPath, optionsBestFit);
                Console.WriteLine($"Saved HTML with PresentationPreference=true to '{bestFitPath}'");

                // Save with default layout (PresentationPreference = false)
                HtmlSaveOptions optionsDefault = new HtmlSaveOptions(); // default false
                string defaultPath = "PresentationPreference_False.html";
                workbook.Save(defaultPath, optionsDefault);
                Console.WriteLine($"Saved HTML with default PresentationPreference to '{defaultPath}'");

                // Simple visual fidelity comparison: file size and a snippet diff
                if (!File.Exists(bestFitPath) || !File.Exists(defaultPath))
                {
                    Console.WriteLine("One or both HTML files were not created successfully.");
                    return;
                }

                string htmlBestFit = File.ReadAllText(bestFitPath);
                string htmlDefault = File.ReadAllText(defaultPath);

                Console.WriteLine();
                Console.WriteLine("=== Comparison Results ===");
                Console.WriteLine($"File size (PresentationPreference=true):  {htmlBestFit.Length} characters");
                Console.WriteLine($"File size (PresentationPreference=false): {htmlDefault.Length} characters");

                // Show first 200 characters of each file to illustrate differences
                int previewLength = 200;
                Console.WriteLine();
                Console.WriteLine("Preview of HTML with PresentationPreference=true:");
                Console.WriteLine(htmlBestFit.Substring(0, Math.Min(previewLength, htmlBestFit.Length)));
                Console.WriteLine();
                Console.WriteLine("Preview of HTML with default PresentationPreference:");
                Console.WriteLine(htmlDefault.Substring(0, Math.Min(previewLength, htmlDefault.Length)));
            }
            catch (Exception ex)
            {
                Console.WriteLine($"An error occurred: {ex.Message}");
            }
        }
    }

    // Entry point for the application
    public class Program
    {
        public static void Main(string[] args)
        {
            HtmlPresentationPreferenceComparison.Run();
        }
    }
}
