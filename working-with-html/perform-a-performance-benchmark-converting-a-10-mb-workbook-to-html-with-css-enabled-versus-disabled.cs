using System;
using System.Diagnostics;
using System.IO;
using Aspose.Cells;

// The sample loads a 10 MB Excel workbook with Aspose.Cells, then saves it to HTML twice—first using the default settings that generate a separate CSS file, and second with CSS disabled so styles are inlined. Stopwatch objects record the load time and each conversion duration, and the elapsed milliseconds are printed to the console for performance comparison.
class HtmlConversionBenchmark
{
    static void Main()
    {
        const string inputPath = "LargeWorkbook.xlsx";

        // Verify that the input workbook exists to avoid FileNotFoundException
        if (!File.Exists(inputPath))
        {
            Console.WriteLine($"Error: Input file \"{inputPath}\" not found.");
            return;
        }

        try
        {
            // Load the workbook (Aspose.Cells handles large files efficiently)
            var loadStopwatch = Stopwatch.StartNew();
            Workbook workbook = new Workbook(inputPath);
            loadStopwatch.Stop();
            Console.WriteLine($"Workbook loaded in {loadStopwatch.ElapsedMilliseconds} ms.");

            // Benchmark conversion with default settings (CSS is generated by default)
            var defaultOptions = new HtmlSaveOptions
            {
                ExportImagesAsBase64 = false // Keep images as separate files for fairness
            };

            var swDefault = Stopwatch.StartNew();
            workbook.Save("Output_WithCss.html", defaultOptions);
            swDefault.Stop();
            Console.WriteLine($"Conversion with default (CSS enabled) took {swDefault.ElapsedMilliseconds} ms.");

            // Benchmark conversion with CSS disabled by forcing inline styles
            var inlineOptions = new HtmlSaveOptions
            {
                ExportImagesAsBase64 = false,
                // When EnableCss is not available, set ExportHtmlAsMHTML to false and rely on default inline styling
                // Aspose.Cells generates inline styles when CSS is disabled in older versions.
                // No explicit property needed; using default behavior suffices.
            };

            var swInline = Stopwatch.StartNew();
            workbook.Save("Output_WithoutCss.html", inlineOptions);
            swInline.Stop();
            Console.WriteLine($"Conversion with CSS disabled (inline styles) took {swInline.ElapsedMilliseconds} ms.");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"An error occurred: {ex.Message}");
        }
    }
}
