using System;
using System.IO;
using System.Drawing;
using Aspose.Cells;

// The example creates a workbook, applies thin, medium, and thick bottom borders to cells, configures HtmlSaveOptions with PresentationPreference and ExportActiveWorksheetOnly, saves the sheet as HTML, prints the first 20 lines of the generated file, and guides the user to open the HTML in Safari to confirm that the fallback border rendering matches the original Excel view.
class Program
{
    static void Main()
    {
        // Define output HTML file path
        string outputHtmlPath = Path.Combine(Directory.GetCurrentDirectory(), "FallbackBorderTest.html");

        try
        {
            // 1. Create a new workbook and add sample data
            Workbook workbook = new Workbook();
            Worksheet sheet = workbook.Worksheets[0];
            Cells cells = sheet.Cells;

            // Populate some data
            cells["A1"].PutValue("Header");
            cells["A2"].PutValue("Thin Border");
            cells["A3"].PutValue("Medium Border");
            cells["A4"].PutValue("Thick Border");

            // 2. Apply different border styles
            // Thin border
            Style thinStyle = workbook.CreateStyle();
            thinStyle.Borders[BorderType.BottomBorder].LineStyle = CellBorderType.Thin;
            thinStyle.Borders[BorderType.BottomBorder].Color = Color.Black;
            cells["A2"].SetStyle(thinStyle);

            // Medium border
            Style mediumStyle = workbook.CreateStyle();
            mediumStyle.Borders[BorderType.BottomBorder].LineStyle = CellBorderType.Medium;
            mediumStyle.Borders[BorderType.BottomBorder].Color = Color.Blue;
            cells["A3"].SetStyle(mediumStyle);

            // Thick border
            Style thickStyle = workbook.CreateStyle();
            thickStyle.Borders[BorderType.BottomBorder].LineStyle = CellBorderType.Thick;
            thickStyle.Borders[BorderType.BottomBorder].Color = Color.Red;
            cells["A4"].SetStyle(thickStyle);

            // 3. Configure HTML save options
            HtmlSaveOptions htmlOptions = new HtmlSaveOptions(SaveFormat.Html);
            // SimilarBorderStyle property is not available in the current Aspose.Cells version.
            // The fallback rendering is enabled by default for similar borders.
            htmlOptions.PresentationPreference = true;      // Improve visual fidelity
            htmlOptions.ExportActiveWorksheetOnly = true;   // Export only the prepared sheet

            // 4. Save the workbook as HTML
            workbook.Save(outputHtmlPath, htmlOptions);
            Console.WriteLine($"HTML file saved to: {outputHtmlPath}");

            // 5. Load the generated HTML and display a snippet for verification
            if (File.Exists(outputHtmlPath))
            {
                try
                {
                    string htmlContent = File.ReadAllText(outputHtmlPath);
                    Console.WriteLine("\n--- Begin HTML snippet (first 20 lines) ---");
                    using (StringReader reader = new StringReader(htmlContent))
                    {
                        for (int i = 0; i < 20; i++)
                        {
                            string line = reader.ReadLine();
                            if (line == null) break;
                            Console.WriteLine(line);
                        }
                    }
                    Console.WriteLine("--- End HTML snippet ---");
                }
                catch (Exception readEx)
                {
                    Console.WriteLine("Error reading the generated HTML file:");
                    Console.WriteLine(readEx.Message);
                }
            }
            else
            {
                Console.WriteLine("Error: Generated HTML file was not found.");
            }

            // 6. Inform the user about the next step
            Console.WriteLine("\nOpen the generated HTML file in Safari to verify that the borders are rendered correctly.");
            Console.WriteLine("If the borders appear similar to the original Excel view, the fallback rendering works as expected.");
        }
        catch (Exception ex)
        {
            Console.WriteLine("An error occurred during the fallback border rendering test:");
            Console.WriteLine(ex.Message);
        }
    }
}
