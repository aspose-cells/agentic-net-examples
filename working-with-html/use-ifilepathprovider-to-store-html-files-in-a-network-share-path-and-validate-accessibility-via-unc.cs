using System;
using System.IO;
using Aspose.Cells;
using Aspose.Cells.Rendering;

// The example shows how to implement a custom NetworkShareFilePathProvider that builds full UNC file names for HTML files generated by Aspose.Cells. It validates that the UNC directory exists and is writable, creates a simple workbook, configures HtmlSaveOptions, saves the workbook as HTML directly to the network share, and confirms the file was created while handling possible errors.
public class NetworkShareFilePathProvider : IFilePathProvider
{
    private readonly string _uncRoot;

    /// <param name="uncRoot">The UNC directory where HTML files will be stored.</param>
    public NetworkShareFilePathProvider(string uncRoot)
    {
        if (string.IsNullOrWhiteSpace(uncRoot))
            throw new ArgumentException("UNC root path cannot be null or empty.", nameof(uncRoot));

        // Ensure the path ends with a backslash for proper concatenation.
        _uncRoot = uncRoot.TrimEnd('\\') + "\\";
    }

    /// <param name="fileName">The file name generated by Aspose.Cells (e.g., "Sheet1.html").</param>
    /// <returns>Full UNC path where the file should be saved.</returns>
    public string GetFullName(string fileName)
    {
        // Combine the UNC root with the file name.
        return Path.Combine(_uncRoot, fileName);
    }
}

class Program
{
    static void Main()
    {
        // Define the UNC path to the network share.
        // Example: \\fileserver\shared\reports
        string uncPath = @"\\fileserver\shared\reports";

        // Validate that the UNC path is accessible.
        if (!Directory.Exists(uncPath))
        {
            Console.WriteLine($"Error: The UNC path '{uncPath}' is not accessible.");
            return;
        }

        // Optional: test write permission by creating a temporary file.
        string testFile = Path.Combine(uncPath, "AsposeCellsWriteTest.tmp");
        try
        {
            File.WriteAllText(testFile, "test");
            File.Delete(testFile);
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error: Write permission to UNC path failed. {ex.Message}");
            return;
        }

        try
        {
            // Create a simple workbook.
            Workbook workbook = new Workbook();
            Worksheet sheet = workbook.Worksheets[0];
            sheet.Name = "SampleData";

            // Populate some data.
            sheet.Cells["A1"].PutValue("Product");
            sheet.Cells["B1"].PutValue("Quantity");
            sheet.Cells["A2"].PutValue("Apples");
            sheet.Cells["B2"].PutValue(120);
            sheet.Cells["A3"].PutValue("Bananas");
            sheet.Cells["B3"].PutValue(85);

            // Configure HTML save options.
            HtmlSaveOptions saveOptions = new HtmlSaveOptions
            {
                // Optional: keep images as separate files (set to false to embed as Base64).
                ExportImagesAsBase64 = false,

                // Optional: generate a single HTML file without external CSS.
                ExportActiveWorksheetOnly = true
            };

            // Full path for the main HTML file on the UNC share.
            string finalHtmlPath = Path.Combine(uncPath, "Report.html");

            // Save the workbook as HTML; files will be written to the UNC share.
            workbook.Save(finalHtmlPath, saveOptions);

            // Verify that the main HTML file exists on the network share.
            if (File.Exists(finalHtmlPath))
            {
                Console.WriteLine($"HTML report successfully saved to: {finalHtmlPath}");
            }
            else
            {
                Console.WriteLine("Error: HTML file was not created on the UNC share.");
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine($"An error occurred during workbook processing: {ex.Message}");
        }
    }
}
