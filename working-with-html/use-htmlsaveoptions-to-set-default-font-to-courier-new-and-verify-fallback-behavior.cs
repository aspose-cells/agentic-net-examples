using System;
using System.IO;
using Aspose.Cells;
using Aspose.Cells.Rendering;

// The sample creates a workbook, applies a non‑existent font to a cell, configures HtmlSaveOptions.DefaultFontName to "Courier New", saves the workbook as HTML, and then reads the generated file to confirm that the fallback font‑family is correctly applied.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook
            Workbook workbook = new Workbook();

            // Access the first worksheet
            Worksheet sheet = workbook.Worksheets[0];

            // Put some text in cell A1
            Cell cell = sheet.Cells["A1"];
            cell.PutValue("Sample text with missing font");

            // Apply a style with a font that likely does not exist on the system
            Style style = cell.GetStyle();
            style.Font.Name = "NonExistentFont"; // This font is expected to be unavailable
            style.Font.Size = 12;
            cell.SetStyle(style);

            // Configure HtmlSaveOptions and set a fallback default font
            HtmlSaveOptions htmlOptions = new HtmlSaveOptions(SaveFormat.Html);
            htmlOptions.DefaultFontName = "Courier New";

            // Define output HTML file path
            string htmlPath = Path.Combine(Environment.CurrentDirectory, "output.html");

            // Ensure the directory exists
            string outputDir = Path.GetDirectoryName(htmlPath);
            if (!Directory.Exists(outputDir))
            {
                Directory.CreateDirectory(outputDir);
            }

            // Save the workbook as HTML using the configured options
            workbook.Save(htmlPath, htmlOptions);

            // Simple verification: read the generated HTML and check for the fallback font
            if (File.Exists(htmlPath))
            {
                string htmlContent = File.ReadAllText(htmlPath);
                if (htmlContent.Contains("font-family:\"Courier New\""))
                {
                    Console.WriteLine("Fallback to \"Courier New\" applied successfully.");
                }
                else
                {
                    Console.WriteLine("Fallback font not applied as expected.");
                }
            }
            else
            {
                Console.WriteLine($"HTML file was not created at path: {htmlPath}");
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine($"An error occurred: {ex.Message}");
        }
    }
}
