using System;
using System.IO;
using System.Drawing;
using Aspose.Cells;
using Aspose.Cells.Rendering;

// // Creates a workbook, fills A1:A10 with values 1‑10, applies a LightGreen DataBar conditional format, saves the workbook as HTML (producing Workbook.html and Workbook.css), and reads the generated CSS file for analysis.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook and get the first worksheet
            Workbook workbook = new Workbook();
            Worksheet sheet = workbook.Worksheets[0];

            // Populate sample data in column A (A1:A10)
            for (int i = 0; i < 10; i++)
            {
                sheet.Cells[i, 0].PutValue(i + 1); // Values 1..10
            }

            // Apply a DataBar conditional formatting to the range A1:A10
            int formatIndex = sheet.ConditionalFormattings.Add();
            FormatConditionCollection fcc = sheet.ConditionalFormattings[formatIndex];

            // Add a DataBar condition (use FormatConditionType enum)
            int conditionIndex = fcc.AddCondition(FormatConditionType.DataBar);
            FormatCondition dataBarCondition = fcc[conditionIndex];

            // Configure the DataBar appearance
            dataBarCondition.DataBar.Color = Color.LightGreen;
            dataBarCondition.DataBar.ShowValue = true;
            dataBarCondition.DataBar.MinLength = 0;
            dataBarCondition.DataBar.MaxLength = 100;

            // Set up HTML save options (default settings)
            HtmlSaveOptions saveOptions = new HtmlSaveOptions(SaveFormat.Html);

            // Define output folder and file names
            string outputFolder = Path.Combine(Directory.GetCurrentDirectory(), "Output");
            Directory.CreateDirectory(outputFolder);
            string htmlPath = Path.Combine(outputFolder, "Workbook.html");
            string cssPath = Path.Combine(outputFolder, "Workbook.css"); // Expected CSS file name

            // Save the workbook as HTML (this will also create the CSS file if applicable)
            try
            {
                workbook.Save(htmlPath, saveOptions);
            }
            catch (Exception saveEx)
            {
                Console.WriteLine("Error saving workbook as HTML: " + saveEx.Message);
                return;
            }

            // Read the generated CSS file content if it exists
            if (File.Exists(cssPath))
            {
                try
                {
                    string cssContent = File.ReadAllText(cssPath);
                    Console.WriteLine("=== Generated CSS Classes ===");
                    Console.WriteLine(cssContent);
                }
                catch (Exception readEx)
                {
                    Console.WriteLine("Error reading CSS file: " + readEx.Message);
                }
            }
            else
            {
                Console.WriteLine("CSS file was not generated at: " + cssPath);
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine("An error occurred: " + ex.Message);
        }
    }
}
