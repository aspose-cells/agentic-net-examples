using System;
using System.IO;
using System.Drawing;
using Aspose.Cells;
using Aspose.Cells.Rendering;

// The example creates a new workbook, fills cells A1:A10 with numbers, adds a DataBar conditional formatting rule to that range, saves the workbook as HTML (which also creates a .css file), and then reads and prints the generated CSS content if the file exists.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook and get the first worksheet
            Workbook workbook = new Workbook();
            Worksheet sheet = workbook.Worksheets[0];

            // Populate sample data in column A (A1:A10)
            for (int i = 0; i < 10; i++)
            {
                sheet.Cells[i, 0].PutValue(i + 1);
            }

            // Define the range for DataBar conditional formatting (A1:A10)
            CellArea area = new CellArea
            {
                StartRow = 0,
                EndRow = 9,
                StartColumn = 0,
                EndColumn = 0
            };

            // Add a conditional formatting collection for the defined range
            int cfIndex = sheet.ConditionalFormattings.Add();
            FormatConditionCollection collection = sheet.ConditionalFormattings[cfIndex];
            collection.AddArea(area);

            // Create a DataBar conditional formatting rule
            FormatCondition dataBarCondition = collection[collection.AddCondition(FormatConditionType.DataBar)];
            dataBarCondition.DataBar.MinLength = 0;   // 0% of the cell width
            dataBarCondition.DataBar.MaxLength = 100; // 100% of the cell width
            dataBarCondition.DataBar.Color = Color.LightGreen; // Set bar color

            // Prepare HTML save options (default options export conditional formatting)
            HtmlSaveOptions htmlOptions = new HtmlSaveOptions();

            // Save the workbook as HTML (generates both HTML and CSS files)
            string htmlPath = "WorkbookWithDataBar.html";
            workbook.Save(htmlPath, htmlOptions);

            // Attempt to locate the generated CSS file (same name with .css extension)
            string cssPath = Path.ChangeExtension(htmlPath, ".css");
            if (File.Exists(cssPath))
            {
                string cssContent = File.ReadAllText(cssPath);
                Console.WriteLine("Generated CSS Classes:");
                Console.WriteLine(cssContent);
            }
            else
            {
                Console.WriteLine("CSS file was not generated.");
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine($"An error occurred: {ex.Message}");
        }
    }
}
