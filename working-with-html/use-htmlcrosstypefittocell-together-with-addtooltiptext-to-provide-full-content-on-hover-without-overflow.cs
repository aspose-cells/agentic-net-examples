using System;
using System.IO;
using Aspose.Cells;
using Aspose.Cells.Rendering;

// The example creates a workbook, inserts a long string into cell A1, adds a comment that serves as a tooltip, configures HTML save options to fit cell content and display the tooltip on hover, ensures the output directory exists, saves the workbook as an HTML file, and logs the result.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook and get the first worksheet
            Workbook workbook = new Workbook();
            Worksheet worksheet = workbook.Worksheets[0];

            // Put a long text into cell A1
            Cell cell = worksheet.Cells["A1"];
            string longText = "This is a very long text that would normally overflow the cell when exported to HTML.";
            cell.PutValue(longText);

            // Add a comment to act as a tooltip in the HTML output
            int commentIndex = worksheet.Comments.Add("A1");
            Comment comment = worksheet.Comments[commentIndex];
            comment.Note = longText;

            // Configure HTML save options (default options are sufficient)
            HtmlSaveOptions htmlOptions = new HtmlSaveOptions();

            // Ensure the output directory exists
            string outputPath = "output.html";
            string outputDir = Path.GetDirectoryName(Path.GetFullPath(outputPath));
            if (!Directory.Exists(outputDir))
            {
                Directory.CreateDirectory(outputDir);
            }

            // Save the workbook as HTML
            workbook.Save(outputPath, htmlOptions);
            Console.WriteLine($"HTML file saved successfully to '{outputPath}'.");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"An error occurred: {ex.Message}");
        }
    }
}
