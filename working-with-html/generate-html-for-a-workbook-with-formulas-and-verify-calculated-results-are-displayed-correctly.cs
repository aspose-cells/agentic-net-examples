using System;
using Aspose.Cells;

namespace AsposeCellsHtmlExample
{
    // The example creates a new Workbook, populates cells A1‑A5 with numeric values, inserts SUM and AVERAGE formulas in B1 and B2, forces calculation of all formulas, and saves the workbook as an HTML file where the computed results are rendered.
    class Program
    {
        static void Main(string[] args)
        {
            // Create a new workbook
            Workbook workbook = new Workbook();

            // Access the first worksheet
            Worksheet sheet = workbook.Worksheets[0];
            sheet.Name = "Data";

            // Populate some numeric values in column A (A1:A5)
            sheet.Cells["A1"].PutValue(10);
            sheet.Cells["A2"].PutValue(20);
            sheet.Cells["A3"].PutValue(30);
            sheet.Cells["A4"].PutValue(40);
            sheet.Cells["A5"].PutValue(50);

            // Insert a formula in cell B1 to calculate the sum of A1:A5
            sheet.Cells["B1"].Formula = "=SUM(A1:A5)";

            // Insert a formula in cell B2 to calculate the average of A1:A5
            sheet.Cells["B2"].Formula = "=AVERAGE(A1:A5)";

            // Force calculation of all formulas in the workbook
            workbook.CalculateFormula();

            // Save the workbook as an HTML file; calculated results will be rendered
            workbook.Save("WorkbookWithFormulas.html", SaveFormat.Html);

            Console.WriteLine("HTML file generated successfully.");
        }
    }
}
