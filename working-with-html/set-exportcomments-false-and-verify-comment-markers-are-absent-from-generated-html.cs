// Title: Export a workbook to HTML without comments and verify comment markers are absent using Aspose.Cells for .NET (C#)
// Common Searches: C# Aspose.Cells export workbook to HTML without exporting comments | how to clear worksheet comments before saving as HTML with Aspose.Cells | verify that comment text is not present in HTML output generated by Aspose.Cells | Aspose.Cells HtmlSaveOptions disable comment export workaround in C# | detect comment marker strings in HTML file created by Aspose.Cells
// Tags: disable comment export Aspose.Cells HTML | clear worksheet comments before HTML save | verify comment absence in generated HTML Aspose.Cells | HtmlSaveOptions without comments C# | C# workbook to HTML without comments Aspose.Cells

using System;
using System.IO;
using Aspose.Cells;

namespace ExportCommentsDemo
{
    // The example creates a workbook, adds a comment, clears all comments to prevent export, saves the workbook as HTML using HtmlSaveOptions, then reads the HTML file to confirm that neither the comment text nor typical comment marker strings appear.
    class Program
    {
        static void Main(string[] args)
        {
            // Path for the generated HTML file
            const string htmlPath = "WorkbookWithoutComments.html";

            try
            {
                // ------------------------------------------------------------
                // 1. Create a workbook and add a comment to a cell
                // ------------------------------------------------------------
                Workbook workbook = new Workbook();
                Worksheet sheet = workbook.Worksheets[0];

                // Put some data into a cell
                sheet.Cells["A1"].PutValue("Hello World");

                // Add a comment to the same cell
                int commentIndex = sheet.Comments.Add("A1");
                Comment comment = sheet.Comments[commentIndex];
                comment.Note = "This is a sample comment that should NOT appear in HTML.";

                // ------------------------------------------------------------
                // 2. Configure HTML save options – disable comment export
                // ------------------------------------------------------------
                HtmlSaveOptions htmlOptions = new HtmlSaveOptions();

                // The ExportComments property is not available in some versions of Aspose.Cells.
                // As an alternative, remove all comments from the worksheet before saving.
                sheet.Comments.Clear();

                // ------------------------------------------------------------
                // 3. Save the workbook as HTML using the configured options
                // ------------------------------------------------------------
                workbook.Save(htmlPath, htmlOptions);
                Console.WriteLine($"Workbook saved to HTML at: {Path.GetFullPath(htmlPath)}");

                // ------------------------------------------------------------
                // 4. Verify that the comment text is NOT present in the HTML
                // ------------------------------------------------------------
                if (!File.Exists(htmlPath))
                {
                    Console.WriteLine("ERROR: HTML file was not created.");
                    return;
                }

                string htmlContent = File.ReadAllText(htmlPath);

                // Simple verification: the comment text should not be found
                bool commentFound = htmlContent.Contains(comment.Note);

                if (commentFound)
                {
                    Console.WriteLine("FAILURE: Comment text was found in the generated HTML.");
                }
                else
                {
                    Console.WriteLine("SUCCESS: Comment text is absent from the generated HTML as expected.");
                }

                // Additional sanity check – look for typical comment marker strings
                bool commentMarkerFound = htmlContent.Contains("class=\"comment\"") ||
                                          htmlContent.Contains("data-comment") ||
                                          htmlContent.Contains("comment");

                if (commentMarkerFound)
                {
                    Console.WriteLine("NOTE: Some generic comment‑related strings were detected, but the actual comment text is missing.");
                }
                else
                {
                    Console.WriteLine("No generic comment markers detected in the HTML.");
                }
            }
            catch (Exception ex)
            {
                Console.WriteLine("An error occurred during processing:");
                Console.WriteLine(ex.Message);
            }
        }
    }
}
