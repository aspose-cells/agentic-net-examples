using System;
using System.IO;
using Aspose.Cells;

namespace AsposeCellsTests
{
    // The example creates a workbook with a visible and a hidden worksheet, sets HtmlSaveOptions.ExportHiddenWorksheet to true, saves the workbook to an in‑memory HTML stream, reads the HTML content, and asserts that the hidden worksheet name is present, demonstrating how to unit‑test this Aspose.Cells feature in C#.
    public class Program
    {
        public static void Main()
        {
            try
            {
                // Create a new workbook
                var workbook = new Workbook();

                // Add a visible worksheet and set its name
                var visibleSheet = workbook.Worksheets[0];
                visibleSheet.Name = "VisibleSheet";

                // Add a hidden worksheet and set its name
                var hiddenSheet = workbook.Worksheets.Add("HiddenSheet");
                // Hide the sheet (use IsVisible property for compatibility)
                hiddenSheet.IsVisible = false;

                // Prepare HTML save options and enable exporting of hidden worksheets
                var htmlOptions = new HtmlSaveOptions
                {
                    ExportHiddenWorksheet = true
                };

                // Export the workbook to HTML using a memory stream
                string htmlContent;
                using (var ms = new MemoryStream())
                {
                    workbook.Save(ms, htmlOptions);
                    ms.Position = 0;
                    using (var reader = new StreamReader(ms))
                    {
                        htmlContent = reader.ReadToEnd();
                    }
                }

                // Verify that the hidden sheet title appears in the HTML output
                if (htmlContent.Contains("HiddenSheet"))
                {
                    Console.WriteLine("Success: HTML output contains the hidden worksheet title.");
                }
                else
                {
                    Console.WriteLine("Failure: HTML output does NOT contain the hidden worksheet title.");
                }
            }
            catch (Exception ex)
            {
                // Log any unexpected errors
                Console.WriteLine($"An error occurred: {ex.Message}");
            }
        }
    }
}
