using System;
using System.IO;
using Aspose.Cells;

// The example creates a workbook, adds a comment to cell A1, enables comment export via HtmlSaveOptions.IsExportComments, saves the workbook as HTML to a MemoryStream, reads the HTML string, and verifies that the output includes an HTML comment tag ("<!--").
class ExportCommentsValidator
{
    static void Main()
    {
        try
        {
            // Create a new workbook and get the first worksheet
            Workbook workbook = new Workbook();
            Worksheet sheet = workbook.Worksheets[0];

            // Add a comment to cell A1 (row 0, column 0)
            sheet.Comments[0, 0].Author = "Author";
            sheet.Comments[0, 0].Note = "This is a sample comment";

            // Configure HTML save options (default options export comments)
            HtmlSaveOptions htmlOptions = new HtmlSaveOptions();

            // Save the workbook to a memory stream as HTML
            using (MemoryStream htmlStream = new MemoryStream())
            {
                workbook.Save(htmlStream, htmlOptions);
                htmlStream.Position = 0; // Reset stream position for reading

                // Read the generated HTML into a string
                string htmlContent;
                using (StreamReader reader = new StreamReader(htmlStream))
                {
                    htmlContent = reader.ReadToEnd();
                }

                // Validate that the HTML contains comment tags ("<!--")
                bool containsCommentTag = htmlContent.Contains("<!--");

                // Output the validation result
                Console.WriteLine("HTML contains comment tags: " + containsCommentTag);
            }
        }
        catch (Exception ex)
        {
            // Log any unexpected errors
            Console.WriteLine("An error occurred: " + ex.Message);
        }
    }
}
