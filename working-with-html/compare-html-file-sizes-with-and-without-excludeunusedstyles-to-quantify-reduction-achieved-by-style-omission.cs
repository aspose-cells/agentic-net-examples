using System;
using System.IO;
using Aspose.Cells;
using Aspose.Cells.Saving;

namespace HtmlStyleComparison
{
    // The example creates a workbook, applies used and unused styles, saves the workbook to HTML twice—once with ExcludeUnusedStyles set to false and once set to true—then reads the file sizes, computes the byte and percentage reduction, and prints the results.
    class Program
    {
        static void Main(string[] args)
        {
            try
            {
                // Create a new workbook and get the first worksheet
                Workbook workbook = new Workbook();
                Worksheet sheet = workbook.Worksheets[0];

                // Populate some data
                for (int row = 0; row < 10; row++)
                {
                    for (int col = 0; col < 5; col++)
                    {
                        sheet.Cells[row, col].PutValue($"R{row + 1}C{col + 1}");
                    }
                }

                // Apply a variety of styles to a subset of cells (used styles)
                for (int i = 0; i < 5; i++)
                {
                    Style usedStyle = workbook.CreateStyle();
                    usedStyle.Font.Name = "Arial";
                    usedStyle.Font.Size = 10 + i;
                    usedStyle.Font.IsBold = i % 2 == 0;
                    usedStyle.ForegroundColor = i % 2 == 0 ? System.Drawing.Color.LightBlue : System.Drawing.Color.LightGreen;
                    usedStyle.Pattern = BackgroundType.Solid;
                    sheet.Cells[i, i].SetStyle(usedStyle);
                }

                // Create several styles that will NOT be applied to any cell (unused styles)
                for (int i = 0; i < 8; i++)
                {
                    Style unusedStyle = workbook.CreateStyle();
                    unusedStyle.Font.Name = "Courier New";
                    unusedStyle.Font.Size = 12 + i;
                    unusedStyle.Font.IsItalic = true;
                    unusedStyle.ForegroundColor = System.Drawing.Color.FromArgb(200, i * 30, i * 20);
                    unusedStyle.Pattern = BackgroundType.Solid;
                    // Do NOT assign this style to any cell – it remains unused
                }

                // Define file names
                string fileWithoutExclusion = "HtmlWithoutExcludeUnusedStyles.html";
                string fileWithExclusion = "HtmlWithExcludeUnusedStyles.html";

                // Save HTML without excluding unused styles
                HtmlSaveOptions optionsWithout = new HtmlSaveOptions();
                optionsWithout.ExcludeUnusedStyles = false; // keep all styles
                workbook.Save(fileWithoutExclusion, optionsWithout);

                // Save HTML with excluding unused styles
                HtmlSaveOptions optionsWith = new HtmlSaveOptions();
                optionsWith.ExcludeUnusedStyles = true; // omit styles that are not used
                workbook.Save(fileWithExclusion, optionsWith);

                // Get file sizes
                long sizeWithout = new FileInfo(fileWithoutExclusion).Length;
                long sizeWith = new FileInfo(fileWithExclusion).Length;

                // Calculate reduction
                double reductionBytes = sizeWithout - sizeWith;
                double reductionPercent = sizeWithout > 0 ? (reductionBytes * 100.0 / sizeWithout) : 0;

                // Output the results
                Console.WriteLine("HTML Export Size Comparison");
                Console.WriteLine("----------------------------");
                Console.WriteLine($"File without ExcludeUnusedStyles : {sizeWithout:N0} bytes");
                Console.WriteLine($"File with ExcludeUnusedStyles    : {sizeWith:N0} bytes");
                Console.WriteLine($"Size reduction                    : {reductionBytes:N0} bytes ({reductionPercent:F2}%)");
            }
            catch (Exception ex)
            {
                Console.WriteLine("An error occurred during processing:");
                Console.WriteLine(ex.Message);
            }
        }
    }
}
