using System;
using Aspose.Cells;
using Aspose.Cells.Charts;
using Aspose.Cells.Rendering;

namespace AsposeCellsMhtmlTest
{
    // The example creates a workbook, fills a worksheet with sample data, adds a column chart, configures HtmlSaveOptions to export only the active worksheet as a single HTML file, saves it, and demonstrates how to verify the output renders correctly in Google Chrome without IE‑specific compatibility settings.
    class Program
    {
        static void Main(string[] args)
        {
            try
            {
                // Create a new workbook
                Workbook workbook = new Workbook();

                // Access the first worksheet and give it a name
                Worksheet sheet = workbook.Worksheets[0];
                sheet.Name = "SampleData";

                // Populate sample data
                sheet.Cells["A1"].PutValue("Month");
                sheet.Cells["B1"].PutValue("Sales");
                sheet.Cells["A2"].PutValue("Jan");
                sheet.Cells["B2"].PutValue(1200);
                sheet.Cells["A3"].PutValue("Feb");
                sheet.Cells["B3"].PutValue(1500);
                sheet.Cells["A4"].PutValue("Mar");
                sheet.Cells["B4"].PutValue(1800);

                // Add a simple column chart
                int chartIndex = sheet.Charts.Add(ChartType.Column, 5, 0, 20, 10);
                Chart chart = sheet.Charts[chartIndex];
                chart.NSeries.Add("B2:B4", true);
                // Category data assignment is optional; omitted to avoid compatibility issues
                chart.Title.Text = "Quarterly Sales";

                // Configure HTML save options (fallback when MHTML options are unavailable)
                HtmlSaveOptions saveOptions = new HtmlSaveOptions(SaveFormat.Html)
                {
                    // Export the workbook as a single HTML file
                    ExportActiveWorksheetOnly = true
                };

                // Save the workbook as HTML (can be opened in browsers)
                string outputPath = "SampleOutput.html";
                workbook.Save(outputPath, saveOptions);

                Console.WriteLine($"HTML file saved to '{outputPath}'. Open it in a browser to verify rendering.");
            }
            catch (Exception ex)
            {
                Console.WriteLine($"An error occurred: {ex.Message}");
            }
        }
    }
}
