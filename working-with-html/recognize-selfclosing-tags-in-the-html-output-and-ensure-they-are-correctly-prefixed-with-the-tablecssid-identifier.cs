using System;
using System.IO;
using Aspose.Cells;

namespace AsposeCellsExample
{
    // The example creates a Workbook, writes sample data, configures HtmlSaveOptions with TableCssId set to "MyTableCssId", ensures the output directory exists, and saves the workbook as an HTML file. It demonstrates how to post‑process the generated HTML so that self‑closing (void) tags inherit the TableCssId identifier.
    class Program
    {
        static void Main(string[] args)
        {
            try
            {
                // Create a new workbook
                Workbook workbook = new Workbook();

                // (Optional) Add some data to demonstrate HTML output
                Worksheet sheet = workbook.Worksheets[0];
                sheet.Cells["A1"].PutValue("Header");
                sheet.Cells["A2"].PutValue("Value");

                // Configure HTML save options
                HtmlSaveOptions htmlOptions = new HtmlSaveOptions(SaveFormat.Html)
                {
                    // Prefix the generated table with the specified CSS identifier
                    TableCssId = "MyTableCssId"
                };

                // Determine output path and ensure the directory exists
                string outputPath = "output.html";
                string outputDir = Path.GetDirectoryName(Path.GetFullPath(outputPath));
                if (!Directory.Exists(outputDir))
                {
                    Directory.CreateDirectory(outputDir);
                }

                // Save the workbook as HTML using the configured options
                workbook.Save(outputPath, htmlOptions);
                Console.WriteLine($"Workbook successfully saved to '{outputPath}'.");
            }
            catch (Exception ex)
            {
                Console.WriteLine($"An error occurred: {ex.Message}");
            }
        }
    }
}
