using System;
using Aspose.Cells;
using Aspose.Cells.Tables;

// The example creates a workbook, fills it with sample data, adds a ListObject covering a range, assigns a display name that becomes the TableCssId, applies a built‑in table style, configures HtmlSaveOptions to export gridlines, and saves the workbook as an HTML file.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook
            Workbook workbook = new Workbook();

            // Get the first worksheet
            Worksheet sheet = workbook.Worksheets[0];

            // Populate sample data
            sheet.Cells["A1"].PutValue("Name");
            sheet.Cells["B1"].PutValue("Age");
            sheet.Cells["A2"].PutValue("John");
            sheet.Cells["B2"].PutValue(30);
            sheet.Cells["A3"].PutValue("Alice");
            sheet.Cells["B3"].PutValue(25);

            // Add a table (ListObject) covering the range A1:B3
            int firstRow = 0;        // zero‑based index for row 1
            int firstColumn = 0;     // zero‑based index for column A
            int totalRows = 3;       // rows A1:B3 inclusive
            int totalColumns = 2;

            int tableIndex = sheet.ListObjects.Add(
                firstRow,
                firstColumn,
                firstRow + totalRows - 1,
                firstColumn + totalColumns - 1,
                true);

            ListObject table = sheet.ListObjects[tableIndex];

            // Assign a display name to the table (used as CSS id in HTML)
            table.DisplayName = "myTable";

            // Optionally set a built‑in table style
            table.TableStyleType = TableStyleType.TableStyleMedium2;

            // Configure HTML save options to enable gridlines
            HtmlSaveOptions htmlOptions = new HtmlSaveOptions(SaveFormat.Html)
            {
                ExportGridLines = true // Show gridlines in the exported HTML
            };

            // Save the workbook as HTML with the specified options
            workbook.Save("output.html", htmlOptions);
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error: {ex.Message}");
        }
    }
}
