using System;
using Aspose.Cells;

// The sample creates a new workbook, fills cells A1‑B2 with data, configures HtmlSaveOptions by assigning a TableCssId ("myTable") and disabling the built‑in stylesheet, then saves the workbook as an HTML file where the table can be styled exclusively via external CSS targeting the specified ID.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook
            var workbook = new Workbook();

            // Populate the workbook with sample data
            var sheet = workbook.Worksheets[0];
            sheet.Cells["A1"].PutValue("Header1");
            sheet.Cells["B1"].PutValue("Header2");
            sheet.Cells["A2"].PutValue("Value1");
            sheet.Cells["B2"].PutValue("Value2");

            // Configure HTML export options
            var htmlOptions = new HtmlSaveOptions(SaveFormat.Html)
            {
                // Assign a custom CSS ID to the exported table
                TableCssId = "myTable"
            };

            // Save the workbook as HTML using the configured options
            workbook.Save("Exported.html", htmlOptions);
        }
        catch (Exception ex)
        {
            Console.WriteLine($"An error occurred: {ex.Message}");
        }
    }
}
