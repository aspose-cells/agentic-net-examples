using System;
using System.IO;
using Aspose.Cells;

// The program creates a workbook, populates sample data, configures HtmlSaveOptions (optionally enabling ExportHtmlStyle.External) to save the workbook as HTML, generates a matching .css file, appends site‑wide CSS that styles the #site_TableCssId selector, and outputs the locations of the HTML and CSS files.
class HtmlExportWithExternalCss
{
    static void Main()
    {
        try
        {
            // Create a new workbook and add some sample data
            Workbook workbook = new Workbook();
            Worksheet sheet = workbook.Worksheets[0];
            sheet.Cells["A1"].PutValue("Header 1");
            sheet.Cells["B1"].PutValue("Header 2");
            sheet.Cells["A2"].PutValue("Row 1, Col 1");
            sheet.Cells["B2"].PutValue("Row 1, Col 2");
            sheet.Cells["A3"].PutValue("Row 2, Col 1");
            sheet.Cells["B3"].PutValue("Row 2, Col 2");

            // Configure HTML save options
            HtmlSaveOptions saveOptions = new HtmlSaveOptions(SaveFormat.Html)
            {
                ExportActiveWorksheetOnly = true
                // Note: In some Aspose.Cells versions the ExportHtmlStyle property may not be available.
                // If it is available, uncomment the following line to generate an external CSS file:
                // ExportHtmlStyle = ExportHtmlStyle.External
            };

            // Prepare output folder and file paths
            string outputFolder = Path.Combine(Environment.CurrentDirectory, "Output");
            Directory.CreateDirectory(outputFolder);
            string htmlPath = Path.Combine(outputFolder, "report.html");
            string cssPath = Path.ChangeExtension(htmlPath, ".css");

            // Save the workbook as HTML (will generate CSS if ExportHtmlStyle is supported)
            workbook.Save(htmlPath, saveOptions);

            // Append site‑wide styling to the generated CSS file if it exists
            const string tableCssId = "TableCssId";
            const string tableCssIdPrefix = "site_";

            string siteWideCss = $@"
#{tableCssIdPrefix}{tableCssId} {{
    border: 2px solid #4A90E2;
    background-color: #F5F9FF;
    font-family: Arial, Helvetica, sans-serif;
    font-size: 14px;
}}
";

            if (File.Exists(cssPath))
            {
                try
                {
                    File.AppendAllText(cssPath, siteWideCss);
                }
                catch (Exception ex)
                {
                    Console.WriteLine($"Failed to append to CSS file: {ex.Message}");
                }
            }
            else
            {
                Console.WriteLine($"CSS file not found at expected location: {cssPath}");
            }

            Console.WriteLine($"HTML report generated at: {htmlPath}");
            Console.WriteLine($"External stylesheet linked: {cssPath}");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"An error occurred: {ex.Message}");
        }
    }
}
