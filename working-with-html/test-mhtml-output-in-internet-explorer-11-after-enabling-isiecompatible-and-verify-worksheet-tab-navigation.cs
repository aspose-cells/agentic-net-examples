using System;
using System.IO;
using Aspose.Cells;

namespace AsposeCellsMhtmlTest
{
    // The sample creates a Workbook with three worksheets, fills cells with text, numbers, dates, and a formula, then uses HtmlSaveOptions to enable IE11 compatibility, embed images as Base64, and export the entire workbook. It saves the result as a .mhtml file, reads the file to verify that worksheet‑tab navigation markup is present, and prompts the user to open the file in Internet Explorer 11 to confirm correct rendering and clickable tabs.
    class Program
    {
        static void Main(string[] args)
        {
            // Path for the generated MHTML (HTML) file
            const string outputFile = "WorkbookOutput.mhtml";

            // -----------------------------------------------------------------
            // 1. Create a workbook with multiple worksheets and sample data
            // -----------------------------------------------------------------
            Workbook workbook = new Workbook();

            // Worksheet 1
            Worksheet sheet1 = workbook.Worksheets[0];
            sheet1.Name = "FirstSheet";
            sheet1.Cells["A1"].PutValue("First Sheet - Cell A1");
            sheet1.Cells["B2"].PutValue(123);

            // Worksheet 2
            int sheet2Index = workbook.Worksheets.Add();
            Worksheet sheet2 = workbook.Worksheets[sheet2Index];
            sheet2.Name = "SecondSheet";
            sheet2.Cells["A1"].PutValue("Second Sheet - Cell A1");
            // Set formula (PutFormula is not available; use Formula property)
            sheet2.Cells["C3"].Formula = "=SUM(1,2,3)";

            // Worksheet 3
            int sheet3Index = workbook.Worksheets.Add();
            Worksheet sheet3 = workbook.Worksheets[sheet3Index];
            sheet3.Name = "ThirdSheet";
            sheet3.Cells["A1"].PutValue(DateTime.Now);
            sheet3.Cells["B1"].PutValue("Some text");

            // -----------------------------------------------------------------
            // 2. Configure HtmlSaveOptions for MHTML-like output
            // -----------------------------------------------------------------
            HtmlSaveOptions htmlOptions = new HtmlSaveOptions(SaveFormat.Html)
            {
                // Enable IE11 compatibility mode
                IsIECompatible = true,

                // Export images as Base64 to keep everything inside the file
                ExportImagesAsBase64 = true,

                // Export the whole workbook (not only the active sheet)
                ExportActiveWorksheetOnly = false
            };

            // -----------------------------------------------------------------
            // 3. Save the workbook as HTML (using .mhtml extension)
            // -----------------------------------------------------------------
            try
            {
                workbook.Save(outputFile, htmlOptions);
                Console.WriteLine($"MHTML-like file saved successfully to '{outputFile}'.");
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Error while saving MHTML-like file: {ex.Message}");
                return;
            }

            // -----------------------------------------------------------------
            // 4. Verify that worksheet tab navigation markup exists
            // -----------------------------------------------------------------
            try
            {
                if (!File.Exists(outputFile))
                {
                    Console.WriteLine($"Error: Output file '{outputFile}' was not found.");
                    return;
                }

                string mhtmlContent = File.ReadAllText(outputFile);

                // Look for known navigation tokens generated by Aspose.Cells
                bool navigationFound = mhtmlContent.Contains("AsposeTabs") ||
                                        mhtmlContent.Contains("WorksheetTabs") ||
                                        mhtmlContent.Contains("sheetTabs");

                if (navigationFound)
                {
                    Console.WriteLine("Worksheet tab navigation markup detected in the MHTML output.");
                }
                else
                {
                    Console.WriteLine("WARNING: Worksheet tab navigation markup NOT found in the MHTML output.");
                }
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Error while verifying MHTML content: {ex.Message}");
            }

            // -----------------------------------------------------------------
            // 5. Inform the user about IE11 testing
            // -----------------------------------------------------------------
            Console.WriteLine("\nTo complete the test, open the generated MHTML file in Internet Explorer 11.");
            Console.WriteLine("Verify that:");
            Console.WriteLine("  • The page renders correctly without layout issues.");
            Console.WriteLine("  • The worksheet tabs are clickable and switch the displayed sheet.");
            Console.WriteLine("Press any key to exit.");
            Console.ReadKey();
        }
    }
}
