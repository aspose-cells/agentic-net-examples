using System;
using System.IO;
using Aspose.Cells;

namespace AsposeCellsCommentExport
{
    // The sample creates a new Workbook, inserts a comment into cell A1, configures HtmlSaveOptions with IsExportComments enabled, saves the workbook as an HTML file, and then reads the HTML to confirm that the comment text is present.
    class Program
    {
        static void Main(string[] args)
        {
            // Define file names (in the current directory)
            string workbookPath = "CommentExportDemo.xlsx";
            string htmlPath = "CommentExportDemo.html";

            // Ensure any previous files are removed
            try
            {
                if (File.Exists(workbookPath)) File.Delete(workbookPath);
                if (File.Exists(htmlPath)) File.Delete(htmlPath);
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Error cleaning up previous files: {ex.Message}");
                return;
            }

            try
            {
                // 1. Create a new workbook and get the first worksheet
                using (Workbook workbook = new Workbook())
                {
                    Worksheet sheet = workbook.Worksheets[0];
                    sheet.Name = "DemoSheet";

                    // 2. Put some data into a cell (optional, just for context)
                    sheet.Cells["A1"].PutValue("Hello World");

                    // 3. Add a comment to cell A1
                    int commentIndex = sheet.Comments.Add("A1");
                    sheet.Comments[commentIndex].Note = "This is a test comment added programmatically.";

                    // 4. Save the workbook as an Excel file (optional, just to show the workbook can be saved)
                    workbook.Save(workbookPath, SaveFormat.Xlsx);

                    // 5. Prepare HTML save options and enable comment export
                    HtmlSaveOptions htmlOptions = new HtmlSaveOptions
                    {
                        IsExportComments = true,               // Export comments to HTML
                        ExportActiveWorksheetOnly = true       // Export only the active sheet for simplicity
                    };

                    // 6. Save the workbook to HTML using the options
                    workbook.Save(htmlPath, htmlOptions);
                }

                // 7. Verify that the comment appears in the generated HTML
                if (File.Exists(htmlPath))
                {
                    string htmlContent = File.ReadAllText(htmlPath);
                    string expectedComment = "This is a test comment added programmatically.";

                    if (htmlContent.Contains(expectedComment))
                    {
                        Console.WriteLine("SUCCESS: Comment was found in the exported HTML file.");
                    }
                    else
                    {
                        Console.WriteLine("FAILURE: Comment was NOT found in the exported HTML file.");
                    }
                }
                else
                {
                    Console.WriteLine("ERROR: HTML file was not created.");
                }
            }
            catch (Exception ex)
            {
                Console.WriteLine($"ERROR during processing: {ex.Message}");
            }

            // 8. Clean up (optional)
            // Uncomment the following lines if you want to delete the generated files after verification
            // try
            // {
