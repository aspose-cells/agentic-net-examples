using System;
using Aspose.Cells;

class Program
{
    static void Main()
    {
        // Load an existing workbook from file
        Workbook workbook = new Workbook("input.xlsx");

        // Access the first worksheet (or any desired worksheet)
        Worksheet worksheet = workbook.Worksheets[0];

        // Enable gridlines visibility in the worksheet
        worksheet.IsGridlinesVisible = true;

        // Set up HTML save options to export gridlines
        HtmlSaveOptions htmlOptions = new HtmlSaveOptions
        {
            ExportGridLines = true,               // Export the gridlines to HTML
            ExportActiveWorksheetOnly = true      // Export only the active worksheet
        };

        // Save the workbook as an HTML file with gridlines displayed
        workbook.Save("output.html", htmlOptions);
    }
}

