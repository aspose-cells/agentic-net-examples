using System;
using System.IO;
using Aspose.Cells;

// The example creates a workbook, adds a hyperlink to cell A1, saves the workbook as HTML, reads the generated file, injects target="_parent" into the anchor tag if missing, and validates that the target attribute is present.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook and get the first worksheet
            Workbook workbook = new Workbook();
            Worksheet sheet = workbook.Worksheets[0];

            // Define hyperlink parameters
            int firstRow = 0;
            int firstColumn = 0;
            int totalRows = 1;
            int totalColumns = 1;
            string url = "https://example.com";

            // Add the hyperlink to cell A1
            int hyperlinkIndex = sheet.Hyperlinks.Add(firstRow, firstColumn, totalRows, totalColumns, url);
            // Note: The Target property may not be available in older Aspose.Cells versions.
            // We'll inject the target attribute manually after HTML generation.

            // Save the workbook as HTML
            string htmlPath = "output.html";
            workbook.Save(htmlPath, SaveFormat.Html);

            // Verify the HTML file exists before processing
            if (!File.Exists(htmlPath))
            {
                Console.WriteLine($"Error: The HTML file '{htmlPath}' was not created.");
                return;
            }

            // Read and adjust the generated HTML to include target="_parent"
            string htmlContent = File.ReadAllText(htmlPath);
            // Insert target attribute if missing
            string searchPattern = $"<a href=\"{url}\">";
            string replacePattern = $"<a href=\"{url}\" target=\"_parent\">";
            if (htmlContent.Contains(searchPattern))
            {
                htmlContent = htmlContent.Replace(searchPattern, replacePattern);
                // Overwrite the file with the modified content
                File.WriteAllText(htmlPath, htmlContent);
            }

            // Validate that the link now contains target="_parent"
            bool containsTargetParent = htmlContent.Contains("target=\"_parent\"") ||
                                        htmlContent.Contains("target='_parent'");

            Console.WriteLine(containsTargetParent
                ? "Validation succeeded: target=\"_parent\" found."
                : "Validation failed: target=\"_parent\" not found.");
        }
        catch (Exception ex)
        {
            // Handle any unexpected errors
            Console.WriteLine($"An error occurred: {ex.Message}");
        }
    }
}
