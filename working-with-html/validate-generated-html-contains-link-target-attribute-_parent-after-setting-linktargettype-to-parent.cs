using System;
using System.IO;
using System.Text.RegularExpressions;
using Aspose.Cells;

// C# sample that creates a workbook, adds a hyperlink, sets HtmlSaveOptions.LinkTargetType to Parent, saves as HTML, reads the file and uses a regex to confirm the <a> tag contains target="_parent". Ideal for automated verification of Aspose.Cells HTML output.
class HtmlLinkTargetValidation
{
    static void Main()
    {
        // Create a new workbook and get the first worksheet
        Workbook workbook = new Workbook();
        Worksheet sheet = workbook.Worksheets[0];

        // Put some text in a cell and add a hyperlink to it
        sheet.Cells["A1"].PutValue("Visit Aspose");
        sheet.Hyperlinks.Add("A1", 1, 1, "https://www.aspose.com");

        // Configure HTML save options to use the Parent target type
        HtmlSaveOptions saveOptions = new HtmlSaveOptions();
        saveOptions.LinkTargetType = HtmlLinkTargetType.Parent; // target="_parent"

        // Define the output HTML file path
        string htmlPath = "LinkTargetParent.html";

        // Save the workbook as HTML using the configured options
        workbook.Save(htmlPath, saveOptions);

        // Read the generated HTML content
        string htmlContent = File.ReadAllText(htmlPath);

        // Use a regular expression to find the <a> tag and its target attribute
        // This pattern looks for <a ... target="_parent" ...>
        bool containsParentTarget = Regex.IsMatch(
            htmlContent,
            @"<a\s+[^>]*target\s*=\s*[""']_parent[""']",
            RegexOptions.IgnoreCase);

        // Output the validation result
        if (containsParentTarget)
        {
            Console.WriteLine("Validation succeeded: HTML contains target=\"_parent\".");
        }
        else
        {
            Console.WriteLine("Validation failed: target=\"_parent\" not found in the HTML.");
        }
    }
}
