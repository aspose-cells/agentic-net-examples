using System;
using System.Collections.Generic;
using System.IO;
using System.Text.RegularExpressions;
using Aspose.Cells;

// The sample creates a workbook, inserts the same PNG image twice, saves it to a single HTML file with ExportImagesAsBase64 and EnableCssCustomProperties enabled, reads the generated HTML, extracts all data:image Base64 strings using regular expressions, counts total <img> tags and distinct Base64 payloads, and reports success when only one unique Base64 string is present despite multiple image tags.
class Program
{
    static void Main()
    {
        try
        {
            // -----------------------------------------------------------------
            // 1. Prepare a workbook with two identical images inserted.
            // -----------------------------------------------------------------
            var workbook = new Workbook();
            var worksheet = workbook.Worksheets[0];

            // Create a simple 1x1 red PNG image from a base64 string.
            byte[] pngBytes = Convert.FromBase64String(
                "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAIAAACQd1PeAAAADUlEQVR42mP8z/C/HwAFgwJ/lcX6WQAAAABJRU5ErkJggg==");
            using (var imgStream = new MemoryStream(pngBytes))
            {
                // Insert the same image twice (A1 and B1).
                worksheet.Pictures.Add(0, 0, imgStream);
                imgStream.Position = 0; // reset for second use
                worksheet.Pictures.Add(0, 5, imgStream);
            }

            // -----------------------------------------------------------------
            // 2. Save the workbook to HTML with EnableCssCustomProperties = true.
            // -----------------------------------------------------------------
            var htmlOptions = new HtmlSaveOptions(SaveFormat.Html)
            {
                // Export images as Base64 strings.
                ExportImagesAsBase64 = true,
                // Enable CSS custom properties – this is the feature we are testing.
                EnableCssCustomProperties = true,
                // Keep everything in a single file for easier analysis.
                ExportWorksheetCSSSeparately = false
            };

            const string htmlFilePath = "dedup_test.html";
            workbook.Save(htmlFilePath, htmlOptions);
            Console.WriteLine($"Workbook saved to HTML: {htmlFilePath}");

            // -----------------------------------------------------------------
            // 3. Load the generated HTML and analyse Base64 image strings.
            // -----------------------------------------------------------------
            if (!File.Exists(htmlFilePath))
                throw new FileNotFoundException("Generated HTML file not found.", htmlFilePath);

            string htmlContent = File.ReadAllText(htmlFilePath);

            // Regex to capture data:image/...;base64,XXXXX
            var base64Regex = new Regex(@"data:image\/[a-zA-Z]+;base64,([A-Za-z0-9+/=]+)", RegexOptions.Compiled);
            var matches = base64Regex.Matches(htmlContent);

            var distinctBase64 = new HashSet<string>();
            foreach (Match m in matches)
            {
                // Group 1 contains the pure Base64 payload.
                distinctBase64.Add(m.Groups[1].Value);
            }

            Console.WriteLine($"Total <img> tags with Base64 data: {matches.Count}");
            Console.WriteLine($"Distinct Base64 image strings found: {distinctBase64.Count}");

            // -----------------------------------------------------------------
            // 4. Verify deduplication.
            // -----------------------------------------------------------------
            if (distinctBase64.Count == 1 && matches.Count > 1)
            {
                Console.WriteLine("SUCCESS: Base64 image strings are deduplicated when EnableCssCustomProperties is true.");
            }
            else if (matches.Count == 0)
            {
                Console.WriteLine("WARNING: No Base64 images were found in the HTML output.");
            }
            else
            {
                Console.WriteLine("FAILURE: Base64 image strings were not deduplicated.");
            }

            // -----------------------------------------------------------------
            // 5. (Optional) Show the CSS custom property that holds the image.
            // -----------------------------------------------------------------
            var cssVarRegex = new Regex(@"--asp-image-\d+\s*:\s*url\(['""]?(data:image\/[a-zA-Z]+;base64,[A-Za-z0-9+/=]+)['""]?\)", RegexOptions.Compiled);
            var cssMatches = cssVarRegex.Matches(htmlContent);
            Console.WriteLine($"CSS custom properties containing images: {cssMatches.Count}");
            foreach (Match cm in cssMatches)
            {
                Console.WriteLine($"  {cm.Value.Trim()}");
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine($"An error occurred: {ex.Message}");
        }
    }
}
