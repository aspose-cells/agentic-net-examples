// Load an existing workbook (replace with your actual file path)
var workbook = new Aspose.Cells.Workbook("input.xlsx");

// Configure HTML save options to disable downlevel revealed comments
var htmlOptions = new Aspose.Cells.HtmlSaveOptions(Aspose.Cells.SaveFormat.Html);
htmlOptions.DisableDownlevelRevealedComments = true; // Improves compatibility with older browsers

// Save the workbook as HTML using the configured options
workbook.Save("output.html", htmlOptions);
