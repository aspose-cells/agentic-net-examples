using System;
using System.IO;
using System.Text;
using System.Reflection;
using Aspose.Cells;

// The example creates a workbook with very large and very small numeric values, exports it to HTML twice—once with default settings and once with the ExportExponentialNotation flag set to false via reflection—and then compares the two HTML outputs, indicating whether they match and printing any differing lines.
class HtmlExportComparison
{
    static void Main()
    {
        try
        {
            // Create a new workbook and add sample data that may be displayed in exponential notation
            Workbook workbook = new Workbook();
            Worksheet sheet = workbook.Worksheets[0];

            // Large and small numbers to trigger exponential format
            sheet.Cells["A1"].PutValue(123456789012345);
            sheet.Cells["A2"].PutValue(0.00000012345);
            sheet.Cells["A3"].PutValue(12345);
            sheet.Cells["A4"].PutValue(0.12345);

            // Export HTML with default settings (exponential notation may be used)
            string defaultHtml;
            using (MemoryStream defaultStream = new MemoryStream())
            {
                HtmlSaveOptions defaultOptions = new HtmlSaveOptions(SaveFormat.Html);
                workbook.Save(defaultStream, defaultOptions);
                defaultHtml = Encoding.UTF8.GetString(defaultStream.ToArray());
            }

            // Export HTML with exponential notation suppression (if the property exists)
            string suppressedHtml;
            using (MemoryStream suppressedStream = new MemoryStream())
            {
                HtmlSaveOptions suppressedOptions = new HtmlSaveOptions(SaveFormat.Html);

                // Attempt to set ExportExponentialNotation via reflection to maintain compatibility
                PropertyInfo expProp = typeof(HtmlSaveOptions).GetProperty("ExportExponentialNotation");
                if (expProp != null && expProp.CanWrite)
                {
                    expProp.SetValue(suppressedOptions, false);
                }

                workbook.Save(suppressedStream, suppressedOptions);
                suppressedHtml = Encoding.UTF8.GetString(suppressedStream.ToArray());
            }

            // Simple comparison: check if the two HTML outputs differ
            bool areEqual = string.Equals(defaultHtml, suppressedHtml, StringComparison.Ordinal);
            Console.WriteLine("Are the HTML outputs identical? " + areEqual);

            // If they differ, display a brief diff snippet for each differing line
            if (!areEqual)
            {
                Console.WriteLine("\n--- Differences ---");
                string[] defaultLines = defaultHtml.Split(new[] { "\r\n", "\n" }, StringSplitOptions.None);
                string[] suppressedLines = suppressedHtml.Split(new[] { "\r\n", "\n" }, StringSplitOptions.None);
                int maxLines = Math.Max(defaultLines.Length, suppressedLines.Length);
                for (int i = 0; i < maxLines; i++)
                {
                    string dLine = i < defaultLines.Length ? defaultLines[i] : "";
                    string sLine = i < suppressedLines.Length ? suppressedLines[i] : "";
                    if (!dLine.Equals(sLine, StringComparison.Ordinal))
                    {
                        Console.WriteLine($"Line {i + 1} (Default):   {dLine}");
                        Console.WriteLine($"Line {i + 1} (Suppressed): {sLine}");
                    }
                }
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine("An error occurred: " + ex.Message);
        }
    }
}
