using System;
using System.IO;
using System.Text.RegularExpressions;
using Aspose.Cells;
using Aspose.Cells.Drawing;

// Creates a workbook, adds WordArt with a gradient fill, saves it as HTML with external CSS (ExportWorksheetCSSSeparately, ExcludeUnusedStyles), then finds the *_files folder and minifies each CSS file by stripping comments and excess whitespace.
class Program
{
    static void Main()
    {
        // Create a new workbook (lifecycle: create)
        Workbook workbook = new Workbook();

        // Access the first worksheet
        Worksheet worksheet = workbook.Worksheets[0];

        // Add a WordArt shape with a gradient fill (preset style 6)
        // Parameters: style, text, upperLeftRow, top, upperLeftColumn, left, height, width
        Shape wordArt = worksheet.Shapes.AddWordArt(
            PresetWordArtStyle.WordArtStyle6,
            "Gradient WordArt",
            2, 0, 2, 0, 100, 400);

        // Configure HTML save options to export CSS separately
        HtmlSaveOptions htmlOptions = new HtmlSaveOptions();
        htmlOptions.ExportWorksheetCSSSeparately = true;   // generate a separate CSS file
        htmlOptions.ExcludeUnusedStyles = true;           // reduce size by removing unused styles

        // Define output HTML file path
        string htmlPath = "WordArt.html";

        // Save the workbook as HTML (lifecycle: save)
        workbook.Save(htmlPath, htmlOptions);

        // After saving, locate the folder that contains the generated CSS files.
        // Aspose creates a folder named "<htmlFileName>_files" next to the HTML file.
        string cssFolder = Path.Combine(
            Path.GetDirectoryName(htmlPath) ?? "",
            Path.GetFileNameWithoutExtension(htmlPath) + "_files");

        if (Directory.Exists(cssFolder))
        {
            // Minify each CSS file found in the folder.
            foreach (string cssFile in Directory.GetFiles(cssFolder, "*.css"))
            {
                string cssContent = File.ReadAllText(cssFile);

                // Remove CSS comments.
                string minified = Regex.Replace(cssContent, @"/\*.*?\*/", string.Empty, RegexOptions.Singleline);
                // Collapse whitespace (spaces, tabs, newlines) into a single space.
                minified = Regex.Replace(minified, @"\s+", " ");
                // Remove spaces before/after braces, colons, and semicolons for tighter output.
                minified = minified.Replace(" {", "{")
                                   .Replace("{ ", "{")
                                   .Replace("; ", ";")
                                   .Replace(": ", ":")
                                   .Trim();

                // Overwrite the original CSS file with the minified version.
                File.WriteAllText(cssFile, minified);
            }
        }

        Console.WriteLine("HTML file and minified CSS have been generated.");
    }
}
