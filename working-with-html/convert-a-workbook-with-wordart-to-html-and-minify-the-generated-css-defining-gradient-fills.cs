using System;
using System.IO;
using System.Text;
using System.Text.RegularExpressions;
using Aspose.Cells;

// The sample verifies the input .xlsx file, loads it with Aspose.Cells, and saves the workbook to HTML using HtmlSaveOptions that embed all images (including WordArt) as base64. The HTML is captured in a MemoryStream, the <style> block is extracted via regex, and the CSS is minified by removing comments, collapsing whitespace, and trimming spaces around symbols. The minified style tag replaces the original, and the final HTML is written to a UTF‑8 file with comprehensive error handling.
class WordArtToHtmlConverter
{
    static void Main()
    {
        const string inputPath = "input.xlsx";
        const string outputPath = "output.html";

        try
        {
            // Verify that the input workbook exists.
            if (!File.Exists(inputPath))
                throw new FileNotFoundException($"Input file not found: {inputPath}");

            // Load the workbook that contains WordArt.
            Workbook workbook = new Workbook(inputPath);

            // Configure HTML save options.
            HtmlSaveOptions htmlOptions = new HtmlSaveOptions
            {
                ExportActiveWorksheetOnly = false, // Export all worksheets.
                ExportImagesAsBase64 = true        // Embed images (including WordArt) as base64.
                // ExportWordArt and CssStyleSheetType are not required / not available in this version.
            };

            // Save the workbook to a memory stream to capture the HTML as a string.
            using (MemoryStream htmlStream = new MemoryStream())
            {
                workbook.Save(htmlStream, htmlOptions);
                htmlStream.Position = 0;
                string htmlContent = new StreamReader(htmlStream).ReadToEnd();

                // Extract the <style> block that contains the generated CSS.
                string pattern = @"<style[^>]*>(.*?)</style>";
                Match styleMatch = Regex.Match(htmlContent, pattern, RegexOptions.Singleline | RegexOptions.IgnoreCase);

                if (styleMatch.Success)
                {
                    string originalCss = styleMatch.Groups[1].Value;

                    // Minify the CSS.
                    string minifiedCss = Regex.Replace(originalCss, @"/\*.*?\*/", string.Empty, RegexOptions.Singleline); // Remove comments
                    minifiedCss = Regex.Replace(minifiedCss, @"\s+", " ");                                         // Collapse whitespace
                    minifiedCss = Regex.Replace(minifiedCss, @"\s*([{}:;,>])\s*", "$1");                         // Remove spaces around symbols
                    minifiedCss = minifiedCss.Trim();

                    // Replace the original CSS block with the minified version.
                    string minifiedStyleTag = $"<style>{minifiedCss}</style>";
                    htmlContent = Regex.Replace(htmlContent, pattern, minifiedStyleTag, RegexOptions.Singleline | RegexOptions.IgnoreCase);
                }

                // Write the final HTML to a file.
                File.WriteAllText(outputPath, htmlContent, Encoding.UTF8);
            }

            Console.WriteLine($"Conversion completed. HTML with minified CSS saved to {outputPath}");
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}
