using System;
using System.Diagnostics;
using System.IO;
using Aspose.Cells;
using Aspose.Cells.Rendering;

// The sample loads an Excel workbook and uses a Stopwatch to time two HTML exports with Aspose.Cells: one with default CSS generation and another with the DisableCss flag set, reporting the elapsed milliseconds for each rendering operation.
class Program
{
    static void Main()
    {
        // Load the workbook (replace with your actual file path)
        Workbook workbook = new Workbook("input.xlsx");

        // Stopwatch for measuring rendering time
        Stopwatch stopwatch = new Stopwatch();

        // ---------- Render HTML with CSS enabled (default) ----------
        HtmlSaveOptions optionsCssEnabled = new HtmlSaveOptions(SaveFormat.Html);
        // CSS is generated by default, no additional settings required

        using (MemoryStream ms = new MemoryStream())
        {
            stopwatch.Start();
            workbook.Save(ms, optionsCssEnabled);
            stopwatch.Stop();

            Console.WriteLine($"HTML rendering with CSS enabled: {stopwatch.ElapsedMilliseconds} ms");
        }

        // ---------- Render HTML with CSS disabled ----------
        HtmlSaveOptions optionsCssDisabled = new HtmlSaveOptions(SaveFormat.Html);
        // Disable CSS generation to compare performance
        optionsCssDisabled.DisableCss = true; // Aspose.Cells property to turn off CSS

        using (MemoryStream ms = new MemoryStream())
        {
            stopwatch.Reset();
            stopwatch.Start();
            workbook.Save(ms, optionsCssDisabled);
            stopwatch.Stop();

            Console.WriteLine($"HTML rendering with CSS disabled: {stopwatch.ElapsedMilliseconds} ms");
        }
    }
}
