using System;
using System.IO;
using System.Text;
using Aspose.Cells;

// The example creates a workbook with a visible and a hidden worksheet, enables HtmlSaveOptions.ExportHiddenWorksheet, saves the workbook to a memory stream as HTML, checks that the hidden sheet's data is present in the HTML, logs the verification result, and writes the HTML to a file.
class Program
{
    static void Main()
    {
        // Create a new workbook
        Workbook workbook = new Workbook();

        // Get the default (first) worksheet and add visible data
        Worksheet visibleSheet = workbook.Worksheets[0];
        visibleSheet.Name = "VisibleSheet";
        visibleSheet.Cells["A1"].PutValue("Visible Data");

        // Add a second worksheet, hide it, and add hidden data
        Worksheet hiddenSheet = workbook.Worksheets.Add("HiddenSheet");
        hiddenSheet.Cells["A1"].PutValue("Hidden Data");
        hiddenSheet.IsVisible = false; // Hide the worksheet

        // Configure HTML save options to export hidden worksheets
        HtmlSaveOptions htmlOptions = new HtmlSaveOptions();
        htmlOptions.ExportHiddenWorksheet = true;

        // Save the workbook to a memory stream as HTML
        using (MemoryStream htmlStream = new MemoryStream())
        {
            workbook.Save(htmlStream, htmlOptions);
            string htmlContent = Encoding.UTF8.GetString(htmlStream.ToArray());

            // Verify that the hidden sheet's data appears in the generated HTML
            bool hiddenDataIncluded = htmlContent.Contains("Hidden Data");
            Console.WriteLine("Hidden sheet included in HTML: " + hiddenDataIncluded);

            // Optionally write the HTML to a file for inspection
            File.WriteAllText("output.html", htmlContent);
        }
    }
}
