using System;
using System.IO;
using Aspose.Cells;

namespace AsposeCellsHtmlCommentCheck
{
    // Creates a workbook, adds a comment to cell A1, sets HtmlSaveOptions.DisableDownlevelRevealedComments = true, saves as HTML, reads the file, and confirms that no conditional comment syntax (e.g., <![if …]> or <!--[if …]><!-->) is present. Ideal for clean, cross‑browser HTML output.
    class Program
    {
        static void Main()
        {
            // 1. Create a new workbook and add a comment to cell A1
            Workbook workbook = new Workbook();
            Worksheet sheet = workbook.Worksheets[0];
            int commentIndex = sheet.Comments.Add("A1");
            Comment comment = sheet.Comments[commentIndex];
            comment.Note = "Sample comment for HTML export";

            // 2. Configure HTML save options to disable downlevel‑revealed comments
            HtmlSaveOptions htmlOptions = new HtmlSaveOptions();
            htmlOptions.DisableDownlevelRevealedComments = true;   // ensures only standard <!-- --> comments are used
            htmlOptions.IsExportComments = true;                  // export the comment so we can verify it

            // 3. Save the workbook as HTML
            string htmlPath = "output.html";
            workbook.Save(htmlPath, htmlOptions);

            // 4. Load the generated HTML file as text
            string htmlContent = File.ReadAllText(htmlPath);

            // 5. Verify that the content does NOT contain downlevel‑revealed comment patterns
            //    Typical downlevel‑revealed syntax includes <![if ...]> or <!--[if ...]><!-->
            bool containsDownlevelRevealed = htmlContent.Contains("<![if") ||
                                            htmlContent.Contains("<!--[if");

            // 6. Output the verification result
            if (containsDownlevelRevealed)
            {
                Console.WriteLine("The HTML file contains downlevel‑revealed comments.");
            }
            else
            {
                Console.WriteLine("The HTML file contains only standard comment tags.");
            }
        }
    }
}
