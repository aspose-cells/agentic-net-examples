using System;
using System.IO;
using System.Text;
using Aspose.Cells;

// The sample builds a workbook with three bold, blue headings, enables the ExportHeadings option in HtmlSaveOptions, saves the workbook as an HTML file, and then reads the file to confirm that heading anchors (heading_1, heading_2, heading_3) and corresponding navigation links are present, reporting success or failure.
class Program
{
    static void Main()
    {
        try
        {
            // -----------------------------------------------------------------
            // 1. Prepare a workbook with multiple headings that will be exported
            //    as navigation anchors in the HTML file.
            // -----------------------------------------------------------------
            Workbook workbook = new Workbook();
            Worksheet sheet = workbook.Worksheets[0];
            Cells cells = sheet.Cells;

            // Add headings in column A
            cells["A1"].PutValue("Heading 1");
            cells["A2"].PutValue("Content under heading 1");
            cells["A5"].PutValue("Heading 2");
            cells["A6"].PutValue("Content under heading 2");
            cells["A9"].PutValue("Heading 3");
            cells["A10"].PutValue("Content under heading 3");

            // Apply a style that makes the headings look like real headings
            Style headingStyle = workbook.CreateStyle();
            headingStyle.Font.IsBold = true;
            headingStyle.Font.Size = 14;
            headingStyle.Font.Color = System.Drawing.Color.Blue;

            cells["A1"].SetStyle(headingStyle);
            cells["A5"].SetStyle(headingStyle);
            cells["A9"].SetStyle(headingStyle);

            // -----------------------------------------------------------------
            // 2. Configure HTML save options to export headings as navigation
            //    links (bookmarks). The property ExportHeadings is the key.
            // -----------------------------------------------------------------
            HtmlSaveOptions htmlOptions = new HtmlSaveOptions
            {
                ExportActiveWorksheetOnly = false, // Export the whole workbook
                ExportHeadings = true,             // Enable heading navigation (obsolete but functional)
                ExportGridLines = true,
                ExportImagesAsBase64 = true
            };

            string outputHtmlPath = Path.Combine(Directory.GetCurrentDirectory(), "ExportedWithHeadings.html");

            // Ensure the output directory exists
            string outputDir = Path.GetDirectoryName(outputHtmlPath);
            if (!Directory.Exists(outputDir))
            {
                Directory.CreateDirectory(outputDir);
            }

            // -----------------------------------------------------------------
            // 3. Save the workbook as HTML.
            // -----------------------------------------------------------------
            workbook.Save(outputHtmlPath, htmlOptions);
            Console.WriteLine($"Workbook exported to HTML: {outputHtmlPath}");

            // -----------------------------------------------------------------
            // 4. Verify that navigation anchors for the headings exist.
            // -----------------------------------------------------------------
            if (!File.Exists(outputHtmlPath))
                throw new FileNotFoundException("Exported HTML file not found.", outputHtmlPath);

            string htmlContent = File.ReadAllText(outputHtmlPath, Encoding.UTF8);

            // Expected anchor names (Aspose uses the cell value with spaces replaced by '_' and prefixed with "heading_")
            string[] expectedAnchors = { "heading_1", "heading_2", "heading_3" };
            bool allAnchorsFound = true;

            foreach (string anchor in expectedAnchors)
            {
                string pattern1 = $"name=\"{anchor}\"";
                string pattern2 = $"id=\"{anchor}\"";

                if (htmlContent.Contains(pattern1) || htmlContent.Contains(pattern2))
                {
                    Console.WriteLine($"✅ Anchor '{anchor}' found.");
                }
                else
                {
                    Console.WriteLine($"❌ Anchor '{anchor}' NOT found.");
                    allAnchorsFound = false;
                }
            }

            // -----------------------------------------------------------------
            // 5. Verify that there are navigation links (e.g., <a href="#heading_2">)
            //    that point to the anchors.
            // -----------------------------------------------------------------
            bool navigationLinksValid = true;
            for (int i = 0; i < expectedAnchors.Length - 1; i++)
            {
                string toAnchor = expectedAnchors[i + 1];
                string linkPattern = $"href=\"#{toAnchor}\"";

                if (htmlContent.Contains(linkPattern))
                {
                    Console.WriteLine($"✅ Navigation link to '{toAnchor}' exists.");
                }
                else
                {
                    Console.WriteLine($"❌ Navigation link to '{toAnchor}' missing.");
                    navigationLinksValid = false;
                }
            }

            // -----------------------------------------------------------------
            // 6. Report final result.
            // -----------------------------------------------------------------
            if (allAnchorsFound && navigationLinksValid)
            {
                Console.WriteLine("All heading navigation checks passed.");
            }
            else
            {
                Console.WriteLine("Heading navigation verification failed.");
                throw new InvalidOperationException("Exported HTML does not contain expected heading navigation.");
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error: {ex.Message}");
            // Optionally rethrow or handle specific exceptions as needed
        }
    }
}
