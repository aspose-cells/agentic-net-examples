using System;
using Aspose.Cells;

namespace RibbonButtonLoggingDemo
{
    // This example shows how to create a workbook with a custom Ribbon UI, add a large button that calls the VBA macro LogButtonAction, and embed the Ribbon XML using Aspose.Cells for .NET. The developer needs to capture the macro’s result when the button is pressed for troubleshooting.
    class Program
    {
        static void Main()
        {
            try
            {
                // Create a new workbook
                Workbook workbook = new Workbook();

                // Define custom Ribbon XML with a button linked to a macro named "LogButtonAction".
                string ribbonXml =
                    "<customUI xmlns=\"http://schemas.microsoft.com/office/2006/01/customui\">" +
                    "  <ribbon>" +
                    "    <tabs>" +
                    "      <tab id=\"customTab\" label=\"Diagnostics\">" +
                    "        <group id=\"logGroup\" label=\"Logging\">" +
                    "          <button id=\"logButton\" label=\"Run Action\" size=\"large\" onAction=\"LogButtonAction\" />" +
                    "        </group>" +
                    "      </tab>" +
                    "    </tabs>" +
                    "  </ribbon>" +
                    "</customUI>";

                // Assign the Ribbon XML to the workbook
                workbook.RibbonXml = ribbonXml;

                // Save the workbook (the Ribbon UI will be embedded)
                workbook.Save("RibbonWithLogging.xlsm");

                Console.WriteLine("Workbook created with custom Ribbon button.");
                Console.WriteLine("When the button is pressed in Excel, the macro 'LogButtonAction' should execute.");
            }
            catch (Exception ex)
            {
                // Log unexpected errors
                Console.WriteLine("An error occurred: " + ex.Message);
            }
        }
    }
}
