using Aspose.Cells;
using System;

// The example loads the merged workbook "combined.xlsx", applies full protection (structure and windows) with the password "myPassword" using Workbook.Protect(ProtectionType.All), and saves the secured file as "combined_protected.xlsx".
class Program
{
    static void Main()
    {
        // Load the merged workbook (result of the combine operation)
        Workbook workbook = new Workbook("combined.xlsx");

        // Protect the workbook with a password to restrict editing.
        // This protects the workbook's structure and windows.
        workbook.Protect(ProtectionType.All, "myPassword");

        // Save the protected workbook
        workbook.Save("combined_protected.xlsx");
    }
}
