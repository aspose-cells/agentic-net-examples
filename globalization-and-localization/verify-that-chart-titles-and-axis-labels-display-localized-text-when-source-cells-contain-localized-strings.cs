using System;
using System.IO;
using Aspose.Cells;
using Aspose.Cells.Charts;

// The sample creates a workbook, writes Spanish strings into cells, adds a column chart, assigns the chart title and axis titles from those cells, saves the file, reloads it, and verifies that the chart's title, X‑axis, and Y‑axis texts match the original localized strings, outputting the verification results.
class ChartLocalizationVerification
{
    static void Main()
    {
        try
        {
            // Create a new workbook and get the first worksheet
            Workbook workbook = new Workbook();
            Worksheet sheet = workbook.Worksheets[0];

            // Populate sample data for the chart
            sheet.Cells["B2"].PutValue(10);
            sheet.Cells["B3"].PutValue(20);
            sheet.Cells["B4"].PutValue(30);

            // Localized strings (e.g., Spanish) for title and axis labels
            string localizedTitle = "Ventas Mensuales";   // Chart title
            string localizedXLabel = "Meses";            // X‑axis title
            string localizedYLabel = "Cantidad";         // Y‑axis title

            // Write localized strings into cells (simulating source localization)
            sheet.Cells["A1"].PutValue(localizedTitle);
            sheet.Cells["A2"].PutValue(localizedXLabel);
            sheet.Cells["A3"].PutValue(localizedYLabel);

            // Add a column chart to the worksheet
            int chartIndex = sheet.Charts.Add(ChartType.Column, 5, 0, 20, 10);
            Chart chart = sheet.Charts[chartIndex];

            // Bind the chart to the data range
            chart.NSeries.Add("B2:B4", true);

            // Set chart title and axis titles using the localized cell values
            chart.Title.Text = sheet.Cells["A1"].StringValue;
            chart.CategoryAxis.Title.Text = sheet.Cells["A2"].StringValue;
            chart.ValueAxis.Title.Text = sheet.Cells["A3"].StringValue;

            // Save the workbook to a file
            string filePath = "LocalizedChart.xlsx";
            workbook.Save(filePath);

            // Reload the workbook to verify that titles retain the localized text
            if (File.Exists(filePath))
            {
                Workbook loadedWorkbook = new Workbook(filePath);
                Worksheet loadedSheet = loadedWorkbook.Worksheets[0];
                Chart loadedChart = loadedSheet.Charts[0];

                // Perform verification
                bool titleMatches = loadedChart.Title.Text == localizedTitle;
                bool xAxisMatches = loadedChart.CategoryAxis.Title.Text == localizedXLabel;
                bool yAxisMatches = loadedChart.ValueAxis.Title.Text == localizedYLabel;

                // Output verification results
                Console.WriteLine("Chart title matches localized text: " + titleMatches);
                Console.WriteLine("X‑axis title matches localized text: " + xAxisMatches);
                Console.WriteLine("Y‑axis title matches localized text: " + yAxisMatches);
            }
            else
            {
                Console.WriteLine($"Error: The file '{filePath}' was not found after saving.");
            }
        }
        catch (Exception ex)
        {
            // Output any unexpected errors
            Console.WriteLine("An error occurred: " + ex.Message);
        }
    }
}
