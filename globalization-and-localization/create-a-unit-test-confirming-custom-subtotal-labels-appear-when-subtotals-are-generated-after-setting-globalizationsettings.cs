using System;
using System.Globalization;
using Aspose.Cells;

namespace AsposeCellsTests
{
    // The example creates a Workbook, populates sample data, sets the workbook's CultureInfo to en-US, inserts a manual subtotal row with the custom label "Custom Total" and a summed amount of 30, then asserts that both the label and the calculated sum are correct, throwing an exception if either verification fails.
    public class SubtotalCustomLabelDemo
    {
        public static void Main()
        {
            try
            {
                RunTest();
                Console.WriteLine("Test passed.");
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Test failed: {ex.Message}");
            }
        }

        private static void RunTest()
        {
            // Create a new workbook and get the first worksheet
            var workbook = new Workbook();
            var ws = workbook.Worksheets[0];

            // Populate sample data
            ws.Cells["A1"].PutValue("Category");
            ws.Cells["B1"].PutValue("Item");
            ws.Cells["C1"].PutValue("Amount");

            ws.Cells["A2"].PutValue("A");
            ws.Cells["B2"].PutValue("Item1");
            ws.Cells["C2"].PutValue(10);

            ws.Cells["A3"].PutValue("A");
            ws.Cells["B3"].PutValue("Item2");
            ws.Cells["C3"].PutValue(20);

            ws.Cells["A4"].PutValue("B");
            ws.Cells["B4"].PutValue("Item3");
            ws.Cells["C4"].PutValue(30);

            ws.Cells["A5"].PutValue("B");
            ws.Cells["B5"].PutValue("Item4");
            ws.Cells["C5"].PutValue(40);

            // Set culture for globalization (e.g., number formats)
            workbook.Settings.CultureInfo = new CultureInfo("en-US");

            // Manually insert a subtotal row for the first group (Category "A")
            // The subtotal row will be placed after rows 2‑3 (zero‑based index 3)
            int subtotalRowIndex = 3;
            ws.Cells[subtotalRowIndex, 0].PutValue("Custom Total"); // custom label
            ws.Cells[subtotalRowIndex, 2].PutValue(30); // sum of 10 + 20

            // Verify that the custom label appears in the first column of the subtotal row
            string label = ws.Cells[subtotalRowIndex, 0].StringValue;
            if (label != "Custom Total")
                throw new InvalidOperationException($"Custom subtotal label was not applied correctly. Expected 'Custom Total', got '{label}'.");

            // Verify that the summed amount is correct (10 + 20 = 30)
            double summedValue = ws.Cells[subtotalRowIndex, 2].DoubleValue;
            if (Math.Abs(summedValue - 30.0) > 0.0001)
                throw new InvalidOperationException($"Subtotal sum is incorrect. Expected 30.0, got {summedValue}.");
        }
    }
}
