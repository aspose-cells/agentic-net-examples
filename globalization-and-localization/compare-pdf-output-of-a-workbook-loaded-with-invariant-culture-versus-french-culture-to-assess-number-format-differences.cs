using System;
using System.Globalization;
using System.IO;
using Aspose.Cells;

// The example loads an Excel workbook twice, assigns CultureInfo.InvariantCulture to one instance and a French (fr-FR) CultureInfo to the other via Workbook.Settings.CultureInfo, saves each as a PDF, and then performs a byte‑by‑byte comparison of the two PDF files to reveal any differences caused by locale‑specific number formatting.
class PdfCultureComparison
{
    static void Main()
    {
        // Path to the source Excel workbook
        string sourcePath = "Sample.xlsx";

        // Output PDF files for each culture
        string pdfInvariantPath = "Output_Invariant.pdf";
        string pdfFrenchPath = "Output_French.pdf";

        // Load the workbook (lifecycle rule: load)
        Workbook workbookInvariant = new Workbook(sourcePath);
        // Set culture to invariant (feature rule: culture handling)
        workbookInvariant.Settings.CultureInfo = CultureInfo.InvariantCulture;
        // Save as PDF (lifecycle rule: save)
        workbookInvariant.Save(pdfInvariantPath, SaveFormat.Pdf);

        // Load the workbook again for French culture
        Workbook workbookFrench = new Workbook(sourcePath);
        // Set culture to French (France)
        workbookFrench.Settings.CultureInfo = new CultureInfo("fr-FR");
        // Save as PDF
        workbookFrench.Save(pdfFrenchPath, SaveFormat.Pdf);

        // Compare the two PDF files byte by byte
        bool areIdentical = FilesAreEqual(pdfInvariantPath, pdfFrenchPath);

        Console.WriteLine("PDF files are {0}.", areIdentical ? "identical" : "different");
        // If different, you can further inspect the PDFs manually to see number format changes.
    }

    // Helper method to compare two files byte by byte
    private static bool FilesAreEqual(string filePath1, string filePath2)
    {
        byte[] file1 = File.ReadAllBytes(filePath1);
        byte[] file2 = File.ReadAllBytes(filePath2);

        if (file1.Length != file2.Length)
            return false;

        for (int i = 0; i < file1.Length; i++)
        {
            if (file1[i] != file2[i])
                return false;
        }
        return true;
    }
}
