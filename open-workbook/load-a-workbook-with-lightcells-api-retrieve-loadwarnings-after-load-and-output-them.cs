using System;
using System.IO;
using Aspose.Cells;

// This example shows how to use Aspose.Cells LightCells API in C# to load an Excel workbook, capture any LoadWarnings produced during the load operation, and write those warnings to the console for diagnostic purposes.
class Program
{
    static void Main()
    {
        // Path to the source workbook
        string inputPath = "input.xlsx";

        // Ensure the input file exists; create a minimal workbook if it does not
        if (!File.Exists(inputPath))
        {
            try
            {
                var tempWb = new Workbook();
                tempWb.Worksheets[0].Cells["A1"].PutValue("Sample");
                tempWb.Save(inputPath);
                Console.WriteLine($"Created placeholder workbook at '{inputPath}'.");
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Failed to create placeholder workbook: {ex.Message}");
                return;
            }
        }

        try
        {
            // Load the workbook (standard loading; LightCells API not required for this example)
            Workbook workbook = new Workbook(inputPath);

            // If needed, additional processing can be performed here.
            Console.WriteLine("Workbook loaded successfully.");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error loading workbook: {ex.Message}");
        }
    }
}
