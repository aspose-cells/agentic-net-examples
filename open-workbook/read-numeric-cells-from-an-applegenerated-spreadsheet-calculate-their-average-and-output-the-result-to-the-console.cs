using System;
using Aspose.Cells;
using Aspose.Cells.Numbers;

class Program
{
    static void Main()
    {
        // Path to the Apple Numbers file
        string inputPath = "sample.numbers";

        // Load the Numbers file using NumbersLoadOptions
        NumbersLoadOptions loadOptions = new NumbersLoadOptions();
        Workbook workbook = new Workbook(inputPath, loadOptions);

        double sum = 0;
        int count = 0;

        // Iterate through all worksheets and their used cells
        foreach (Worksheet sheet in workbook.Worksheets)
        {
            Cells cells = sheet.Cells;
            int maxRow = cells.MaxDataRow;
            int maxCol = cells.MaxDataColumn;

            for (int row = 0; row <= maxRow; row++)
            {
                for (int col = 0; col <= maxCol; col++)
                {
                    Cell cell = cells[row, col];
                    if (cell != null && cell.Type == CellValueType.IsNumeric)
                    {
                        sum += cell.DoubleValue;
                        count++;
                    }
                }
            }
        }

        // Output the average to the console
        if (count > 0)
        {
            double average = sum / count;
            Console.WriteLine($"Average of numeric cells: {average}");
        }
        else
        {
            Console.WriteLine("No numeric cells found.");
        }
    }
}

