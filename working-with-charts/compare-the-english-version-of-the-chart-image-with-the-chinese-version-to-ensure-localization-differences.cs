using Aspose.Cells;
using Aspose.Cells.Charts;
using System;
using System.IO;
using System.Security.Cryptography;

// The sample loads English.xlsx and Chinese.xlsx, extracts the first chart from each workbook, saves each chart as a temporary PNG via Chart.ToImage, computes MD5 hashes of the PNG byte arrays, and reports whether the charts are identical or differ, optionally copying the PNGs for manual inspection.
class ChartLocalizationComparer
{
    static void Main()
    {
        try
        {
            // Verify that the required workbooks exist
            const string englishPath = "English.xlsx";
            const string chinesePath = "Chinese.xlsx";

            if (!File.Exists(englishPath))
                throw new FileNotFoundException($"File not found: {englishPath}");
            if (!File.Exists(chinesePath))
                throw new FileNotFoundException($"File not found: {chinesePath}");

            // Load the workbooks
            Workbook wbEnglish = new Workbook(englishPath);
            Workbook wbChinese = new Workbook(chinesePath);

            // Assume the chart to compare is the first chart on the first worksheet
            Chart chartEnglish = wbEnglish.Worksheets[0].Charts[0];
            Chart chartChinese = wbChinese.Worksheets[0].Charts[0];

            // Save charts to temporary PNG files (Aspose.Cells Chart.ToImage may only accept a file path)
            string tempEnglish = Path.GetTempFileName();
            string tempChinese = Path.GetTempFileName();

            try
            {
                chartEnglish.ToImage(tempEnglish);
                chartChinese.ToImage(tempChinese);

                // Compute MD5 hashes of the saved images
                string hashEnglish = ComputeMD5(File.ReadAllBytes(tempEnglish));
                string hashChinese = ComputeMD5(File.ReadAllBytes(tempChinese));

                // Compare the hashes
                if (hashEnglish == hashChinese)
                {
                    Console.WriteLine("Charts are identical. No localization differences detected.");
                }
                else
                {
                    Console.WriteLine("Charts differ. Localization differences exist.");

                    // Optionally copy the images for manual inspection
                    try
                    {
                        File.Copy(tempEnglish, "Chart_English.png", true);
                        File.Copy(tempChinese, "Chart_Chinese.png", true);
                    }
                    catch (Exception ex)
                    {
                        Console.WriteLine($"Error saving images: {ex.Message}");
                    }
                }
            }
            finally
            {
                // Clean up temporary files
                try { if (File.Exists(tempEnglish)) File.Delete(tempEnglish); } catch { }
                try { if (File.Exists(tempChinese)) File.Delete(tempChinese); } catch { }
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error: {ex.Message}");
        }
    }

    // Compute MD5 hash from a byte array
    static string ComputeMD5(byte[] data)
    {
        using (MD5 md5 = MD5.Create())
        {
            byte[] hashBytes = md5.ComputeHash(data);
            return BitConverter.ToString(hashBytes).Replace("-", "").ToLowerInvariant();
        }
    }
}
