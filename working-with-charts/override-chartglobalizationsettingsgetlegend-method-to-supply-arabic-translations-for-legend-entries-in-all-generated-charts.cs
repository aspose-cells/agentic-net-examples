using System;
using System.Collections.Generic;
using Aspose.Cells;
using Aspose.Cells.Charts; // For ChartType, Chart, etc.

namespace AsposeCellsChartLocalization
{
    // The example demonstrates how to create a custom ChartGlobalizationSettings class that overrides GetLegend to return Arabic strings, apply it to a Workbook, generate a column chart with Arabic series names, and save the workbook as an Excel file.
    class Program
    {
        static void Main()
        {
            try
            {
                // Create a new workbook.
                Workbook workbook = new Workbook();

                // Populate sample data.
                Worksheet sheet = workbook.Worksheets[0];
                sheet.Cells["A1"].PutValue("Month");
                sheet.Cells["B1"].PutValue("Sales");
                sheet.Cells["C1"].PutValue("Profit");
                sheet.Cells["A2"].PutValue("Jan");
                sheet.Cells["A3"].PutValue("Feb");
                sheet.Cells["A4"].PutValue("Mar");
                sheet.Cells["B2"].PutValue(1200);
                sheet.Cells["B3"].PutValue(1500);
                sheet.Cells["B4"].PutValue(1800);
                sheet.Cells["C2"].PutValue(300);
                sheet.Cells["C3"].PutValue(400);
                sheet.Cells["C4"].PutValue(500);

                // Add a column chart.
                int chartIndex = sheet.Charts.Add(ChartType.Column, 5, 0, 20, 10);
                Chart chart = sheet.Charts[chartIndex];

                // Set the data range for the chart.
                chart.NSeries.Add("B2:B4", true);
                chart.NSeries[0].Name = "المبيعات"; // Arabic for "Sales"

                chart.NSeries.Add("C2:C4", true);
                chart.NSeries[1].Name = "الربح";   // Arabic for "Profit"

                // Set category (X‑axis) labels.
                chart.NSeries.CategoryData = "A2:A4";

                // Save the workbook.
                string outputPath = "ChartWithArabicLegend.xlsx";
                workbook.Save(outputPath);
                Console.WriteLine($"Workbook saved successfully to '{outputPath}'.");
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Error: {ex.Message}");
            }
        }
    }
}
