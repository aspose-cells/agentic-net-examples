using System;
using System.Timers;
using Aspose.Cells;
using Aspose.Cells.Charts;

// The sample creates a Workbook, fills 100 rows of random data, adds a line chart, and sets up a System.Timers.Timer that fires every 60 seconds. On each tick the start row of a ten‑point window is advanced, the chart series is rebuilt with new X and Y ranges, and the workbook is saved, resulting in a continuously rolling line chart.
class RollingChartExample
{
    // Workbook and worksheet references
    static Workbook workbook;
    static Worksheet sheet;

    // Rolling window configuration
    static int windowSize = 10;      // Number of points displayed at once
    static int startRow = 0;         // Zero‑based index of the first row in the window

    // Timer to shift the window each minute
    static System.Timers.Timer timer;

    static void Main()
    {
        try
        {
            // ---------- Create workbook and populate sample data ----------
            workbook = new Workbook();
            sheet = workbook.Worksheets[0];
            sheet.Name = "Data";

            // Example: 100 rows of data (Column A = index, Column B = random value)
            Random rnd = new Random();
            for (int i = 0; i < 100; i++)
            {
                sheet.Cells[i, 0].PutValue(i + 1);               // X‑axis (e.g., time or index)
                sheet.Cells[i, 1].PutValue(rnd.Next(0, 100));   // Y‑axis value
            }

            // ---------- Add a line chart ----------
            // Chart placed at cells D5 to N25 (adjust as needed)
            int chartIdx = sheet.Charts.Add(ChartType.Line, 5, 3, 25, 13);
            Chart chart = sheet.Charts[chartIdx];

            // Initialize chart series with the first window of data
            UpdateChartSeries(chart);

            // ---------- Set up timer to shift data window every minute ----------
            timer = new System.Timers.Timer(60000); // 60,000 ms = 1 minute
            timer.Elapsed += OnTimerElapsed;
            timer.AutoReset = true;
            timer.Start();

            Console.WriteLine("Rolling chart is running. Press Enter to stop.");
            Console.ReadLine(); // Keep the application alive

            // Cleanup
            timer.Stop();
            timer.Dispose();

            // Save final workbook
            workbook.Save("RollingChart.xlsx");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error: {ex.Message}");
        }
    }

    // Timer callback: shift the window and refresh the chart
    static void OnTimerElapsed(object sender, ElapsedEventArgs e)
    {
        try
        {
            // Move the window forward by one row
            startRow++;

            // If we reach the end of the data, wrap around to the beginning
            if (startRow + windowSize > sheet.Cells.MaxDataRow + 1)
            {
                startRow = 0;
            }

            // Update the chart series to reflect the new window
            Chart chart = sheet.Charts[0];
            UpdateChartSeries(chart);

            // Optional: persist the workbook after each update
            workbook.Save("RollingChart.xlsx");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Timer error: {ex.Message}");
        }
    }

    // Helper: rebuild the chart series based on the current window
    static void UpdateChartSeries(Chart chart)
    {
        // Clear any existing series
        chart.NSeries.Clear();

        // Determine the first and last rows of the current window (1‑based for range strings)
        int firstRow = startRow;
        int lastRow = startRow + windowSize - 1;

        // Build range strings for X (Category) and Y (Values) data
        string xRange = $"{sheet.Name}!A{firstRow + 1}:A{lastRow + 1}";
        string yRange = $"{sheet.Name}!B{firstRow + 1}:B{lastRow + 1}";

        // Add Y‑values series; set CategoryData to X‑values range
        chart.NSeries.Add(yRange, true);
        chart.NSeries.CategoryData = xRange;
    }
}
