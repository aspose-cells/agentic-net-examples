using System;
using System.IO;
using Aspose.Cells;

// The sample creates a workbook, fills it with data, saves it twice—once with default settings and once using OoxmlSaveOptions configured for OoxmlCompressionType.Level5—then reads both .xlsx files' sizes and prints a comparison indicating which compression method yields a smaller file.
class Program
{
    static void Main()
    {
        // Create a new workbook and add some sample data
        Workbook workbook = new Workbook();
        Worksheet sheet = workbook.Worksheets[0];
        Cells cells = sheet.Cells;
        for (int row = 0; row < 100; row++)
        {
            for (int col = 0; col < 10; col++)
            {
                cells[row, col].PutValue($"R{row}C{col}");
            }
        }

        // Save with default compression (no explicit OoxmlCompressionType set)
        string defaultPath = "default.xlsx";
        workbook.Save(defaultPath, SaveFormat.Xlsx);
        long defaultSize = new FileInfo(defaultPath).Length;

        // Save with OoxmlCompressionType.Level5
        string compressedPath = "compressed.xlsx";
        OoxmlSaveOptions level5Options = new OoxmlSaveOptions(SaveFormat.Xlsx);
        level5Options.CompressionType = OoxmlCompressionType.Level5;
        workbook.Save(compressedPath, level5Options);
        long compressedSize = new FileInfo(compressedPath).Length;

        // Compare file sizes and output the result
        Console.WriteLine($"Default compression size: {defaultSize} bytes");
        Console.WriteLine($"Level5 compression size: {compressedSize} bytes");
        if (compressedSize < defaultSize)
        {
            Console.WriteLine("Level5 compression produced a smaller file.");
        }
        else if (compressedSize > defaultSize)
        {
            Console.WriteLine("Level5 compression produced a larger file.");
        }
        else
        {
            Console.WriteLine("Both files have the same size.");
        }
    }
}
