using System;
using System.IO;
using Aspose.Cells;
using Aspose.Cells.Rendering;

// Creates a workbook with three sheets, fills each with many rows, enables PdfSaveOptions.OnePagePerSheet, saves to a MemoryStream as PDF, then uses WorkbookRender to read the PDF page count and confirms it matches the worksheet count, outputting a verification result.
class VerifyOnePagePerSheet
{
    static void Main()
    {
        try
        {
            // Create a workbook with three worksheets, each filled with enough rows to normally span multiple pages
            Workbook workbook = new Workbook();
            for (int sheetIndex = 0; sheetIndex < 3; sheetIndex++)
            {
                Worksheet sheet = sheetIndex == 0 ? workbook.Worksheets[0] : workbook.Worksheets.Add($"Sheet{sheetIndex + 1}");
                for (int row = 0; row < 200; row++)
                {
                    sheet.Cells[row, 0].PutValue($"Sheet{sheetIndex + 1} Row {row + 1}");
                }
            }

            // Configure PDF save options to force one page per sheet
            PdfSaveOptions pdfOptions = new PdfSaveOptions
            {
                OnePagePerSheet = true
            };

            // Save the workbook to a PDF in a memory stream
            using (MemoryStream pdfStream = new MemoryStream())
            {
                workbook.Save(pdfStream, pdfOptions);
                pdfStream.Position = 0; // Reset stream position for any further processing

                // Use WorkbookRender to obtain the number of pages generated in the PDF
                ImageOrPrintOptions renderOptions = new ImageOrPrintOptions();
                WorkbookRender renderer = new WorkbookRender(workbook, renderOptions);
                int pdfPageCount = renderer.PageCount;

                int worksheetCount = workbook.Worksheets.Count;

                Console.WriteLine($"Number of worksheets: {worksheetCount}");
                Console.WriteLine($"Number of PDF pages: {pdfPageCount}");

                // Verify that each worksheet corresponds to exactly one PDF page
                if (pdfPageCount == worksheetCount)
                {
                    Console.WriteLine("Verification succeeded: one PDF page per worksheet.");
                }
                else
                {
                    Console.WriteLine("Verification failed: PDF page count does not match worksheet count.");
                }
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine($"An error occurred: {ex.Message}");
        }
    }
}
