using System;
using System.IO;
using System.Text;
using Aspose.Cells;

namespace AsposeCellsFitToPagesTallDemo
{
    // The example defines two C# tests that populate a worksheet with many rows, configure FitToPagesWide and FitToPagesTall, export the workbook to PDF via a MemoryStream, and validate pagination by counting '/Type /Page' markers in the PDF byte array—demonstrating unlimited height when FitToPagesTall is zero and single‑page restriction when it is set to one.
    class Program
    {
        static void Main()
        {
            try
            {
                FitToPagesTallZero_ShouldAllowMultiplePdfPages();
                Console.WriteLine("FitToPagesTallZero test passed.");
            }
            catch (Exception ex)
            {
                Console.WriteLine($"FitToPagesTallZero test failed: {ex.Message}");
            }

            try
            {
                FitToPagesTallOne_ShouldRestrictToSinglePdfPage();
                Console.WriteLine("FitToPagesTallOne test passed.");
            }
            catch (Exception ex)
            {
                Console.WriteLine($"FitToPagesTallOne test failed: {ex.Message}");
            }
        }

        // Test that setting FitToPagesTall to 0 results in multiple PDF pages (unlimited height)
        private static void FitToPagesTallZero_ShouldAllowMultiplePdfPages()
        {
            // Create a new workbook and get the first worksheet
            var workbook = new Workbook();
            var worksheet = workbook.Worksheets[0];

            // Populate many rows to force pagination
            for (int row = 0; row < 200; row++)
            {
                worksheet.Cells[row, 0].PutValue($"Row {row + 1}");
            }

            // Set width to one page and height to unlimited (0)
            worksheet.PageSetup.FitToPagesWide = 1;
            worksheet.PageSetup.FitToPagesTall = 0;

            // Export to PDF using a memory stream
            using (var pdfStream = new MemoryStream())
            {
                workbook.Save(pdfStream, SaveFormat.Pdf);
                pdfStream.Position = 0;

                // Get PDF bytes and count pages without external PDF library
                byte[] pdfBytes = pdfStream.ToArray();
                int pageCount = GetPdfPageCount(pdfBytes);

                // Unlimited height should produce more than one page
                if (pageCount <= 1)
                {
                    throw new InvalidOperationException($"Expected multiple PDF pages, but found {pageCount}.");
                }
            }
        }

        // Additional verification: limiting height to one page should produce a single PDF page
        private static void FitToPagesTallOne_ShouldRestrictToSinglePdfPage()
        {
            var workbook = new Workbook();
            var worksheet = workbook.Worksheets[0];

            for (int row = 0; row < 200; row++)
            {
                worksheet.Cells[row, 0].PutValue($"Row {row + 1}");
            }

            // Limit both width and height to one page
            worksheet.PageSetup.FitToPagesWide = 1;
            worksheet.PageSetup.FitToPagesTall = 1;

            using (var pdfStream = new MemoryStream())
            {
                workbook.Save(pdfStream, SaveFormat.Pdf);
                pdfStream.Position = 0;

                byte[] pdfBytes = pdfStream.ToArray();
                int pageCount = GetPdfPageCount(pdfBytes);

                // Height limited to one page should result in a single PDF page
                if (pageCount != 1)
                {
                    throw new InvalidOperationException($"Expected a single PDF page, but found {pageCount}.");
                }
            }
        }

        // Simple PDF page count by counting occurrences of the "/Type /Page" marker
        private static int GetPdfPageCount(byte[] pdfBytes)
        {
            string pdfText = Encoding.ASCII.GetString(pdfBytes);
            const string pageMarker = "/Type /Page";
            int count = 0;
            int index = 0;

            while ((index = pdfText.IndexOf(pageMarker, index, StringComparison.Ordinal)) != -1)
            {
                count++;
                index += pageMarker.Length;
            }

            return count;
        }
    }
}
