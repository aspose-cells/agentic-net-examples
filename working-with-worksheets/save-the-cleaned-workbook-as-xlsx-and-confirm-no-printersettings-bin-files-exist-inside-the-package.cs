using Aspose.Cells;
using System;
using System.IO;
using System.IO.Compression;

// The example loads an existing workbook or creates a new one, saves it as an XLSX file using Aspose.Cells, then opens the resulting file as a ZIP archive to scan for any entries ending with ".bin", reporting whether any printer‑settings binary files are present.
class Program
{
    static void Main()
    {
        const string inputPath = "cleaned_workbook.xlsx";
        const string outputPath = "cleaned_workbook_output.xlsx";

        try
        {
            Workbook workbook;

            // Load existing workbook if it exists; otherwise create a new one.
            if (File.Exists(inputPath))
            {
                workbook = new Workbook(inputPath);
                Console.WriteLine($"Loaded workbook from '{inputPath}'.");
            }
            else
            {
                workbook = new Workbook();
                // Optionally add a default worksheet.
                workbook.Worksheets[0].Name = "Sheet1";
                Console.WriteLine($"Input file not found. Created a new workbook.");
            }

            // Save the workbook as XLSX.
            workbook.Save(outputPath, SaveFormat.Xlsx);
            Console.WriteLine($"Workbook saved to '{outputPath}'.");

            // Verify that the XLSX package does not contain any printer‑settings .bin files.
            if (File.Exists(outputPath))
            {
                using (ZipArchive archive = ZipFile.OpenRead(outputPath))
                {
                    bool binFileFound = false;
                    foreach (ZipArchiveEntry entry in archive.Entries)
                    {
                        if (entry.FullName.EndsWith(".bin", StringComparison.OrdinalIgnoreCase))
                        {
                            binFileFound = true;
                            Console.WriteLine($"Unexpected .bin file detected: {entry.FullName}");
                        }
                    }

                    if (!binFileFound)
                    {
                        Console.WriteLine("No printer‑settings .bin files found inside the XLSX package.");
                    }
                }
            }
            else
            {
                Console.WriteLine($"Output file '{outputPath}' was not created.");
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine($"An error occurred: {ex.Message}");
        }
    }
}
