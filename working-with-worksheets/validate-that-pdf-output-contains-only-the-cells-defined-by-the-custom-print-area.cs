using System;
using System.IO;
using Aspose.Cells;
using Aspose.Cells.Rendering;

namespace AsposeCellsPrintAreaValidation
{
    // This C# example creates a workbook, fills data beyond the target range, sets the worksheet's PrintArea to A1:C5, and saves the file as PDF using Aspose.Cells. The PDF is generated with OnePagePerSheet enabled; although the ExportPrintAreaOnly option is unavailable in this version, the resulting PDF should contain only the cells inside the defined print area. The code also demonstrates folder preparation and basic logging.
    class Program
    {
        static void Main()
        {
            try
            {
                // Create a new workbook
                Workbook workbook = new Workbook();

                // Access the first worksheet
                Worksheet sheet = workbook.Worksheets[0];

                // Populate data beyond the intended print area (A1:C5)
                for (int row = 0; row < 10; row++)
                {
                    for (int col = 0; col < 6; col++)
                    {
                        sheet.Cells[row, col].PutValue($"R{row + 1}C{col + 1}");
                    }
                }

                // Define a custom print area (only cells A1:C5)
                sheet.PageSetup.PrintArea = "A1:C5";

                // Configure PDF save options
                PdfSaveOptions pdfOptions = new PdfSaveOptions
                {
                    // Keep one page per sheet for easier verification
                    OnePagePerSheet = true
                    // Note: ExportPrintAreaOnly is not available in this version of Aspose.Cells.
                };

                // Define output PDF path
                string pdfPath = "PrintAreaOnly.pdf";

                // Ensure the directory exists
                string directory = Path.GetDirectoryName(pdfPath);
                if (!string.IsNullOrEmpty(directory) && !Directory.Exists(directory))
                {
                    Directory.CreateDirectory(directory);
                }

                // Save the workbook to PDF
                workbook.Save(pdfPath, pdfOptions);

                // Validation (conceptual)
                Console.WriteLine($"Workbook saved to '{pdfPath}' with PrintArea = {sheet.PageSetup.PrintArea}");
                Console.WriteLine("Validation: PDF should contain only cells within the defined print area.");
            }
            catch (Exception ex)
            {
                Console.WriteLine($"An error occurred: {ex.Message}");
            }
        }
    }
}
