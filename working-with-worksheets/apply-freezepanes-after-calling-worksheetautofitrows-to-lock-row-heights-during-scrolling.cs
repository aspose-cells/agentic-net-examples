using System;
using Aspose.Cells;

// Demonstrates creating a workbook with Aspose.Cells, populating sample data, auto‑fitting all rows, then applying Worksheet.FreezePanes to lock the first row’s height during scrolling, and finally saving the file as Output.xlsx.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook
            var workbook = new Workbook();

            // Get the first worksheet
            var sheet = workbook.Worksheets[0];

            // Sample data to demonstrate autofit
            sheet.Cells["A1"].PutValue("Header1");
            sheet.Cells["B1"].PutValue("Header2");
            for (int i = 0; i < 20; i++)
            {
                sheet.Cells[i + 1, 0].PutValue($"Row {i + 1}");
                sheet.Cells[i + 1, 1].PutValue(i * 10);
            }

            // Auto‑fit all rows so their heights match the content
            sheet.AutoFitRows();

            // Freeze the first row (row index 1) to lock row heights while scrolling
            // Parameters: first unfrozen row index, first unfrozen column index,
            // total rows to freeze, total columns to freeze
            sheet.FreezePanes(1, 0, 1, 0);

            // Save the workbook
            workbook.Save("Output.xlsx");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"An error occurred: {ex.Message}");
        }
    }
}
