using Aspose.Cells;
using System;

// // Creates a workbook, fills sample data, hides columns 5‑9, and saves the file as a PDF using PdfSaveOptions so the hidden columns remain hidden in the exported document.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook
            Workbook workbook = new Workbook();

            // Get the first worksheet
            Worksheet sheet = workbook.Worksheets[0];

            // Populate sample data
            for (int row = 0; row < 10; row++)
            {
                for (int col = 0; col < 15; col++)
                {
                    sheet.Cells[row, col].PutValue($"R{row}C{col}");
                }
            }

            // Hide columns with indexes 5 through 9 (inclusive)
            for (int col = 5; col <= 9; col++)
            {
                sheet.Cells.HideColumn(col);
            }

            // Set PDF save options (properties for hidden rows/columns are not available in older versions)
            PdfSaveOptions pdfOptions = new PdfSaveOptions();

            // Export the workbook to PDF
            workbook.Save("HiddenColumnsPreserved.pdf", pdfOptions);
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error: {ex.Message}");
        }
    }
}
