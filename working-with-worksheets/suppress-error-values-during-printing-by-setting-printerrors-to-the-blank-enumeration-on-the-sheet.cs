{
    static void Main()
    {
        try
        {
            // Create a new workbook
            Workbook workbook = new Workbook();

            // Get the first worksheet
            Worksheet sheet = workbook.Worksheets[0];

            // Note: Worksheet does not have a PrintErrors property.
            // If you need to control error printing for PDF/XPS output,
            // configure a PrintOptions instance when saving those formats.

            // Define output file path
            string outputPath = "output.xlsx";

