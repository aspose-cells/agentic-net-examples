using Aspose.Cells;
using System;

// The sample creates a Workbook, accesses the first Worksheet, sets its Zoom property to 110%, adds a sample cell value, configures PdfSaveOptions (including font‑embedding settings when available), and saves the result as a PDF file.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook
            Workbook workbook = new Workbook();

            // Get the first worksheet
            Worksheet sheet = workbook.Worksheets[0];

            // Apply 110% zoom to the worksheet
            sheet.Zoom = 110;

            // Add sample data to visualize in the PDF
            sheet.Cells["A1"].PutValue("Sample data for PDF export");

            // Set PDF save options (font embedding properties are not available in this version)
            PdfSaveOptions pdfOptions = new PdfSaveOptions();

            // Save the workbook as a PDF
            workbook.Save("Worksheet_110Zoom.pdf", pdfOptions);
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error: {ex.Message}");
        }
    }
}
