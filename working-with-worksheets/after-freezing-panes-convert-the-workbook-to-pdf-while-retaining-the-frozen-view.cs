using Aspose.Cells;
using System;
using System.IO;

// The example creates a workbook, fills it with data, freezes the first row and column using FreezePanes, configures PdfSaveOptions, and saves the workbook as a PDF that maintains the frozen pane view.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook (or load an existing one)
            Workbook workbook = new Workbook();

            // Get the first worksheet
            Worksheet sheet = workbook.Worksheets[0];

            // Fill the sheet with sample data
            for (int row = 0; row < 30; row++)
            {
                for (int col = 0; col < 10; col++)
                {
                    sheet.Cells[row, col].PutValue($"R{row + 1}C{col + 1}");
                }
            }

            // Freeze the first row and first column.
            // Use the 4‑parameter overload: rows above 'row', columns left of 'column' are frozen.
            int totalRows = sheet.Cells.MaxDataRow + 1;      // scrollable rows count
            int totalColumns = sheet.Cells.MaxDataColumn + 1; // scrollable columns count
            sheet.FreezePanes(1, 1, totalRows, totalColumns);

            // Prepare PDF save options (optional customizations)
            PdfSaveOptions pdfOptions = new PdfSaveOptions
            {
                // Keep the layout as shown in Excel; frozen panes are rendered accordingly.
                OnePagePerSheet = false
            };

            // Save the workbook to PDF while retaining the frozen view.
            string outputPath = "FrozenView.pdf";
            workbook.Save(outputPath, pdfOptions);
            Console.WriteLine($"Workbook saved successfully to '{Path.GetFullPath(outputPath)}'.");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error: {ex.Message}");
        }
    }
}
