using Aspose.Cells;

// The example creates a new workbook, accesses the first worksheet, sets PageSetup.PrintHeadings to false to prevent row and column headings from being printed, and saves the result as MarketingBrochure.xlsx.
class Program
{
    static void Main()
    {
        // Create a new workbook (empty workbook)
        Workbook workbook = new Workbook();

        // Get the first worksheet (default sheet)
        Worksheet sheet = workbook.Worksheets[0];

        // Disable printing of row (and column) headings for a cleaner layout
        sheet.PageSetup.PrintHeadings = false;

        // Save the workbook to a file
        workbook.Save("MarketingBrochure.xlsx");
    }
}
