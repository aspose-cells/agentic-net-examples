using System;
using Aspose.Cells;

// The sample creates a new Workbook, accesses the first worksheet, calls worksheet.FreezePanes(1, 1, 1, 1) to freeze the first row and first column together, saves the workbook as "FrozenPaneDemo.xlsx", and prints a success message.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook
            var workbook = new Workbook();

            // Get the first worksheet
            var worksheet = workbook.Worksheets[0];

            // Freeze the first row and first column simultaneously.
            // Parameters: row index, column index, number of rows to freeze, number of columns to freeze.
            worksheet.FreezePanes(1, 1, 1, 1);

            // Save the workbook to a file
            workbook.Save("FrozenPaneDemo.xlsx");
            Console.WriteLine("Workbook saved successfully.");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error: {ex.Message}");
        }
    }
}
