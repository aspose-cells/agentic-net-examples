using System;
using System.Collections.Generic;
using System.IO;
using System.Text.Json;
using Aspose.Cells;
using Aspose.Cells.Drawing;

// The program creates a new workbook, adds a rectangle shape to the first worksheet, retrieves its connection points via GetConnectionPoints, serializes each point's index, X, and Y coordinates into an indented JSON file, and saves both the JSON file and the workbook.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook
            Workbook workbook = new Workbook();

            // Access the first worksheet
            Worksheet sheet = workbook.Worksheets[0];

            // Add a rectangle shape to the worksheet
            // Parameters: shape type, upper left row, upper left column, row offset, column offset, height, width
            Shape shape = sheet.Shapes.AddShape(MsoDrawingType.Rectangle, 2, 2, 0, 0, 100, 200);

            // Retrieve the connection points from the shape
            var connectionPoints = shape.GetConnectionPoints();

            // Prepare a list to hold the connection point data
            var pointsList = new List<object>();

            // Iterate over the returned points (use dynamic to avoid explicit ConnectionPoint type)
            foreach (var cpObj in connectionPoints)
            {
                dynamic cp = cpObj;
                pointsList.Add(new
                {
                    Index = (int)cp.Index,
                    X = (double)cp.X,
                    Y = (double)cp.Y
                });
            }

            // Serialize the list to JSON with indentation for readability
            string json = JsonSerializer.Serialize(pointsList, new JsonSerializerOptions { WriteIndented = true });

            // Write the JSON string to a file
            string jsonPath = "shape_connection_points.json";
            File.WriteAllText(jsonPath, json);
            Console.WriteLine($"Connection points saved to '{jsonPath}'.");

            // Save the workbook (optional, for inspection)
            string workbookPath = "output.xlsx";
            workbook.Save(workbookPath);
            Console.WriteLine($"Workbook saved to '{workbookPath}'.");
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"An error occurred: {ex.Message}");
        }
    }
}
