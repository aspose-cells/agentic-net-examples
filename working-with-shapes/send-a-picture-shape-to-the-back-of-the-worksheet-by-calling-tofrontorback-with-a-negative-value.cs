using System;
using System.IO;
using Aspose.Cells;
using Aspose.Cells.Drawing;

// The example creates a new workbook, adds a PNG picture at cell E5, sends the picture to the back layer with ToFrontOrBack(-1), and saves the workbook as output.xlsx.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook
            Workbook workbook = new Workbook();

            // Get the first worksheet
            Worksheet sheet = workbook.Worksheets[0];

            // Path to the image file to be added as a picture shape
            string imagePath = "sample.png";

            // Ensure the image file exists before adding
            if (!File.Exists(imagePath))
            {
                Console.WriteLine($"Image file not found: {imagePath}");
                return;
            }

            // Add the picture shape to the worksheet at row 5, column 5
            int pictureIndex = sheet.Pictures.Add(5, 5, imagePath);
            Picture picture = sheet.Pictures[pictureIndex];

            // Send the picture shape to the back of the worksheet (negative value moves to back)
            picture.ToFrontOrBack(-1);

            // Save the workbook
            string outputPath = "output.xlsx";
            workbook.Save(outputPath);
            Console.WriteLine($"Workbook saved to {outputPath}");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error: {ex.Message}");
        }
    }
}
