using System;
using System.IO;
using Aspose.Cells;
using Aspose.Cells.Drawing;

// The example loads an existing Excel file, finds the first picture shape, attempts to call its Refresh method via reflection (when the picture is linked), saves the workbook as a PDF, and then confirms that the PDF was created and contains data.
class Program
{
    static void Main()
    {
        try
        {
            const string inputPath = "input.xlsx";
            const string outputPath = "output.pdf";

            // Verify that the input workbook exists
            if (!File.Exists(inputPath))
            {
                Console.WriteLine($"Input file not found: {inputPath}");
                return;
            }

            // Load the existing Excel workbook
            Workbook workbook = new Workbook(inputPath);

            // Locate the first picture in the first worksheet
            Worksheet sheet = workbook.Worksheets[0];
            Picture picture = null;

            foreach (Shape shape in sheet.Shapes)
            {
                if (shape is Picture pic)
                {
                    picture = pic;
                    break;
                }
            }

            if (picture == null)
            {
                Console.WriteLine("No picture found in the workbook.");
                return;
            }

            // Attempt to refresh the picture if the Refresh method is available (for linked pictures)
            try
            {
                var refreshMethod = picture.GetType().GetMethod("Refresh");
                refreshMethod?.Invoke(picture, null);
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Unable to refresh picture: {ex.Message}");
            }

            // Save the workbook as PDF after the (optional) refresh operation
            workbook.Save(outputPath, SaveFormat.Pdf);

            // Simple verification: ensure the PDF file was created and has content
            FileInfo pdfInfo = new FileInfo(outputPath);
            if (pdfInfo.Exists && pdfInfo.Length > 0)
            {
                Console.WriteLine($"PDF generated successfully. Size: {pdfInfo.Length} bytes");
            }
            else
            {
                Console.WriteLine("PDF generation failed or file is empty.");
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine($"An error occurred: {ex.Message}");
        }
    }
}
