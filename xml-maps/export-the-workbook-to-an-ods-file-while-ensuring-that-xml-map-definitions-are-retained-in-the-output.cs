using System;
using Aspose.Cells;

// The example creates a workbook, adds sample data, defines an XSD schema, attaches it as an XML map, and saves the file as ODS. Aspose.Cells automatically retains the XML map definitions in the ODS output.
class Program
{
    static void Main()
    {
        try
        {
            // -----------------------------------------------------------------
            // 1. Create a new workbook and add some sample data
            // -----------------------------------------------------------------
            Workbook workbook = new Workbook();
            Worksheet sheet = workbook.Worksheets[0];

            // Populate the worksheet with sample data that will be mapped to XML
            sheet.Cells["A1"].PutValue("Name");
            sheet.Cells["B1"].PutValue("Value");
            sheet.Cells["A2"].PutValue("Item1");
            sheet.Cells["B2"].PutValue(100);
            sheet.Cells["A3"].PutValue("Item2");
            sheet.Cells["B3"].PutValue(200);

            // -----------------------------------------------------------------
            // 2. Define an XML schema (XSD) that describes the desired XML structure
            // -----------------------------------------------------------------
            string xmlSchema = @"
<xs:schema xmlns:xs='http://www.w3.org/2001/XMLSchema'>
  <xs:element name='Data'>
    <xs:complexType>
      <xs:sequence>
        <xs:element name='Item' maxOccurs='unbounded'>
          <xs:complexType>
            <xs:sequence>
              <xs:element name='Name' type='xs:string'/>
              <xs:element name='Value' type='xs:integer'/>
            </xs:sequence>
          </xs:complexType>
        </xs:element>
      </xs:sequence>
    </xs:complexType>
  </xs:element>
</xs:schema>";

            // -----------------------------------------------------------------
            // 3. Add the XML map to the workbook
            // -----------------------------------------------------------------
            int mapIndex = workbook.Worksheets.XmlMaps.Add(xmlSchema);
            XmlMap xmlMap = workbook.Worksheets.XmlMaps[mapIndex];
            xmlMap.Name = "SampleMap"; // optional, gives a friendly name

            // -----------------------------------------------------------------
            // 4. (Optional) Export the XML to verify the map works – not required for ODS,
            //    but demonstrates that the map is correctly attached.
            // -----------------------------------------------------------------
            // workbook.ExportXml(xmlMap.Name, "sample.xml");

            // -----------------------------------------------------------------
            // 5. Save the workbook as an ODS file. The XML map definitions are retained
            //    automatically when saving to ODS format.
            // -----------------------------------------------------------------
            string odsPath = "WorkbookWithXmlMap.ods";
            workbook.Save(odsPath, SaveFormat.Ods);

            Console.WriteLine($"Workbook successfully saved to ODS format at '{odsPath}'.");
            Console.WriteLine("XML map definitions are preserved in the ODS file.");
        }
        catch (Exception ex)
        {
            Console.WriteLine("An error occurred: " + ex.Message);
        }
    }
}
