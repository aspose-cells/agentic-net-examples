using System;
using System.IO;
using Aspose.Cells;
using Aspose.Cells.Drawing;
using Aspose.Cells.Rendering;

namespace AsposeCellsAttachmentVerification
{
    // Creates a workbook, adds a text file as an OLE object, saves the sheet as a PDF with PdfSaveOptions.EmbedAttachments enabled, and guides you to confirm the attachment appears in any PDF viewer.
    class Program
    {
        static void Main()
        {
            try
            {
                // Create a new workbook and get the first worksheet
                Workbook workbook = new Workbook();
                Worksheet sheet = workbook.Worksheets[0];
                sheet.Cells["A1"].PutValue("PDF with Embedded Attachment Example");

                // Prepare a sample file that will be embedded as an OLE object
                string sampleFilePath = Path.Combine(Path.GetTempPath(), "sample.txt");
                File.WriteAllText(sampleFilePath, "This is a sample attachment file.");

                // Ensure the sample file exists before reading it
                if (!File.Exists(sampleFilePath))
                    throw new FileNotFoundException("Sample attachment file not found.", sampleFilePath);

                // Add the OLE object (attachment) to the worksheet
                // Parameters: row, column, width, height, byte[] data
                int oleIndex = sheet.OleObjects.Add(5, 5, 200, 200, File.ReadAllBytes(sampleFilePath));
                OleObject ole = sheet.OleObjects[oleIndex];
                ole.DisplayAsIcon = true;          // Show as an icon in the sheet
                ole.Label = "Sample Attachment";

                // Configure PDF save options to embed attachments
                PdfSaveOptions pdfOptions = new PdfSaveOptions
                {
                    EmbedAttachments = true   // Ensure OLE objects are embedded in the PDF
                };

                // Define output PDF path
                string outputPdf = Path.Combine(Path.GetTempPath(), "WorkbookWithAttachment.pdf");

                // Save the workbook as PDF with the specified options
                workbook.Save(outputPdf, pdfOptions);

                Console.WriteLine($"PDF saved to: {outputPdf}");
                Console.WriteLine("Open the PDF in a viewer and verify the attachment is listed.");

                // Clean up the temporary sample file
                File.Delete(sampleFilePath);
            }
            catch (Exception ex)
            {
                Console.WriteLine($"An error occurred: {ex.Message}");
            }
        }
    }
}
