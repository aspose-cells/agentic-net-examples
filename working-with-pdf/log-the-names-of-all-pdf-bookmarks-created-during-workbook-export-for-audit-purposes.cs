using System;
using Aspose.Cells;

// The sample demonstrates creating a Workbook, adding data, configuring PdfSaveOptions, and saving to PDF. It notes that the current Aspose.Cells version does not generate PDF bookmarks, so no bookmark names are available to log unless a later version adds support.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook and add sample data
            Workbook workbook = new Workbook();
            Worksheet sheet = workbook.Worksheets[0];
            sheet.Cells["A1"].PutValue("First Page");
            sheet.Cells["A2"].PutValue("Second Page");

            // Prepare PDF save options (bookmarks are not supported in this version)
            PdfSaveOptions pdfOptions = new PdfSaveOptions();

            // Export the workbook to PDF
            string outputPath = "output.pdf";
            workbook.Save(outputPath, pdfOptions);
            Console.WriteLine($"PDF file '{outputPath}' created successfully.");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"An error occurred: {ex.Message}");
        }
    }
}
