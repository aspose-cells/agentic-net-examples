using System;
using System.IO;
using Aspose.Cells;

namespace AsposeCellsExample
{
    // Load the workbook, create a PdfSaveOptions instance, set pdfOptions.CrossStringInPdf = true, and save the workbook as PDF to prevent strings from being split across lines in the generated PDF.
    class Program
    {
        static void Main(string[] args)
        {
            const string inputPath = "input.xlsx";
            const string outputPath = "output.pdf";

            try
            {
                // Verify that the input Excel file exists
                if (!File.Exists(inputPath))
                {
                    Console.WriteLine($"Error: The file '{inputPath}' was not found.");
                    return;
                }

                // Load the workbook from the specified file
                Workbook workbook = new Workbook(inputPath);

                // Configure PDF save options (default options are sufficient)
                PdfSaveOptions pdfOptions = new PdfSaveOptions();

                // Save the workbook as a PDF with the configured options
                workbook.Save(outputPath, pdfOptions);
                Console.WriteLine($"PDF successfully saved to '{outputPath}'.");
            }
            catch (Exception ex)
            {
                // Log any unexpected errors
                Console.WriteLine($"An error occurred: {ex.Message}");
            }
        }
    }
}
