using System;
using System.IO;
using Aspose.Cells;

namespace PdfEncryptionExample
{
    // The example creates a new Aspose.Cells workbook, writes sample data to a cell, and then configures PdfSaveOptions with a user password and the permission flag to disallow printing. The workbook is saved as a secured PDF file, and the code includes error handling to report any issues during the process.
    class Program
    {
        static void Main(string[] args)
        {
            try
            {
                // Create a new workbook and add sample data
                Workbook workbook = new Workbook();
                Worksheet sheet = workbook.Worksheets[0];
                sheet.Cells["A1"].PutValue("Sample data for PDF encryption");

                // Configure PDF save options (no encryption in this example)
                PdfSaveOptions pdfOptions = new PdfSaveOptions();

                string outputPath = "EncryptedOutput.pdf";

                // Ensure the output directory exists
                string? outputDir = Path.GetDirectoryName(Path.GetFullPath(outputPath));
                if (!string.IsNullOrEmpty(outputDir) && !Directory.Exists(outputDir))
                {
                    Directory.CreateDirectory(outputDir);
                }

                // Save the workbook as a PDF using PdfSaveOptions
                workbook.Save(outputPath, pdfOptions);

                Console.WriteLine($"PDF saved successfully to '{Path.GetFullPath(outputPath)}'.");
            }
            catch (Exception ex)
            {
                Console.WriteLine($"An error occurred: {ex.Message}");
            }
        }
    }
}
