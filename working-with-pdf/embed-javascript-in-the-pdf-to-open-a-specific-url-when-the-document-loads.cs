using System;
using Aspose.Cells;
using Aspose.Cells.Rendering;

// The sample demonstrates creating a Workbook, adding data, configuring PdfSaveOptions, and saving as a PDF while noting that JavaScript embedding (e.g., app.launchURL) is not available in the current Aspose.Cells version but may be supported via a PdfJavaScript property in future releases.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook (or load an existing one if needed)
            Workbook workbook = new Workbook();

            // Add sample data to the first worksheet
            Worksheet sheet = workbook.Worksheets[0];
            sheet.Cells["A1"].PutValue("Hello, Aspose.Cells!");
            sheet.Cells["A2"].PutValue("This PDF is generated by Aspose.Cells.");

            // Configure PDF save options
            PdfSaveOptions pdfOptions = new PdfSaveOptions();

            // NOTE: Embedding JavaScript in PDF is not supported in the current Aspose.Cells version.
            // If a newer version provides PdfJavaScript property, it can be set here, e.g.:
            // pdfOptions.PdfJavaScript = "app.launchURL('https://www.example.com');";

            // Save the workbook as a PDF
            string outputPath = "OutputWithJavaScript.pdf";
            workbook.Save(outputPath, pdfOptions);
            Console.WriteLine($"PDF saved successfully to '{outputPath}'.");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"An error occurred: {ex.Message}");
        }
    }
}
