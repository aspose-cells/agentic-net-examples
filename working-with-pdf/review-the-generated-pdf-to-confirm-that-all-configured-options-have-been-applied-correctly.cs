using System;
using System.IO;
using Aspose.Cells;   // Aspose.Cells namespace for workbook handling

// The sample program confirms that the PDF file created by Aspose.Cells exists, loads the original Excel workbook, checks that the worksheet count matches the expected number, verifies a specific heading in the first cell, reports whether gridlines are visible, and outputs any discrepancies or errors.
class PdfReview
{
    static void Main()
    {
        // Path to the PDF generated by Aspose.Cells (verification of existence only)
        string pdfPath = "output.pdf";

        // Verify that the PDF file exists before any further processing
        if (!File.Exists(pdfPath))
        {
            Console.WriteLine($"PDF file not found: {pdfPath}");
            // Continue only if you have alternative verification logic
        }
        else
        {
            Console.WriteLine($"PDF file found: {pdfPath}");
        }

        // Example: Load the source workbook (if available) and perform basic checks using Aspose.Cells
        string workbookPath = "output.xlsx";

        if (!File.Exists(workbookPath))
        {
            Console.WriteLine($"Workbook file not found: {workbookPath}");
            return;
        }

        try
        {
            // Load the workbook generated before PDF conversion
            Workbook workbook = new Workbook(workbookPath);

            // Verify worksheet count (example: expecting at least one sheet)
            int expectedSheetCount = 1; // adjust as needed
            if (workbook.Worksheets.Count != expectedSheetCount)
            {
                Console.WriteLine($"Worksheet count mismatch. Expected {expectedSheetCount}, found {workbook.Worksheets.Count}.");
            }
            else
            {
                Console.WriteLine("Worksheet count matches expected value.");
            }

            // Example: Check for a specific heading in the first cell of the first worksheet
            string expectedHeading = "Report"; // adjust as needed
            string actualHeading = workbook.Worksheets[0].Cells[0, 0].StringValue;

            if (actualHeading.Contains(expectedHeading))
            {
                Console.WriteLine($"Heading \"{expectedHeading}\" found in the workbook.");
            }
            else
            {
                Console.WriteLine($"Heading \"{expectedHeading}\" not found in the workbook.");
            }

            // Additional checks (e.g., gridlines) can be performed via worksheet properties
            bool gridlinesEnabled = workbook.Worksheets[0].IsGridlinesVisible;
            Console.WriteLine(gridlinesEnabled ? "Gridlines are enabled." : "Gridlines are disabled.");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"An error occurred while processing the workbook: {ex.Message}");
        }
    }
}
