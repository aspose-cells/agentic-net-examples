using System;
using System.IO;
using Aspose.Cells;

// The C# program loads an Excel workbook created by Aspose.Cells, verifies that the workbook contains the expected number of worksheets, checks that cell A1 in the first sheet matches the expected header text, reports pass/fail results, disposes the workbook, and handles any runtime exceptions.
class WorkbookVerification
{
    static void Main()
    {
        // Path to the workbook generated by Aspose.Cells
        string workbookPath = "output.xlsx";

        // Ensure the file exists before attempting to load
        if (!File.Exists(workbookPath))
        {
            Console.WriteLine($"File not found: {workbookPath}");
            return;
        }

        try
        {
            // Load the workbook
            Workbook workbook = new Workbook(workbookPath);

            // Example verification: expected number of worksheets
            int expectedSheetCount = 2; // adjust as needed
            if (workbook.Worksheets.Count == expectedSheetCount)
                Console.WriteLine($"Worksheet count verification passed: {workbook.Worksheets.Count}");
            else
                Console.WriteLine($"Worksheet count verification failed: Expected {expectedSheetCount}, found {workbook.Worksheets.Count}");

            // Example verification: check a specific header text in the first worksheet
            Worksheet firstSheet = workbook.Worksheets[0];
            string expectedHeader = "Sales Report Q1";
            string actualHeader = firstSheet.Cells["A1"].StringValue;

            if (actualHeader == expectedHeader)
                Console.WriteLine("Header text verification passed.");
            else
                Console.WriteLine($"Header text verification failed: Expected '{expectedHeader}', found '{actualHeader}'");

            // Additional checks can be added here (e.g., cell values, formulas, formatting, etc.)

            // Cleanup
            workbook.Dispose();
        }
        catch (Exception ex)
        {
            Console.WriteLine($"An error occurred during verification: {ex.Message}");
        }
    }
}
