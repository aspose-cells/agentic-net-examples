using System;
using System.IO;
using Aspose.Cells;

// Demonstrates creating an Aspose.Cells workbook, saving it as a PDF with SaveFormat.Pdf, and generating a temporary JSON configuration file; it also notes that embedding the JSON into the PDF would require the Aspose.Pdf library.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook and add sample data
            Workbook workbook = new Workbook();
            Worksheet sheet = workbook.Worksheets[0];
            sheet.Cells["A1"].PutValue("Sample data for PDF with attachment");

            // Define output PDF path
            string pdfPath = Path.Combine(Environment.CurrentDirectory, "OutputWithAttachment.pdf");

            // Save the workbook as a PDF
            workbook.Save(pdfPath, SaveFormat.Pdf);

            // Create a temporary JSON configuration file
            string jsonContent = "{ \"setting1\": true, \"setting2\": \"value\" }";
            string jsonPath = Path.Combine(Path.GetTempPath(), "config.json");

            try
            {
                File.WriteAllText(jsonPath, jsonContent);
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Failed to write JSON file: {ex.Message}");
                return;
            }

            // Ensure the JSON file exists before proceeding
            if (!File.Exists(jsonPath))
            {
                Console.WriteLine("The JSON configuration file was not created.");
                return;
            }

            // Note: Adding attachments to PDF requires Aspose.Pdf, which is not referenced here.
            // The PDF has been generated successfully at the specified location.
            Console.WriteLine($"PDF generated at: {pdfPath}");
            Console.WriteLine($"JSON configuration file created at: {jsonPath}");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error: {ex.Message}");
        }
    }
}
