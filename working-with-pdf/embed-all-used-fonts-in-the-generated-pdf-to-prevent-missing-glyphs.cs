using System;
using Aspose.Cells;
using Aspose.Cells.Rendering;

namespace AsposeCellsFontEmbeddingDemo
{
    // Demonstrates how to use Aspose.Cells PdfSaveOptions in C# to embed every font used in a workbook—setting FontEncoding to Identity, enabling EmbedStandardWindowsFonts, defining a DefaultFont, and checking the workbook's default font—so the resulting PDF contains all glyphs and displays correctly on any device.
    class Program
    {
        static void Main()
        {
            // Create a new workbook and access the first worksheet
            Workbook workbook = new Workbook();
            Worksheet sheet = workbook.Worksheets[0];

            // Add sample data with different fonts
            sheet.Cells["A1"].PutValue("Default Font Text");
            sheet.Cells["A2"].PutValue("Arial Font Text");
            sheet.Cells["A3"].PutValue("Times New Roman Font Text");

            // Apply specific fonts to cells
            Style styleArial = workbook.CreateStyle();
            styleArial.Font.Name = "Arial";
            sheet.Cells["A2"].SetStyle(styleArial);

            Style styleTimes = workbook.CreateStyle();
            styleTimes.Font.Name = "Times New Roman";
            sheet.Cells["A3"].SetStyle(styleTimes);

            // Configure PDF save options to embed all used fonts
            PdfSaveOptions pdfOptions = new PdfSaveOptions
            {
                // Use Identity encoding to ensure all glyphs are embedded
                FontEncoding = PdfFontEncoding.Identity,
                // Ensure standard Windows TrueType fonts are embedded
                EmbedStandardWindowsFonts = true,
                // Set a default font in case a cell does not specify one
                DefaultFont = "Arial",
                // Check workbook default font for Unicode characters
                CheckWorkbookDefaultFont = true
            };

            // Save the workbook as PDF with the configured options
            workbook.Save("EmbeddedFontsOutput.pdf", pdfOptions);

            Console.WriteLine("PDF saved with all used fonts embedded.");
        }
    }
}
