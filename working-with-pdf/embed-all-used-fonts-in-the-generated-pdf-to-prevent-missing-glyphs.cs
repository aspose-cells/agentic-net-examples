using System;
using Aspose.Cells;
using Aspose.Cells.Rendering;

// Creates a workbook with English and Chinese text, applies Arial and SimSun fonts, and uses PdfSaveOptions (Identity encoding, EmbedStandardWindowsFonts, DefaultFont, CheckWorkbookDefaultFont) to embed every used font in the generated PDF, eliminating missing‑glyph problems.
class EmbedAllFontsPdf
{
    static void Main()
    {
        // Create a new workbook and get the first worksheet
        Workbook workbook = new Workbook();
        Worksheet worksheet = workbook.Worksheets[0];

        // Add sample data with different languages
        worksheet.Cells["A1"].PutValue("English text");
        worksheet.Cells["A2"].PutValue("中文字符"); // Chinese characters

        // Apply a Western font to the first cell
        Style style1 = worksheet.Cells["A1"].GetStyle();
        style1.Font.Name = "Arial";
        worksheet.Cells["A1"].SetStyle(style1);

        // Apply a CJK font to the second cell
        Style style2 = worksheet.Cells["A2"].GetStyle();
        style2.Font.Name = "SimSun"; // Ensure this font is available or placed in a custom font folder
        worksheet.Cells["A2"].SetStyle(style2);

        // Configure PDF save options to embed all used fonts
        PdfSaveOptions pdfOptions = new PdfSaveOptions
        {
            // Use Identity encoding to embed the full glyph set for every font
            FontEncoding = PdfFontEncoding.Identity,

            // Ensure standard Windows TrueType fonts are embedded
            EmbedStandardWindowsFonts = true,

            // Provide a fallback default font
            DefaultFont = "Arial",

            // Use the workbook's default font when a cell's font is missing
            CheckWorkbookDefaultFont = true
        };

        // Save the workbook as a PDF with the specified options
        workbook.Save("EmbeddedFonts.pdf", pdfOptions);
    }
}
