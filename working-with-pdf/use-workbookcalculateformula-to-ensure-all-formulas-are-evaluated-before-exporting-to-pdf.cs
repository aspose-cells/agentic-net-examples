using Aspose.Cells;

// The example loads an Excel workbook, runs Workbook.CalculateFormula to evaluate every formula, and then saves the workbook as a PDF using SaveFormat.Pdf.
class Program
{
    static void Main()
    {
        // Load the workbook from an existing Excel file
        Workbook workbook = new Workbook("input.xlsx");

        // Ensure all formulas in the workbook are evaluated
        workbook.CalculateFormula();

        // Export the workbook to PDF format
        workbook.Save("output.pdf", SaveFormat.Pdf);
    }
}
