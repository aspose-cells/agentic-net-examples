using System;
using System.IO;
using Aspose.Cells;

// The example creates a Workbook, writes sample data, configures PdfSaveOptions, and uses reflection to instantiate Aspose.Cells.Pdf.FileAttachment for each existing file. Each attachment is added to the PdfSaveOptions.Attachments collection before saving the workbook as a PDF, allowing external files to be embedded without a direct compile‑time dependency on Aspose.Cells.Pdf.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook (or load an existing one)
            Workbook workbook = new Workbook();

            // Add some sample data to the first worksheet
            Worksheet sheet = workbook.Worksheets[0];
            sheet.Cells["A1"].PutValue("Sample data for PDF");

            // Configure PDF save options
            PdfSaveOptions pdfOptions = new PdfSaveOptions();

            // Attempt to add attachments if the required files exist
            // Note: Attachment support requires the Aspose.Cells.Pdf assembly.
            // If the assembly is not available, this step is skipped.
            TryAddAttachment(pdfOptions, "Sample.txt", "Sample Text File");
            TryAddAttachment(pdfOptions, "Image.png", "Sample Image");

            // Save the workbook as a PDF
            workbook.Save("Result.pdf", pdfOptions);
            Console.WriteLine("PDF saved successfully.");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error: {ex.Message}");
        }
    }

    private static void TryAddAttachment(PdfSaveOptions options, string filePath, string description)
    {
        try
        {
            if (!File.Exists(filePath))
            {
                Console.WriteLine($"Warning: Attachment file '{filePath}' not found. Skipping.");
                return;
            }

            // The FileAttachment class resides in the Aspose.Cells.Pdf namespace.
            // It is available only when the Aspose.Cells.Pdf assembly is referenced.
            // Use reflection to add the attachment without a direct compile‑time dependency.
            byte[] content = File.ReadAllBytes(filePath);
            Type attachmentType = Type.GetType("Aspose.Cells.Pdf.FileAttachment, Aspose.Cells.Pdf");
            if (attachmentType == null)
            {
                Console.WriteLine("Attachment feature is not available in the current Aspose.Cells version.");
                return;
            }

            // Create an instance of FileAttachment using the constructor:
            // FileAttachment(string name, string description, byte[] content)
            object attachment = Activator.CreateInstance(attachmentType, Path.GetFileName(filePath), description, content);
            var attachmentsProp = options.GetType().GetProperty("Attachments");
            var addMethod = attachmentsProp?.PropertyType.GetMethod("Add");
            addMethod?.Invoke(attachmentsProp?.GetValue(options), new[] { attachment });
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Failed to add attachment '{filePath}': {ex.Message}");
        }
    }
}
