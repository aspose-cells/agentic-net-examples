using Aspose.Cells;
using System;
using System.IO;

// The example loads an Excel workbook, optionally adds a hyperlink, ensures the output directory exists, and saves the workbook as a PDF using Aspose.Cells. PdfSaveOptions are used (hyperlinks are preserved by default), resulting in a PDF where all Excel hyperlinks remain functional.
class Program
{
    static void Main()
    {
        try
        {
            const string inputPath = "input.xlsx";
            const string outputPath = "output.pdf";

            // Verify that the input file exists
            if (!File.Exists(inputPath))
            {
                Console.WriteLine($"Input file not found: {inputPath}");
                return;
            }

            // Load the workbook from the Excel file
            Workbook workbook = new Workbook(inputPath);

            // (Optional) Add a hyperlink to demonstrate preservation
            // workbook.Worksheets[0].Hyperlinks.Add(0, 0, "https://example.com", "Example Link");

            // Configure PDF save options (hyperlinks are preserved by default)
            PdfSaveOptions pdfOptions = new PdfSaveOptions();

            // Ensure the output directory exists
            string outputDir = Path.GetDirectoryName(outputPath);
            if (!string.IsNullOrEmpty(outputDir) && !Directory.Exists(outputDir))
            {
                Directory.CreateDirectory(outputDir);
            }

            // Save the workbook as a PDF file
            workbook.Save(outputPath, pdfOptions);
            Console.WriteLine($"Workbook successfully saved as PDF: {outputPath}");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"An error occurred: {ex.Message}");
        }
    }
}
