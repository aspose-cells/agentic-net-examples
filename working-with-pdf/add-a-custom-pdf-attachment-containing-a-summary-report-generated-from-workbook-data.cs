using System;
using System.IO;
using System.Text;
using Aspose.Cells;
using Aspose.Cells.Rendering; // For PdfSaveOptions

// This example creates an Excel workbook, populates it with product data, builds a plain‑text summary report, saves the report to a temporary file, adds the file as an OLE object on the worksheet, enables attachment embedding via PdfSaveOptions, and exports the workbook to a PDF that contains the summary as an attached document.
class AddPdfAttachmentWithSummary
{
    static void Main()
    {
        try
        {
            // 1. Create a new workbook (lifecycle: create)
            Workbook workbook = new Workbook();
            Worksheet sheet = workbook.Worksheets[0];
            sheet.Name = "Data";

            // Populate some sample data
            sheet.Cells["A1"].PutValue("Product");
            sheet.Cells["B1"].PutValue("Quantity");
            sheet.Cells["A2"].PutValue("Apples");
            sheet.Cells["B2"].PutValue(120);
            sheet.Cells["A3"].PutValue("Bananas");
            sheet.Cells["B3"].PutValue(85);
            sheet.Cells["A4"].PutValue("Cherries");
            sheet.Cells["B4"].PutValue(45);

            // 2. Save the workbook temporarily so that the summary can read it
            string tempExcelPath = Path.Combine(Path.GetTempPath(), "TempWorkbook.xlsx");
            workbook.Save(tempExcelPath);

            // 3. Generate a simple summary report (replace CellsAI with manual summary)
            StringBuilder sb = new StringBuilder();
            sb.AppendLine("Summary Report");
            sb.AppendLine("==============");
            int lastRow = sheet.Cells.MaxDataRow;
            int totalQuantity = 0;
            for (int row = 1; row <= lastRow; row++)
            {
                string product = sheet.Cells[row, 0].StringValue;
                int quantity = (int)sheet.Cells[row, 1].IntValue;
                sb.AppendLine($"{product}: {quantity}");
                totalQuantity += quantity;
            }
            sb.AppendLine($"Total Quantity: {totalQuantity}");
            string summaryText = sb.ToString();

            // 4. Write the summary to a temporary text file
            string summaryFilePath = Path.Combine(Path.GetTempPath(), "SummaryReport.txt");
            File.WriteAllText(summaryFilePath, summaryText);

            // 5. Embed the summary report as an OLE object (attachment) in the worksheet
            // Parameters: upperLeftRow, upperLeftColumn, height, width, byte[] of the file content
            int oleIndex = sheet.OleObjects.Add(6, 0, 200, 200, File.ReadAllBytes(summaryFilePath));
            // Set the file format type to unknown (plain text) and display as an icon
            sheet.OleObjects[oleIndex].FileFormatType = FileFormatType.Unknown;
            sheet.OleObjects[oleIndex].DisplayAsIcon = true;

            // 6. Prepare PDF save options with attachment embedding enabled
            PdfSaveOptions pdfOptions = new PdfSaveOptions
            {
                EmbedAttachments = true,               // Embed the OLE attachment in the PDF
                Producer = "Aspose.Cells PDF Generator"
            };

            // 7. Save the workbook as PDF (lifecycle: save)
            string outputPdfPath = "WorkbookWithSummary.pdf";
            workbook.Save(outputPdfPath, pdfOptions);

            // 8. Clean up temporary files
            if (File.Exists(tempExcelPath))
                File.Delete(tempExcelPath);
            if (File.Exists(summaryFilePath))
                File.Delete(summaryFilePath);

            Console.WriteLine($"PDF saved to '{outputPdfPath}' with embedded summary attachment.");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"An error occurred: {ex.Message}");
        }
    }
}
