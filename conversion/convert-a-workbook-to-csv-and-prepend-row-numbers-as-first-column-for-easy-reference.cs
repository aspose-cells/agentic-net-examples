using System;
using System.IO;
using Aspose.Cells;

namespace AsposeCellsExample
{
    // The example loads an Excel workbook, inserts a new column at the left edge of the first worksheet, fills it with sequential row numbers starting at 1, and then saves the result as a CSV file using Aspose.Cells, with error handling for missing files and password‑protected workbooks.
    class Program
    {
        static void Main()
        {
            const string inputPath = "input.xlsx";
            const string outputPath = "output.csv";

            try
            {
                // Verify that the input file exists
                if (!File.Exists(inputPath))
                {
                    Console.WriteLine($"Input file not found: {inputPath}");
                    return;
                }

                // Load the workbook (no password supplied)
                Workbook workbook = new Workbook(inputPath);

                // Work with the first worksheet
                Worksheet sheet = workbook.Worksheets[0];

                // Insert a new column at the very left to hold row numbers
                sheet.Cells.InsertColumn(0);

                // Determine the last row that contains data
                int lastRow = sheet.Cells.MaxDataRow;

                // Populate the new first column with sequential row numbers (starting at 1)
                for (int row = 0; row <= lastRow; row++)
                {
                    sheet.Cells[row, 0].PutValue(row + 1);
                }

                // Save the modified workbook as CSV
                workbook.Save(outputPath, SaveFormat.Csv);
                Console.WriteLine($"Workbook saved as CSV: {outputPath}");
            }
            catch (CellsException ex)
            {
                // Handle password-protected workbook or other Cells-specific errors
                if (ex.Message != null && ex.Message.IndexOf("password", StringComparison.OrdinalIgnoreCase) >= 0)
                {
                    Console.WriteLine("The workbook is password protected. Provide a password to load it.");
                }
                else
                {
                    Console.WriteLine($"CellsException: {ex.Message}");
                }
            }
            catch (Exception ex)
            {
                // General exception handling
                Console.WriteLine($"An error occurred: {ex.Message}");
            }
        }
    }
}
