using System;
using System.IO;
using System.Xml.Linq;
using Aspose.Cells;

// The example creates a Workbook, adds data, saves it to a MemoryStream in Excel 2003 XML format, loads the XML with XDocument, replaces the default root element with a custom <CustomRoot> while preserving child nodes, and writes the resulting XML to "CustomWorkbook.xml".
class ExportWorkbookAsCustomXml
{
    static void Main()
    {
        // Create a new workbook
        Workbook workbook = new Workbook();

        // Add sample data to the first worksheet
        Worksheet sheet = workbook.Worksheets[0];
        sheet.Cells["A1"].PutValue("Sample Text");
        sheet.Cells["B1"].PutValue(12345);

        // Save the workbook to a memory stream in XML (Excel 2003) format
        using (MemoryStream xmlStream = new MemoryStream())
        {
            workbook.Save(xmlStream, SaveFormat.Xml);
            xmlStream.Position = 0; // Reset stream position for reading

            // Load the XML into an XDocument for manipulation
            XDocument xmlDoc = XDocument.Load(xmlStream);

            // Replace the default root element with a custom one (e.g., <CustomRoot>)
            XElement originalRoot = xmlDoc.Root;
            XElement customRoot = new XElement("CustomRoot", originalRoot.Elements());

            // Create a new XDocument with the custom root
            XDocument customXmlDoc = new XDocument(customRoot);

            // Save the modified XML to a file
            customXmlDoc.Save("CustomWorkbook.xml");
        }

        Console.WriteLine("Workbook exported as XML with custom root element.");
    }
}
