using System;
using System.IO;
using System.Net.Http;
using System.Threading.Tasks;
using Aspose.Cells;
using Aspose.Cells.Utility;

// A complete C# example that fetches an Excel workbook from any cloud storage URL, saves it to a temporary file, converts the workbook to CSV using Aspose.Cells ConversionUtility, writes the CSV to disk, and safely removes the temporary file while handling download and conversion errors.
class Program
{
    // Entry point
    static async Task Main(string[] args)
    {
        // URL of the Excel file stored in cloud storage
        string excelUrl = "https://example.com/path/to/file.xlsx"; // TODO: replace with actual URL

        // Local temporary path for the downloaded Excel file
        string tempExcelPath = Path.Combine(Path.GetTempPath(), "temp_downloaded.xlsx");

        // Destination CSV file path
        string csvOutputPath = "converted_output.csv";

        try
        {
            // Download the Excel file from cloud storage
            await DownloadFileAsync(excelUrl, tempExcelPath);

            // Verify that the file was downloaded successfully
            if (!File.Exists(tempExcelPath))
            {
                Console.WriteLine("Downloaded file not found. Conversion aborted.");
                return;
            }

            // Convert the downloaded Excel file to CSV using Aspose.Cells ConversionUtility
            ConversionUtility.Convert(tempExcelPath, csvOutputPath);
            Console.WriteLine($"Conversion completed. CSV saved to: {csvOutputPath}");
        }
        catch (HttpRequestException httpEx)
        {
            Console.WriteLine($"Error downloading file: {httpEx.Message}");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"An error occurred: {ex.Message}");
        }
        finally
        {
            // Clean up the temporary Excel file
            if (File.Exists(tempExcelPath))
            {
                try
                {
                    File.Delete(tempExcelPath);
                }
                catch (Exception delEx)
                {
                    Console.WriteLine($"Failed to delete temporary file: {delEx.Message}");
                }
            }
        }
    }

    // Helper method to download a file from a URL to a local path
    private static async Task DownloadFileAsync(string url, string destinationPath)
    {
        using (HttpClient client = new HttpClient())
        using (HttpResponseMessage response = await client.GetAsync(url))
        {
            response.EnsureSuccessStatusCode();

            using (Stream contentStream = await response.Content.ReadAsStreamAsync())
            using (FileStream fileStream = new FileStream(destinationPath, FileMode.Create, FileAccess.Write, FileShare.None))
            {
                await contentStream.CopyToAsync(fileStream);
            }
        }
    }
}
