using Aspose.Cells;
using System;
using System.IO;
using System.Security.Cryptography;

// The program creates an Aspose.Cells workbook, saves it as JSON to a MemoryStream, derives a 256‑bit AES key and 128‑bit IV from a password using PBKDF2 with a random 16‑byte salt, then writes the salt followed by the AES‑CBC encrypted JSON to a binary file via CryptoStream.
class Program
{
    static void Main()
    {
        // 1. Create a workbook and populate it with sample data
        var workbook = new Workbook();
        var sheet = workbook.Worksheets[0];
        sheet.Cells["A1"].PutValue("Name");
        sheet.Cells["B1"].PutValue("Age");
        sheet.Cells["A2"].PutValue("Alice");
        sheet.Cells["B2"].PutValue(30);
        sheet.Cells["A3"].PutValue("Bob");
        sheet.Cells["B3"].PutValue(25);

        // 2. Save the workbook as JSON into a memory stream
        using (var jsonStream = new MemoryStream())
        {
            var jsonOptions = new JsonSaveOptions(); // default options
            workbook.Save(jsonStream, jsonOptions);
            jsonStream.Position = 0; // reset stream for reading

            // 3. Prepare encryption parameters
            string password = "MySecretPassword";          // password for protection
            string outputPath = "encryptedData.bin";       // encrypted file path

            // Generate a random salt (will be stored at the beginning of the file)
            byte[] salt = new byte[16];
            using (var rng = RandomNumberGenerator.Create())
            {
                rng.GetBytes(salt);
            }

            // Derive a 256‑bit key and a 128‑bit IV from the password and salt
            using (var kdf = new Rfc2898DeriveBytes(password, salt, 100_000, HashAlgorithmName.SHA256))
            {
                byte[] key = kdf.GetBytes(32); // AES‑256 key
                byte[] iv = kdf.GetBytes(16);  // AES block size

                // 4. Create AES encryptor
                using (var aes = Aes.Create())
                {
                    aes.Key = key;
                    aes.IV = iv;
                    aes.Mode = CipherMode.CBC;
                    aes.Padding = PaddingMode.PKCS7;

                    // 5. Write salt + encrypted JSON to disk
                    using (var fileStream = new FileStream(outputPath, FileMode.Create, FileAccess.Write))
                    {
                        // Store salt first so it can be used during decryption
                        fileStream.Write(salt, 0, salt.Length);

                        // Encrypt JSON data while writing
                        using (var cryptoStream = new CryptoStream(fileStream, aes.CreateEncryptor(), CryptoStreamMode.Write))
                        {
                            jsonStream.CopyTo(cryptoStream);
                        }
                    }
                }
            }
        }
    }
}
