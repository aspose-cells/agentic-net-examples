using System;
using Aspose.Cells;
using Aspose.Cells.Drawing;

// Creates a workbook, imports sample data into cells A1:A5, defines a style that uses the workbook's Theme Accent1 color as a solid background, applies the style to the imported range, and saves the file as an XLSX document.
class Program
{
    static void Main()
    {
        // Create a new workbook (lifecycle create)
        Workbook workbook = new Workbook();
        Worksheet worksheet = workbook.Worksheets[0];
        Cells cells = worksheet.Cells;

        // Simulate a data import routine: populate cells A1:A5
        for (int row = 0; row < 5; row++)
        {
            cells[row, 0].PutValue($"Record {row + 1}");
        }

        // Create a style that uses the theme's Accent1 color for the cell fill
        Style accentStyle = workbook.CreateStyle();
        accentStyle.Pattern = BackgroundType.Solid;                     // Solid fill
        accentStyle.ForegroundThemeColor = new ThemeColor(ThemeColorType.Accent1, 0); // Accent1, no tint

        // Apply the style to the imported cells
        for (int row = 0; row < 5; row++)
        {
            cells[row, 0].SetStyle(accentStyle);
        }

        // Save the workbook (lifecycle save)
        workbook.Save("DataImport_With_Accent1_Fill.xlsx");
    }
}
