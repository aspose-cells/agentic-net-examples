using System;
using Aspose.Cells;
using Aspose.Cells.Pivot;
using Aspose.Cells.Drawing;

namespace AsposeCellsPivotAccent2
{
    // Shows how to build a workbook, insert sample sales data, create a pivot table, define a style that uses the workbook theme's Accent2 color as a solid fill, and apply that style to all pivot‑table cells—including totals—via the FormatAll method, then save the workbook.
    class Program
    {
        static void Main()
        {
            // Create a new workbook and get the first worksheet
            Workbook workbook = new Workbook();
            Worksheet sheet = workbook.Worksheets[0];

            // Populate sample data for the pivot table
            sheet.Cells["A1"].Value = "Category";
            sheet.Cells["B1"].Value = "Region";
            sheet.Cells["C1"].Value = "Sales";

            sheet.Cells["A2"].Value = "Food";
            sheet.Cells["B2"].Value = "North";
            sheet.Cells["C2"].Value = 1200;

            sheet.Cells["A3"].Value = "Food";
            sheet.Cells["B3"].Value = "South";
            sheet.Cells["C3"].Value = 850;

            sheet.Cells["A4"].Value = "Beverage";
            sheet.Cells["B4"].Value = "North";
            sheet.Cells["C4"].Value = 950;

            sheet.Cells["A5"].Value = "Beverage";
            sheet.Cells["B5"].Value = "South";
            sheet.Cells["C5"].Value = 1100;

            // Add a pivot table based on the data range
            int pivotIndex = sheet.PivotTables.Add("A1:C5", "E3", "SalesPivot");
            PivotTable pivotTable = sheet.PivotTables[pivotIndex];

            // Configure the pivot fields
            pivotTable.AddFieldToArea(PivotFieldType.Row, "Category");
            pivotTable.AddFieldToArea(PivotFieldType.Column, "Region");
            pivotTable.AddFieldToArea(PivotFieldType.Data, "Sales");

            // Calculate the pivot data
            pivotTable.CalculateData();

            // Create a style that uses the theme's Accent2 color for the cell fill
            Style accentStyle = workbook.CreateStyle();
            accentStyle.Pattern = BackgroundType.Solid;                     // Solid fill
            accentStyle.BackgroundThemeColor = new ThemeColor(ThemeColorType.Accent2, 0); // Accent2 with no tint

            // Apply the style to all cells generated by the pivot table (including summary cells)
            pivotTable.FormatAll(accentStyle);

            // Save the workbook
            workbook.Save("PivotTable_With_Accent2_Fill.xlsx");
        }
    }
}
