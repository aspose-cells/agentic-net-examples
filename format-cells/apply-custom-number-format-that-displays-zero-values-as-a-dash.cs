using Aspose.Cells;
using System;

// The sample creates a new workbook, writes positive, negative, and zero numbers to cells A1‑A3, defines a custom number format '#,##0;-#,##0;-' that renders zeros as a dash, applies this format to the range using a StyleFlag that targets only the number format, and saves the file as CustomNumberFormat.xlsx.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook
            Workbook workbook = new Workbook();

            // Get the first worksheet
            Worksheet sheet = workbook.Worksheets[0];

            // Insert sample numeric values, including zero
            sheet.Cells["A1"].PutValue(123);   // Positive number
            sheet.Cells["A2"].PutValue(-456);  // Negative number
            sheet.Cells["A3"].PutValue(0);     // Zero value

            // Create a style with a custom number format:
            // Positive; Negative; Zero displayed as a dash
            Style customStyle = workbook.CreateStyle();
            customStyle.Custom = "#,##0;-#,##0;-";

            // Apply the style to the range A1:A3
            Aspose.Cells.Range range = sheet.Cells.CreateRange("A1:A3");
            StyleFlag flag = new StyleFlag();
            flag.NumberFormat = true; // Apply only the number format part of the style
            range.ApplyStyle(customStyle, flag);

            // Save the workbook to a file
            workbook.Save("CustomNumberFormat.xlsx");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error: {ex.Message}");
        }
    }
}
