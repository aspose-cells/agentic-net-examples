using System;
using Aspose.Cells;

// The example creates a new Workbook, writes text to cell A1, sets built‑in document properties such as Title, Author, Subject, Keywords, and Comments, and then saves the workbook as a PDF using PdfSaveOptions, which automatically embeds the defined metadata into the resulting PDF file.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook
            Workbook workbook = new Workbook();

            // Add some content to the first worksheet
            Worksheet sheet = workbook.Worksheets[0];
            sheet.Cells["A1"].PutValue("Hello Aspose.Cells!");

            // Adjust built‑in document properties using the provided properties
            var props = workbook.BuiltInDocumentProperties;
            props.Title = "Sample PDF Document";
            props.Author = "John Doe";
            props.Subject = "Demonstration of metadata embedding";
            props.Keywords = "Aspose.Cells, PDF, metadata";
            props.Comments = "Generated by Aspose.Cells example";

            // Save the workbook as PDF; built‑in properties are embedded automatically
            PdfSaveOptions pdfOptions = new PdfSaveOptions();
            workbook.Save("SampleDocument.pdf", pdfOptions);
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error: {ex.Message}");
        }
    }
}
