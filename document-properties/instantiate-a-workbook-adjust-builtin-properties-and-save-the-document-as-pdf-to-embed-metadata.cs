using System;
using System.IO;
using Aspose.Cells;

// The example creates a new Workbook, updates its built‑in document properties (Author, Title, Subject, Keywords, Comments), optionally adds sample data, ensures the output folder exists, and then saves the workbook as a PDF. The specified properties are embedded in the resulting PDF file as metadata.
class Program
{
    static void Main()
    {
        try
        {
            // Create a new workbook
            Workbook workbook = new Workbook();

            // Access built‑in document properties
            var props = workbook.BuiltInDocumentProperties;

            // Set metadata properties using the appropriate properties (read‑only indexer cannot be used)
            props.Author = "John Doe";
            props.Title = "Sample Report";
            props.Subject = "Sales Data";
            props.Keywords = "Sales,Report,2026";
            props.Comments = "Generated by Aspose.Cells";

            // Add sample data to the first worksheet (optional)
            Worksheet sheet = workbook.Worksheets[0];
            sheet.Cells["A1"].PutValue("Hello, PDF!");
            sheet.Cells["A2"].PutValue(DateTime.Now);

            // Define output file path
            string outputPath = "Output.pdf";

            // Ensure the directory for the output file exists
            string outputDir = Path.GetDirectoryName(Path.GetFullPath(outputPath));
            if (!Directory.Exists(outputDir))
            {
                Directory.CreateDirectory(outputDir);
            }

            // Save the workbook as PDF; metadata will be embedded in the PDF file
            workbook.Save(outputPath, SaveFormat.Pdf);
            Console.WriteLine($"Workbook saved successfully to '{outputPath}'.");
        }
        catch (Exception ex)
        {
            Console.WriteLine("An error occurred: " + ex.Message);
        }
    }
}
