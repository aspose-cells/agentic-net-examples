using System;
using Aspose.Cells;

// Creates a workbook, adds data to A1, C1, A2 and C2 leaving column B empty, then calls worksheet.Cells.DeleteBlankColumns() which uses the default DeleteOptions (UpdateReference = false) to remove the empty column, and saves the file as output.xlsx.
class Program
{
    static void Main()
    {
        // Create a new workbook
        Workbook workbook = new Workbook();

        // Access the first worksheet
        Worksheet worksheet = workbook.Worksheets[0];

        // Populate the worksheet with data that includes a blank column (column B)
        worksheet.Cells["A1"].PutValue("Column A");
        worksheet.Cells["C1"].PutValue("Column C"); // Column B is intentionally left blank
        worksheet.Cells["A2"].PutValue("Data A");
        worksheet.Cells["C2"].PutValue("Data C");

        // Delete all blank columns using the default DeleteOptions (UpdateReference = false)
        worksheet.Cells.DeleteBlankColumns();

        // Save the modified workbook
        workbook.Save("output.xlsx");
    }
}
