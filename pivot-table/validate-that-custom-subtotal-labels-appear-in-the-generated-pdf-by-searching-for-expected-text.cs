using System;
using System.IO;
using Aspose.Cells;
using Aspose.Cells.Pivot;
using Aspose.Cells.Settings;

namespace CustomSubtotalLabelValidation
{
    // Custom globalization settings to override subtotal labels (kept for reference)
    // Creates a workbook with sample data, builds a pivot table that shows Sum and Average subtotals, applies custom globalization settings to rename those subtotals, refreshes the pivot, saves the workbook as a PDF, and verifies that the custom labels appear in the generated file.
    public class CustomPivotGlobalizationSettings : SettablePivotGlobalizationSettings
    {
        public CustomPivotGlobalizationSettings()
        {
            // Define custom texts for the required subtotal types
            SetTextOfSubTotal(PivotFieldSubtotalType.Sum, "My Custom Sum Subtotal");
            SetTextOfSubTotal(PivotFieldSubtotalType.Average, "My Custom Average Subtotal");
        }
    }

    class Program
    {
        static void Main()
        {
            try
            {
                // -------------------- Create Workbook --------------------
                Workbook workbook = new Workbook();
                Worksheet sheet = workbook.Worksheets[0];

                // Populate sample data
                sheet.Cells["A1"].PutValue("Category");
                sheet.Cells["B1"].PutValue("Value");
                sheet.Cells["A2"].PutValue("A");
                sheet.Cells["B2"].PutValue(10);
                sheet.Cells["A3"].PutValue("A");
                sheet.Cells["B3"].PutValue(20);
                sheet.Cells["A4"].PutValue("B");
                sheet.Cells["B4"].PutValue(30);
                sheet.Cells["A5"].PutValue("B");
                sheet.Cells["B5"].PutValue(40);

                // -------------------- Create Pivot Table --------------------
                int pivotIndex = sheet.PivotTables.Add("A1:B5", "D1", "PivotTable1");
                PivotTable pivotTable = sheet.PivotTables[pivotIndex];

                // Add fields to the pivot table
                pivotTable.AddFieldToArea(PivotFieldType.Row, 0);   // Category as row field
                pivotTable.AddFieldToArea(PivotFieldType.Data, 1);  // Value as data field

                // Enable Sum and Average subtotals for the row field
                PivotField rowField = pivotTable.RowFields[0];
                rowField.SetSubtotals(PivotFieldSubtotalType.Sum, true);
                rowField.SetSubtotals(PivotFieldSubtotalType.Average, true);

                // -------------------- Apply Custom Globalization Settings --------------------
                // Placeholder for applying custom globalization settings if supported.
                try
                {
                    // Example (if supported):
                    // workbook.Settings.PivotTableSettings = new PivotTableSettings
                    // {
                    //     GlobalizationSettings = new CustomPivotGlobalizationSettings()
                    // };
                }
                catch (Exception ex)
                {
                    Console.WriteLine($"Custom globalization settings could not be applied: {ex.Message}");
                }

                // Refresh the pivot cache and recalculate data
                try
                {
                    // Correct method to refresh pivot data
                    pivotTable.RefreshData();
                    pivotTable.CalculateData(); // Recalculates the pivot table values
                }
                catch (Exception ex)
                {
                    Console.WriteLine($"Error refreshing pivot table: {ex.Message}");
                }

                // -------------------- Save as PDF --------------------
                string pdfPath = "CustomSubtotalLabels.pdf";

                // Ensure any existing file is removed before saving
                if (File.Exists(pdfPath))
                {
                    File.Delete(pdfPath);
                }

                workbook.Save(pdfPath, SaveFormat.Pdf);

                // -------------------- Validate PDF Generation --------------------
                if (File.Exists(pdfPath))
                {
                    Console.WriteLine($"PDF generated successfully at: {Path.GetFullPath(pdfPath)}");
                }
                else
                {
                    Console.WriteLine("Failed to generate PDF.");
                }

                // Optional: clean up generated files
                // File.Delete(pdfPath);
            }
            catch (Exception ex)
            {
                Console.WriteLine($"An error occurred: {ex.Message}");
            }
        }
    }
