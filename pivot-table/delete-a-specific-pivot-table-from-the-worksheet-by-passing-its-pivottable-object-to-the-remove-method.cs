using System;
using Aspose.Cells;
using Aspose.Cells.Pivot;

namespace AsposeCellsPivotRemovalDemo
{
    // Loads a workbook, accesses a worksheet, retrieves its PivotTableCollection, selects a PivotTable object, deletes it with the Remove method, and saves the updated file.
    class Program
    {
        static void Main()
        {
            // Load an existing workbook that contains pivot tables
            Workbook workbook = new Workbook("PivotTableExample.xlsx");

            // Access the first worksheet (adjust index if needed)
            Worksheet sheet = workbook.Worksheets[0];

            // Get the collection of pivot tables on this worksheet
            PivotTableCollection pivotTables = sheet.PivotTables;

            // Ensure there is at least one pivot table to remove
            if (pivotTables.Count > 0)
            {
                // Retrieve the pivot table you want to delete (e.g., the first one)
                PivotTable pivotTable = pivotTables[0];

                // Remove the pivot table by passing the PivotTable object to the Remove method
                pivotTables.Remove(pivotTable);

                Console.WriteLine("Pivot table removed successfully. Remaining count: " + pivotTables.Count);
            }
            else
            {
                Console.WriteLine("No pivot tables found in the worksheet.");
            }

            // Save the modified workbook
            workbook.Save("PivotTableRemoved.xlsx");
        }
    }
}
