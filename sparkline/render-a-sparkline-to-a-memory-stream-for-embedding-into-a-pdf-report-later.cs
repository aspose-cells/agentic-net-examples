using System;
using System.IO;
using System.Drawing;
using Aspose.Cells;
using Aspose.Cells.Charts;          // Sparkline related classes
using Aspose.Cells.Rendering;      // ImageOrPrintOptions
using Aspose.Cells.Drawing;        // ImageType enum

namespace SparklineToMemoryStreamDemo
{
    // The example creates a workbook, fills cells A1:A5, adds a line sparkline in B1, customizes its markers, sets PNG rendering options at 300 DPI, and renders the sparkline directly into a MemoryStream. The resulting PNG byte array can be used for PDF embedding or saved to disk, and the workbook is saved to verify the sparkline presence.
    class Program
    {
        static void Main(string[] args)
        {
            try
            {
                // 1. Create a new workbook and get the first worksheet
                Workbook workbook = new Workbook();
                Worksheet worksheet = workbook.Worksheets[0];

                // 2. Populate sample data for the sparkline (range A1:A5)
                worksheet.Cells["A1"].PutValue(10);
                worksheet.Cells["A2"].PutValue(20);
                worksheet.Cells["A3"].PutValue(30);
                worksheet.Cells["A4"].PutValue(25);
                worksheet.Cells["A5"].PutValue(15);

                // 3. Define the location where the sparkline will be placed (cell B1)
                CellArea location = new CellArea
                {
                    StartRow = 0,
                    EndRow = 0,
                    StartColumn = 1, // Column B
                    EndColumn = 1
                };

                // 4. Add a sparkline group: source data A1:A5, location B1
                int groupIndex = worksheet.SparklineGroups.Add(SparklineType.Line, "A1:A5", false, location);
                SparklineGroup sparklineGroup = worksheet.SparklineGroups[groupIndex];

                // Optional: customize appearance
                sparklineGroup.ShowMarkers = true;
                // Set marker color using CellsColor
                CellsColor markerColor = workbook.CreateCellsColor();
                markerColor.Color = Color.Red;
                sparklineGroup.MarkersColor = markerColor;

                // 5. Prepare image rendering options (PNG, 300 DPI)
                ImageOrPrintOptions imgOptions = new ImageOrPrintOptions
                {
                    ImageType = ImageType.Png,
                    HorizontalResolution = 300,
                    VerticalResolution = 300
                };

                // 6. Render the first sparkline to a byte array using a MemoryStream
                byte[] sparklineImageBytes;
                Sparkline sparkline = sparklineGroup.Sparklines[0];
                using (MemoryStream ms = new MemoryStream())
                {
                    // Directly write the image to the stream
                    sparkline.ToImage(ms, imgOptions);
                    sparklineImageBytes = ms.ToArray();
                }

                // 7. Demonstrate usage of the generated byte array
                using (MemoryStream sparklineStream = new MemoryStream(sparklineImageBytes))
                {
                    Console.WriteLine("Sparkline rendered successfully.");
                    Console.WriteLine($"Image size: {sparklineStream.Length} bytes.");

                    // Save the PNG image to disk (optional)
                    string imagePath = "Sparkline.png";
                    File.WriteAllBytes(imagePath, sparklineStream.ToArray());
                    Console.WriteLine($"Sparkline image saved as '{imagePath}'.");
                }

                // 8. Save the workbook to verify the sparkline exists in the sheet
                string workbookPath = "WorkbookWithSparkline.xlsx";
                workbook.Save(workbookPath, SaveFormat.Xlsx);
                Console.WriteLine($"Workbook with sparkline saved as '{workbookPath}'.");
            }
            catch (Exception ex)
            {
                Console.WriteLine($"An error occurred: {ex.Message}");
                Console.WriteLine(ex.StackTrace);
            }
        }
    }
}
